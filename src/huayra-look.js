// 3D Pagani Huayra 的表面細節（投影貼圖），做法跟 gtr-look.js 一樣。
// 位置照 Wikimedia Commons 的四張照片量的：照片上的點從相機打光線到車身（camfit.hit，huayra3d/hit.mjs），得到車身上的 (x, y, z)。
// 藍色那台：車頂、A 柱、中間那條脊（車頂一路到排氣管）是碳纖維（黑），車門下面的側裙、車尾下半部、前下巴也是碳纖維。
// 拉花「三色」：義大利國旗的綠白紅細條（側裙上緣、後葉子板前面一小塊、前下巴兩角），不畫任何字或標誌。
import { BOX, layers, poly, smooth, line, text, both, frit, canvas } from './masks.js';

export const HUAYRA_LOOK = (() => {
  const M = (pts) => pts.map(([u, y]) => [-u, y]); // 左右鏡射
  const circle = (g, x, y, r) => { g.beginPath(); g.arc(x, y, r, 0, Math.PI * 2); };

  // ---- 側面（x, y）----
  // 車門的窗：A 柱後面 → 車頂下緣 → B 柱，下緣是往後升高的腰線
  const DLO = [[0.84, 0.776], [0.70, 0.862], [0.55, 0.952], [0.42, 1.028], [0.18, 1.064], [-0.05, 1.07], [-0.22, 1.058], [-0.27, 0.99],
    [-0.285, 0.882], [0.10, 0.832], [0.50, 0.800]];
  // 後面的小三角窗（B 柱後面）
  const QTR = [[-0.335, 1.046], [-0.55, 1.038], [-0.74, 1.005], [-0.60, 0.93], [-0.34, 0.89]];
  // 碳纖維側裙（往後升高，接到後輪拱前面）
  const SKIRT = [[0.80, 0.128], [0.50, 0.15], [0.245, 0.167], [-0.147, 0.222], [-0.382, 0.269], [-0.731, 0.32], [-1.13, 0.355], [-1.13, -0.1], [0.80, -0.1]];
  const VENT = [[0.885, 0.613], [0.842, 0.617], [0.752, 0.199], [0.795, 0.191]]; // 前輪後面的直立出風口
  function side() {
    return layers(BOX.side, [
      (g) => { smooth(g, DLO); g.fill(); smooth(g, QTR); g.fill(); },
      (g) => { // 黑色：窗框、A 柱、B 柱、碳纖維車頂、側裙、車尾下半部、前下巴、出風口、耳朵進氣口裡面
        g.lineJoin = 'round'; g.lineWidth = 0.02; smooth(g, DLO); g.stroke(); smooth(g, QTR); g.stroke();
        poly(g, [[-0.215, 1.07], [-0.345, 1.06], [-0.355, 0.88], [-0.28, 0.88]]); g.fill(); // B 柱
        line(g, [[0.86, 0.77], [0.72, 0.862], [0.56, 0.958], [0.43, 1.038], [0.30, 1.07]], 0.05); // A 柱
        poly(g, [[0.45, 1.06], [0.18, 1.08], [-0.25, 1.075], [-0.75, 1.02], [-1.3, 0.93], [-2.3, 0.80], [-2.3, 1.4], [0.45, 1.4]]); g.fill(); // 車頂＋脊
        smooth(g, SKIRT); g.fill();
        poly(g, [[-1.92, 0.52], [-2.05, 0.515], [-2.4, 0.50], [-2.4, -0.1], [-1.92, -0.1]]); g.fill(); // 後輪後面的碳纖維
        poly(g, [[2.45, 0.405], [2.09, 0.40], [1.99, 0.30], [1.90, 0.20], [1.84, 0.12], [1.80, -0.1], [2.45, -0.1]]); g.fill(); // 前保桿下面
        poly(g, VENT); g.fill();
        smooth(g, [[-0.28, 0.93], [-0.30, 0.83], [-0.36, 0.80], [-0.42, 0.84], [-0.42, 0.93], [-0.36, 0.955]]); g.fill(); // 耳朵進氣口
      },
      (g) => { // 縫
        line(g, [[0.845, 0.776], [0.80, 0.64], [0.73, 0.40], [0.72, 0.20], [0.78, 0.135]], 0.005);   // 車門前緣（出風口後面）
        line(g, [[-0.365, 0.80], [-0.312, 0.581], [-0.245, 0.347], [-0.194, 0.24]], 0.005);         // 車門後緣
        line(g, [[1.98, 0.555], [2.05, 0.47], [2.10, 0.40]], 0.004);                                  // 前蓋側邊
        line(g, [[-1.75, 0.84], [-1.95, 0.70], [-2.02, 0.56]], 0.004);                               // 後蓋側邊
        line(g, [[-0.37, 0.80], [-0.50, 0.835], [-0.70, 0.86], [-0.95, 0.875]], 0.003);              // 後葉子板鼓起來的前緣
      },
      null,
    ]);
  }

  // ---- 正面（u＝|z|，畫的時候左右鏡射；y）----
  // 大燈另外做成零件（huayra-spec.js 的 HUAYRA_pods），這裡只畫黑色的燈座邊、進氣口、下巴
  const GRILLE = [[0, 0.355], [0.20, 0.36], [0.42, 0.395], [0.58, 0.43], [0.70, 0.47], [0.78, 0.47], [0.83, 0.40], [0.84, 0.28], [0.80, 0.16],
    [0.62, 0.135], [0.30, 0.125], [0, 0.122]];
  const BOTH = (P) => [...P, ...M(P).reverse()];
  function front() {
    return layers(BOX.front, [
      null,
      (g) => { // G：黑色（下面一整片大進氣口、下巴）
        smooth(g, BOTH(GRILLE)); g.fill();
        poly(g, [[-0.95, 0.125], [0.95, 0.125], [0.95, -0.1], [-0.95, -0.1]]); g.fill();
      },
      (g) => { for (const s of [1, -1]) { poly(g, [[0.955 * s, 0.53], [0.99 * s, 0.53], [0.99 * s, 0.545], [0.955 * s, 0.545]]); g.fill(); } }, // B：側邊小方向燈
      (g) => { // A：進氣口裡的網子（中間一條直的隔板留黑）
        g.save(); smooth(g, BOTH(GRILLE)); g.clip();
        g.lineWidth = 0.0016; // 斜斜的菱形網
        for (let k = -1.6; k < 1.6; k += 0.024) { g.beginPath(); g.moveTo(k, 0); g.lineTo(k + 0.5, 0.5); g.moveTo(k + 0.5, 0); g.lineTo(k, 0.5); g.stroke(); }
        g.fillStyle = '#000'; g.fillRect(-0.012, 0, 0.024, 0.5); g.fillRect(-1, 0.125, 2, 0.02);
        g.restore();
      },
    ]);
  }

  // ---- 後面（u＝z，y）：兩邊碳纖維燈座裡各三顆圓尾燈（上面兩顆、下面一顆），中間黑網、下面碳纖維 ----
  const LAMPS = [[0.815, 0.825], [0.705, 0.79], [0.83, 0.69]];
  const POD = [[0.62, 0.745], [0.66, 0.86], [0.80, 0.895], [0.92, 0.87], [0.95, 0.75], [0.92, 0.62], [0.82, 0.585], [0.70, 0.60]];
  const LOWER = [[0, 0.70], [0.30, 0.70], [0.56, 0.745], [0.64, 0.66], [0.72, 0.58], [0.84, 0.54], [0.96, 0.50], [0.98, -0.1], [0, -0.1]];
  function rear() {
    return layers(BOX.rear, [
      (g) => { for (const s of [1, -1]) for (const [u, y] of LAMPS) { circle(g, u * s, y, 0.052); g.fill(); } },
      (g) => {
        smooth(g, BOTH(LOWER)); g.fill();
        for (const s of [1, -1]) { smooth(g, POD.map(([u, y]) => [u * s, y])); g.fill(); }
        g.fillStyle = '#000'; for (const s of [1, -1]) for (const [u, y] of LAMPS) { circle(g, u * s, y, 0.052); g.fill(); }
      },
      (g) => { for (const s of [1, -1]) for (const [u, y] of LAMPS) { circle(g, u * s, y, 0.03); g.fill(); } }, // 中間銀色（倒車燈那個顏色）
      (g) => { // 縫：黑網的外框
        line(g, [[-0.58, 0.70], [-0.30, 0.68], [0.30, 0.68], [0.58, 0.70]], 0.006);
        line(g, [[-0.60, 0.47], [0.60, 0.47]], 0.005);
      },
    ]);
  }

  // ---- 上面（x, z）：前擋、碳纖維車頂＋中間的脊、脊上面的後窗、車頂後面的進氣口、前蓋、後擾流板的縫 ----
  const WS = [[1.16, 0], [1.135, 0.33], [1.03, 0.52], [0.88, 0.64], [0.66, 0.575], [0.45, 0.50], [0.31, 0.445], [0.23, 0.25], [0.21, 0]];
  const ROOF = [[0.24, 0], [0.26, 0.30], [0.33, 0.47], [0.15, 0.60], [-0.20, 0.64], [-0.55, 0.60], [-0.85, 0.52], [-1.20, 0.38], [-1.60, 0.27],
    [-1.95, 0.20], [-2.30, 0.16], [-2.30, 0]];
  const RWIN = [[-0.72, 0], [-0.73, 0.17], [-0.86, 0.27], [-1.05, 0.25], [-1.21, 0.13], [-1.23, 0]];
  function top() {
    return layers(BOX.top, [
      (g) => { // R：霧面黑（車頂後面的進氣口、脊上面引擎蓋的百葉）
        poly(g, both([[-0.34, 0], [-0.34, 0.15], [-0.52, 0.16], [-0.53, 0]])); g.fill();
        g.save(); smooth(g, both(RWIN)); g.clip();
        for (let x = -0.74; x > -1.24; x -= 0.045) g.fillRect(x - 0.022, -1, 0.022, 2);
        g.restore();
      },
      (g) => { // G：黑色（前擋黑邊、碳纖維車頂＋脊、耳朵進氣口裡面）
        frit(g, both(WS), 0.03, [0.18, 0.34], [1.10, 1.20]);
        smooth(g, both(ROOF)); g.fill();
        for (const s of [1, -1]) { smooth(g, [[-0.26, 0.85 * s], [-0.30, 0.79 * s], [-0.40, 0.78 * s], [-0.44, 0.84 * s], [-0.40, 0.90 * s], [-0.30, 0.90 * s]]); g.fill(); }
      },
      (g) => { // B：縫
        line(g, [[2.14, 0.42], [2.17, 0], [2.14, -0.42]], 0.005);                     // 前蓋前緣
        for (const s of [1, -1]) {
          line(g, [[2.14, 0.42 * s], [1.80, 0.33 * s], [1.40, 0.21 * s], [1.20, 0.16 * s]], 0.005); // 中間那塊盾牌形車蓋的兩邊
          line(g, [[1.98, 0.86 * s], [1.70, 0.92 * s], [1.30, 0.95 * s]], 0.004);  // 前葉子板上的縫
          poly(g, [[-1.72, 0.30 * s], [-1.70, 0.62 * s], [-2.08, 0.62 * s], [-2.14, 0.24 * s]]); g.stroke(); // 後面的主動式擾流板
        }
      },
      (g) => { smooth(g, both(WS)); g.fill(); },
    ]);
  }

  // ---- 拉花 ----
  const TRI = ['#0e8a3e', '#f4f4f2', '#d0202a'];
  function livery(sd, s = 'tri') {
    const { c, g } = canvas(BOX.side);
    g.clearRect(-3, -1, 6, 3);
    if (s === 'none') return c;
    // 側裙上緣的三條細線（往後升高）
    const edge = [[0.78, 0.13], [0.245, 0.167], [-0.147, 0.222], [-0.382, 0.269], [-0.731, 0.32], [-1.10, 0.352]];
    TRI.forEach((col, i) => { g.strokeStyle = col; line(g, edge.map(([x, y]) => [x, y + 0.012 + i * 0.012]), 0.011); });
    // 後葉子板前面一小塊國旗（照片 3 那台車有）
    TRI.forEach((col, i) => { g.fillStyle = col; poly(g, [[-0.74 - i * 0.06, 0.425 + i * 0.012], [-0.80 - i * 0.06, 0.437 + i * 0.012], [-0.80 - i * 0.06, 0.457 + i * 0.012], [-0.74 - i * 0.06, 0.445 + i * 0.012]]); g.fill(); });
    return c;
  }
  function frontLivery(s = 'tri') {
    const { c, g } = canvas(BOX.front);
    g.clearRect(-2, -1, 4, 3);
    if (s === 'none') return c;
    for (const k of [1, -1]) TRI.forEach((col, i) => { g.fillStyle = col; g.fillRect(k > 0 ? 0.62 + i * 0.05 : -0.67 - i * 0.05, 0.128, 0.05, 0.014); });
    return c;
  }

  return {
    side, rear, top,
    fronts: { base: front },
    livery, frontLivery,
    livDefault: 1,
    nose: () => 'base',
    U: { uXr: -1.525, uXf: 1.27, uFx: [1.85, 1.95], uRx: [-1.88, -1.96], uWell: [0.3305, 0.372, 0.95], uWellR: [0.3545, 0.397, 0.97], uGlassY: 0.72 },
  };
})();
