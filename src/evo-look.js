// 3D Lancer Evolution IX（CT9A）的表面細節（投影貼圖），做法跟 gtr-look.js 一樣。
// 位置是照 Wikimedia Commons 的幾張照片量的：照片上的點從相機打光線到車身（evo3d/hit.mjs），得到車身上的 (x, y, z)，
// 幾張照片量的不一樣時取中間。沒有任何廠牌字、徽章（水箱罩中間、行李箱上原本有徽章的地方都是平的）。
import { BOX, layers, poly, smooth, line, both, frit, canvas } from './masks.js';

export const EVO_LOOK = (() => {
  const M = (pts) => pts.map(([u, y]) => [-u, y]); // 左右鏡射
  const S = (pts, s) => pts.map(([u, y]) => [u * s, y]);
  const rrect = (g, x0, y0, x1, y1, r) => { g.beginPath(); g.roundRect(x0, y0, x1 - x0, y1 - y0, r); };
  const circle = (g, x, y, r) => { g.beginPath(); g.arc(x, y, r, 0, Math.PI * 2); };
  const mesh = (g, P, step = 0.014, w = 0.0035) => { // 網子（斜的格子）
    g.save(); smooth(g, P); g.clip();
    for (let k = -1.6; k < 1.6; k += step) { line(g, [[k, -0.2], [k + 1.2, 1.2]], w); line(g, [[k, 1.2], [k + 1.2, -0.2]], w); }
    g.restore();
  };

  // ---- 側面（x, y）----
  // 側窗：前門窗＋後門窗（後門窗後面有一條黑色分隔），窗框黑色
  const DLO = [[0.855, 0.917], [0.80, 0.955], [0.70, 1.015], [0.55, 1.10], [0.40, 1.18], [0.25, 1.255], [0.14, 1.303], [0.04, 1.33],
    [-0.15, 1.345], [-0.50, 1.35], [-0.80, 1.34], [-0.93, 1.315], [-1.03, 1.262], [-1.11, 1.175], [-1.165, 1.075], [-1.195, 0.995],
    [-1.20, 0.958], [-1.00, 0.952], [-0.50, 0.94], [0.20, 0.926], [0.70, 0.918]];
  const BPIL = [[-0.465, 1.352], [-0.35, 1.352], [-0.355, 0.935], [-0.47, 0.935]];
  const BELT = [[0.86, 0.918], [0.20, 0.925], [-0.50, 0.939], [-1.00, 0.951], [-1.205, 0.957]];
  function side() {
    return layers(BOX.side, [
      (g) => { poly(g, DLO); g.fill(); },
      (g) => { // 黑色
        poly(g, BPIL); g.fill();
        g.lineJoin = 'round'; g.lineWidth = 0.018; poly(g, DLO); g.stroke(); // 窗框
        line(g, BELT, 0.018);
        line(g, [[-0.935, 1.30], [-1.075, 0.955]], 0.016); // 後門窗的分隔條
        poly(g, [[0.80, 0.93], [0.875, 0.92], [0.86, 0.985], [0.78, 0.975]]); g.fill(); // 後照鏡底座的黑三角
        g.beginPath(); g.ellipse(0.927, 0.655, 0.026, 0.011, -0.05, 0, Math.PI * 2); g.fill(); // 側方向燈
      },
      (g) => { // 縫
        line(g, [[0.86, 0.915], [0.875, 0.84], [0.888, 0.70], [0.885, 0.52], [0.895, 0.40], [0.91, 0.345]], 0.005); // 前門前緣
        line(g, [[-0.35, 0.935], [-0.335, 0.80], [-0.31, 0.60], [-0.29, 0.42], [-0.285, 0.34]], 0.005);            // 前門後緣
        line(g, [[-1.20, 0.955], [-1.195, 0.78], [-1.14, 0.73], [-1.05, 0.69], [-0.98, 0.625], [-0.935, 0.53], [-0.915, 0.43], [-0.91, 0.34]], 0.005); // 後門後緣
        line(g, [[-0.91, 0.338], [0.0, 0.343], [0.91, 0.348]], 0.004); // 車門下緣（側裙上面）
        g.lineWidth = 0.004; rrect(g, -0.25, 0.80, -0.07, 0.848, 0.018); g.stroke(); rrect(g, -1.10, 0.825, -0.92, 0.873, 0.018); g.stroke(); // 門把
        rrect(g, -1.665, 0.775, -1.475, 0.895, 0.03); g.stroke(); // 油箱蓋
        line(g, [[1.755, 0.565], [1.70, 0.535], [1.64, 0.505]], 0.004); // 前保桿和葉子板的縫
        line(g, [[-1.935, 0.70], [-1.82, 0.655], [-1.69, 0.60]], 0.004); // 後保桿和葉子板的縫
        g.fillStyle = g.strokeStyle = 'rgb(70,70,70)';
        line(g, [[-1.0, 0.535], [0.0, 0.52], [0.90, 0.506]], 0.004); // 車門上的腰線（淡淡的）
        g.fillStyle = g.strokeStyle = 'rgb(150,150,150)';
        rrect(g, -0.24, 0.808, -0.08, 0.84, 0.014); g.fill(); rrect(g, -1.09, 0.833, -0.93, 0.865, 0.014); g.fill(); // 門把凹槽
      },
      null,
    ]);
  }

  // ---- 正面（u＝|z|，左右鏡射畫；y）----
  // 大燈：往後斜的長燈，外側包到葉子板上（uFx 從 1.70 開始，所以 u 超過車寬的部分就是包過去的那段）
  const HEAD = [[0.505, 0.592], [0.515, 0.632], [0.54, 0.672], [0.585, 0.703], [0.66, 0.715], [0.76, 0.72], [0.84, 0.712], [0.95, 0.70],
    [0.95, 0.585], [0.80, 0.583], [0.70, 0.585], [0.60, 0.588]];
  const AMBER = [[0.70, 0.586], [0.80, 0.584], [0.95, 0.586], [0.95, 0.615], [0.82, 0.611], [0.72, 0.6]]; // 大燈下面外側的橘色方向燈
  const GRILLE = [[-0.495, 0.703], [0.495, 0.703], [0.53, 0.668], [0.505, 0.618], [0.40, 0.602], [0.0, 0.596], [-0.40, 0.602], [-0.505, 0.618], [-0.53, 0.668]];
  const LOWER = [[-0.355, 0.468], [0.355, 0.468], [0.385, 0.445], [0.385, 0.345], [0.36, 0.318], [-0.36, 0.318], [-0.385, 0.345], [-0.385, 0.445]];
  const DUCT = [[0.585, 0.445], [0.75, 0.445], [0.765, 0.42], [0.76, 0.36], [0.74, 0.345], [0.60, 0.345], [0.578, 0.37]]; // 兩邊的導風口
  const SLOT = [[0.07, 0.527], [0.33, 0.522], [0.335, 0.503], [0.07, 0.508]]; // 水箱罩下面兩條細縫
  const ROUND = [0.43, 0.335, 0.048]; // 下面角落的圓形導風口
  function front() {
    return layers(BOX.front, [
      (g) => { // R：大燈（鍍鉻反射罩）
        for (const s of [1, -1]) { smooth(g, S(HEAD, s)); g.fill(); }
      },
      (g) => { // G：黑色
        smooth(g, GRILLE); g.fill(); smooth(g, LOWER); g.fill();
        for (const s of [1, -1]) {
          smooth(g, S(DUCT, s)); g.fill(); poly(g, S(SLOT, s)); g.fill();
          circle(g, ROUND[0] * s, ROUND[1], ROUND[2]); g.fill();
          g.lineWidth = 0.007; smooth(g, S(HEAD, s)); g.stroke(); // 燈的黑邊
        }
        line(g, [[-0.95, 0.575], [-0.55, 0.578], [0.55, 0.578], [0.95, 0.575]], 0.004); // 保桿上緣的縫
        line(g, [[-0.86, 0.19], [-0.6, 0.165], [0.6, 0.165], [0.86, 0.19]], 0.03); // 最下面黑色的下巴
      },
      (g) => { for (const s of [1, -1]) { smooth(g, S(AMBER, s)); g.fill(); } }, // B：橘色方向燈
      (g) => { // A：燈裡面的暗色細節（投射燈、反射碗）、開口裡的網子
        for (const s of [1, -1]) {
          g.save(); smooth(g, S(HEAD, s)); g.clip();
          g.fillStyle = 'rgb(170,170,170)'; poly(g, S([[0.48, 0.70], [0.99, 0.70], [0.99, 0.74], [0.48, 0.74]], s)); g.fill(); // 上緣的暗條
          g.fillStyle = 'rgb(110,110,110)'; circle(g, 0.60 * s, 0.645, 0.036); g.fill(); // 投射燈（內側）
          g.fillStyle = 'rgb(60,60,60)'; circle(g, 0.60 * s, 0.645, 0.022); g.fill();
          g.strokeStyle = 'rgb(150,150,150)'; g.lineWidth = 0.006;
          circle(g, 0.70 * s, 0.652, 0.04); g.stroke(); circle(g, 0.79 * s, 0.655, 0.036); g.stroke(); // 反射碗
          g.restore(); g.fillStyle = g.strokeStyle = '#fff';
        }
        mesh(g, GRILLE, 0.016); mesh(g, LOWER, 0.012, 0.004);
        for (const s of [1, -1]) mesh(g, S(DUCT, s), 0.014);
        for (const s of [1, -1]) { g.lineWidth = 0.008; circle(g, ROUND[0] * s, ROUND[1], ROUND[2] - 0.004); g.stroke(); } // 圓口的邊
      },
    ]);
  }

  // ---- 後面（u＝z，y）：尾燈（煙燻燈殼裡兩個紅色圓燈＋一個白色倒車燈）、行李箱、黑色下擴散器 ----
  const TAIL = [[0.545, 0.748], [0.57, 0.79], [0.60, 0.835], [0.63, 0.885], [0.645, 0.90], [0.70, 0.888], [0.76, 0.868], [0.815, 0.83],
    [0.86, 0.79], [0.86, 0.70], [0.78, 0.712], [0.70, 0.728], [0.60, 0.742]];
  const DIFF = [[-0.86, 0.15], [0.86, 0.15], [0.84, 0.30], [0.76, 0.37], [0.62, 0.43], [0.50, 0.452], [-0.50, 0.452], [-0.62, 0.43], [-0.76, 0.37], [-0.84, 0.30]];
  function rear() {
    return layers(BOX.rear, [
      (g) => { // R：紅色的燈（兩個圓）
        for (const s of [1, -1]) { circle(g, 0.785 * s, 0.808, 0.04); g.fill(); circle(g, 0.708 * s, 0.832, 0.04); g.fill(); }
      },
      (g) => { // G：黑色（燈殼、擴散器、車牌位置）
        for (const s of [1, -1]) { smooth(g, S(TAIL, s)); g.fill(); }
        g.fillStyle = '#000'; // 圓燈的地方挖掉（紅色、白色才看得到）
        for (const s of [1, -1]) { circle(g, 0.785 * s, 0.808, 0.04); g.fill(); circle(g, 0.708 * s, 0.832, 0.04); g.fill(); circle(g, 0.648 * s, 0.795, 0.028); g.fill(); }
        g.fillStyle = '#fff';
        smooth(g, DIFF); g.fill();
        rrect(g, -0.26, 0.457, 0.26, 0.567, 0.012); g.fill(); // 車牌（空白、黑色）
      },
      (g) => { for (const s of [1, -1]) { circle(g, 0.648 * s, 0.795, 0.028); g.fill(); } }, // B：倒車燈（白）
      (g) => { // A：縫
        line(g, [[-0.545, 0.748], [0.545, 0.748]], 0.004); // 行李箱蓋下緣
        for (const s of [1, -1]) line(g, S([[0.545, 0.748], [0.60, 0.835], [0.645, 0.90], [0.655, 0.97]], s), 0.004);
        rrect(g, -0.29, 0.44, 0.29, 0.58, 0.02); g.lineWidth = 0.005; g.stroke(); // 車牌凹槽
        for (const z of [-0.45, -0.15, 0.15]) line(g, [[z, 0.18], [z, 0.40]], 0.006); // 擴散器的導流片
      },
    ]);
  }

  // ---- 上面（x, z）：前擋、後擋、雨刷飾板、雨刷、引擎蓋大散熱口＋兩邊的小百葉、引擎蓋和行李箱的縫 ----
  const WS = [[1.045, 0], [1.04, 0.25], [1.025, 0.45], [0.985, 0.62], [0.925, 0.71], [0.75, 0.69], [0.50, 0.622], [0.30, 0.555],
    [0.205, 0.505], [0.19, 0.30], [0.19, 0]];
  const BL = [[-1.12, 0], [-1.11, 0.30], [-1.085, 0.50], [-1.11, 0.565], [-1.30, 0.615], [-1.50, 0.63], [-1.62, 0.595], [-1.675, 0.45],
    [-1.70, 0.25], [-1.705, 0]];
  const COWL = [[1.13, 0], [1.125, 0.40], [1.10, 0.62], [1.03, 0.725], [0.96, 0.71], [1.01, 0.61], [1.035, 0.42], [1.04, 0]];
  const VENT = [[1.43, 0], [1.432, 0.30], [1.445, 0.395], [1.48, 0.41], [1.56, 0.37], [1.66, 0.315], [1.685, 0.27], [1.685, 0]];
  function top() {
    return layers(BOX.top, [
      (g) => { smooth(g, both(VENT)); g.fill(); }, // R：消光黑（散熱口）
      (g) => {
        frit(g, both(WS), 0.03, [0.15, 0.24], [0.995, 1.10]);
        frit(g, both(BL), 0.03, [-1.17, -1.08], [-1.75, -1.67]);
        smooth(g, both(COWL)); g.fill();
        line(g, [[1.02, -0.62], [0.88, -0.30], [0.84, 0.0]], 0.012); line(g, [[1.035, -0.05], [0.93, 0.28], [0.92, 0.55]], 0.012); // 雨刷
        for (const s of [1, -1]) for (let i = 0; i < 4; i++) { // 兩邊的小百葉
          const x = 1.20 + i * 0.035;
          poly(g, [[x, s * (0.63 + i * 0.012)], [x + 0.016, s * (0.63 + i * 0.012)], [x + 0.03, s * (0.72 + i * 0.006)], [x + 0.014, s * (0.72 + i * 0.006)]]); g.fill();
        }
        g.beginPath(); g.ellipse(-1.04, 0, 0.05, 0.022, 0, 0, Math.PI * 2); g.fill(); // 天線底座
      },
      (g) => { // 縫：引擎蓋、行李箱、散熱口裡的百葉
        line(g, [[1.14, 0.745], [1.50, 0.75], [1.80, 0.725], [1.98, 0.66], [2.09, 0.55], [2.135, 0.30], [2.14, 0], [2.135, -0.30], [2.09, -0.55], [1.98, -0.66], [1.80, -0.725], [1.50, -0.75], [1.14, -0.745]], 0.005);
        line(g, [[1.14, 0.745], [1.14, -0.745]], 0.005);
        line(g, [[-2.15, 0.64], [-1.905, 0.535], [-1.905, -0.535], [-2.15, -0.64]], 0.005);
        for (let x = 1.455; x < 1.68; x += 0.028) line(g, [[x, -0.39], [x, 0.39]], 0.009);
      },
      (g) => { smooth(g, both(WS)); g.fill(); smooth(g, both(BL)); g.fill(); },
    ]);
  }

  // ---- 拉花：簡單的拉力賽條紋（側面一條紅色粗條＋黑色細條，後門後面往上斜；沒有字、沒有號碼）----
  function livery(sd, style = 'rally') {
    const { c, g } = canvas(BOX.side);
    g.clearRect(-3, -1, 6, 3);
    if (style === 'none') return c;
    const band = (y0, h, col, dx) => { // 從前輪拱後面到後輪拱前面，後段往上斜
      g.fillStyle = col;
      poly(g, [[0.93, y0], [0.93, y0 + h], [-0.70 + dx, y0 + h], [-1.02 + dx, y0 + h + 0.30], [-1.10 + dx, y0 + h + 0.30], [-0.78 + dx, y0]]); g.fill();
    };
    band(0.40, 0.065, '#d01c1f', 0);
    band(0.48, 0.018, '#15161a', 0.08);
    band(0.375, 0.012, '#15161a', -0.04);
    // 前葉子板上三條斜的短條
    g.fillStyle = '#d01c1f';
    for (let i = 0; i < 3; i++) { const x = 1.62 - i * 0.07; poly(g, [[x, 0.40], [x + 0.035, 0.40], [x + 0.075, 0.47], [x + 0.04, 0.47]]); g.fill(); }
    return c;
  }
  function frontLivery(style = 'rally') {
    const { c, g } = canvas(BOX.front);
    g.clearRect(-2, -1, 4, 3);
    if (style === 'none') return c;
    g.fillStyle = '#d01c1f'; // 保桿兩邊的紅色斜條
    for (const s of [1, -1]) { poly(g, S([[0.80, 0.50], [0.86, 0.50], [0.86, 0.555], [0.77, 0.555]], s)); g.fill(); }
    return c;
  }

  return {
    side, rear, top,
    fronts: { base: front },
    livery, frontLivery,
    livDefault: 0,
    nose: () => 'base',
    U: { uXr: -1.325, uXf: 1.30, uFx: [1.70, 1.72], uRx: [-1.92, -1.95], uWell: [0.3217, 0.362, 0.87], uGlassY: 0.93 },
  };
})();
