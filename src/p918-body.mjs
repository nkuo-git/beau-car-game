export const BOUNDS = [-2.40, 0.04, 2.40, 1.22, 1.02];
const mirrorZ = (r) => [...r, ...r.slice(1, -1).reverse().map(([x, z, s]) => [x, -z, s])];

// 下半身側面：最高那條線（前面是大燈鼓包和前葉子板的稜線、中間是腰線、後面是後葉子板）
