function lerpTable(t, x) {
  if (x <= t[0][0]) return t[0][1];
  for (let i = 1; i < t.length; i++) if (x <= t[i][0]) { const a = t[i - 1], b = t[i], u = (x - a[0]) / (b[0] - a[0]), s = u * u * (3 - 2 * u); return a[1] + (b[1] - a[1]) * s; }
  return t[t.length - 1][1];
}
const sstep = (a, b, x) => { const t = Math.max(0, Math.min(1, (x - a) / (b - a))); return t * t * (3 - 2 * t); };
const box2 = (x, y, hx, hy, r) => { const qx = Math.abs(x) - hx + r, qy = Math.abs(y) - hy + r; return Math.hypot(Math.max(qx, 0), Math.max(qy, 0)) + Math.min(Math.max(qx, qy), 0) - r; };
// 前車蓋凹下去多深（中間比兩邊的大燈鼓包／葉子板稜線低）
const VALLEY = [[0.45, 0.0], [0.75, 0.07], [1.1, 0.075], [1.6, 0.07], [2.0, 0.08], [2.2, 0.06], [2.32, 0.03]];
// 稜線在哪（|z|），往外是肩線往下掉
const RIDGE = [[0.4, 0.70], [1.0, 0.72], [1.6, 0.70], [2.1, 0.64], [2.3, 0.55]];

export const NOSE_X = 1.5;
export function makeSDF(opt = {}) {
  const res = 0.005;
  const side = sdf2d(curve(LOWER_SIDE), -2.45, -0.05, 2.45, 1.2, res);
  const cabS = sdf2d(curve(CABIN_SIDE), -0.7, 0.6, 1.0, 1.25, res);
  const deckS = sdf2d(curve(DECK_SIDE), -2.45, 0.6, -0.1, 1.25, res);
  const buttS = sdf2d(curve(BUTT_SIDE), -2.45, 0.6, 0.0, 1.25, res);
  const plan = sdf2d(curve(PLAN), -2.45, -1.1, 2.45, 1.1, res);
  const cabP = sdf2d(curve(CABIN_PLAN), -0.8, -1.0, 1.1, 1.0, res);
  const front = sdf2d(curve(FRONT), -1.1, -0.05, 1.1, 1.2, res);
  const R1 = 0.07, R2 = 0.06, RC = 0.08, RU = 0.04;
  const AR = [[P918.xr, P918.RR, 0.40], [P918.xf, P918.RF, 0.385]];
  return function f(x, y, z) {
    const az = Math.abs(z);
    // 前車蓋：稜線裡面凹下去，稜線外面肩線往下掉
    const rz = lerpTable(RIDGE, x);
    const val = lerpTable(VALLEY, x) * (1 - sstep(rz - 0.22, rz, az)) * sstep(0.35, 0.6, x);
    const sh = 0.10 * sstep(rz, 0.99, az) ** 2 * sstep(0.2, 0.7, x);
    const back = (0.07 + 0.07 * sstep(-0.9, -1.8, x)) * (az / 0.97) ** 3 * (1 - sstep(0.2, 0.7, x));
    const dS = look(side, x, y + val + sh + back);
    const dP = look(plan, x, az);
    const dF = look(front, az, y);
    let d = smax(dS, dP, R1);
    d = smax(d, dF, R2);
    // 車艙（前擋＋車頂＋直立的後窗）
    const zc = az / 0.75;
    const cS = look(cabS, x, y + 0.035 * zc * zc);
    const cP = look(cabP, x, az + Math.max(0, y - CABIN_Y0) * TUMBLE);
    d = smin(d, smax(cS, cP, RC), RU);
    // 引擎蓋（中間，比後葉子板高）
    if (x < 0.0) {
      const dk = smax(look(deckS, x, y + 0.03 * (az / 0.6) ** 2), az - 0.64, 0.06);
      d = smin(d, dk, 0.05);
      // 兩條飛扶壁
      const bw = 0.12 - 0.05 * sstep(-0.5, -2.1, x), bc = 0.47 - 0.06 * sstep(-0.5, -2.1, x);
      const bt = smax(look(buttS, x, y + 0.25 * Math.max(0, Math.abs(az - bc) - 0.04) ** 2), Math.abs(az - bc) - bw, 0.05);
      d = smin(d, bt, 0.03);
    }
    // 側裙
    if (x > -1.05 && x < 0.95 && y < 0.30) {
      const sk = smax(smax(az - 0.925, Math.max(y - 0.24, 0.12 - y), 0.03), Math.max(-1.0 - x, x - 0.88), 0.05);
      d = smin(d, sk, 0.02);
    }
    // 車門後面的大進氣口（後輪前面）
    if (x > -1.25 && x < -0.2 && y > 0.35 && y < 1.0) {
      const sc = rbox(x + 0.78, y - 0.66, az - 1.0, 0.13, 0.15, 0.14, 0.05);
      d = smax(d, -sc, 0.03);
    }
    // 前保桿：兩側大進氣口、中間下面的開口
    if (x > 1.7) {
      for (const [z0, z1, y0, y1, dep] of [[0.36, 0.74, 0.21, 0.40, 0.035], [-0.28, 0.28, 0.135, 0.24, 0.03]]) {
        const win = box2(az - (z0 + z1) / 2, y - (y0 + y1) / 2, (z1 - z0) / 2, (y1 - y0) / 2, 0.04);
        d = smax(d, -Math.max(win, -(d + dep)), 0.02);
      }
    }
    // 後擴散器
    if (x < -1.8 && y < 0.40) {
      const df = Math.max(az - 0.64, y - (0.17 + (-1.95 - x) * 0.55), -2.4 - x);
      d = smax(d, -df, 0.03);
    }
    // 輪拱：外緣一圈、挖洞
    for (const [xa, R, ar] of AR) {
      if (y > 0.16 && Math.abs(x - xa) < 0.7) {
        const q = Math.hypot(x - xa, y - R) - (ar + 0.01);
        d = smin(d, Math.hypot(q, az - 0.935) - 0.02, 0.03);
      }
    }
    for (const [xa, R, ar] of AR) {
      const dc = Math.hypot(x - xa, y - R) - ar;
      d = smax(d, -smax(dc, 0.62 - az, 0.03), 0.025);
    }
    return d;
  };
}
