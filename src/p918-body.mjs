// 車艙（前擋＋targa 車頂）後面接兩條飛扶壁一路到車尾，中間是低一點的引擎蓋（頂出排氣管）。
// 座標（公尺）：x 往車頭（-2.3215 車尾、+2.3215 車頭）、y 往上、z 往車的右側。
// 尺寸：長 4.643、寬 1.940、高 1.167、軸距 2.730（前懸 1.008、後懸 0.905）、輪距前 1.664／後 1.612、前 265/35R20、後 325/30R21。
// 形狀照 Nick 2026-09-27 傳的兩張 918 照片：相機從輪子、車牌反推，兩張照片同一個點（A 柱、後照鏡…）交會量出位置。
