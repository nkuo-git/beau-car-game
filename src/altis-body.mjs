// 拱形（中線高 → 兩側低多少）
const CROWN = [[-2.4, 0.03], [-1.7, 0.03], [-1.0, 0.04], [0.0, 0.05], [0.9, 0.06], [1.5, 0.075], [2.4, 0.10]];
const CABIN_CROWN = 0.06;
function lerpTable(t, x) {
  if (x <= t[0][0]) return t[0][1];
  for (let i = 1; i < t.length; i++) if (x <= t[i][0]) { const a = t[i - 1], b = t[i], u = (x - a[0]) / (b[0] - a[0]), s = u * u * (3 - 2 * u); return a[1] + (b[1] - a[1]) * s; }
  return t[t.length - 1][1];
}
const sstep = (a, b, x) => { const t = Math.max(0, Math.min(1, (x - a) / (b - a))); return t * t * (3 - 2 * t); };

export function makeSDF(opt = {}) {
  const res = 0.005;
  const side = sdf2d(curve(LOWER_SIDE), -2.45, -0.05, 2.45, 1.25, res);
  const cabS = sdf2d(curve(CABIN_SIDE), -1.95, 0.75, 1.3, 1.55, res);
  const plan = sdf2d(curve(PLAN), -2.45, -1.1, 2.45, 1.1, res);
  const cabP = sdf2d(curve(CABIN_PLAN), -1.95, -1.0, 1.3, 1.0, res);
  const front = sdf2d(curve(FRONT), -1.1, -0.05, 1.1, 1.2, res);
  const R1 = opt.R1 ?? 0.09, R2 = opt.R2 ?? 0.08, RC = opt.RC ?? 0.11, RU = opt.RU ?? 0.05;
  const arch = { R: 0.36, y: ALTIS.R + 0.01, zIn: 0.62 };
  return function f(x, y, z) {
    const az = Math.abs(z);
    const zz = az / 0.9;
    const cr = lerpTable(CROWN, x) * zz * zz;
    const dS = look(side, x, y + cr);
    // 車頭上半部（大燈那段）往後掃；車尾上半部（行李箱蓋、尾燈）兩邊往前收
    const sw = x > 1.4 ? Math.max(0, y - 0.45) * 0.9 * (az / 0.89) ** 2 : x < -1.3 ? -0.09 * sstep(0.55, 0.85, y) * sstep(0.15, 0.5, az) : 0;
    const dP = look(plan, x + sw, az);
    const dF = look(front, az, y);
    let d = smax(dS, dP, R1);
    d = smax(d, dF, R2);
    // 車艙
    const zc = az / 0.78;
    const cS = look(cabS, x, y + CABIN_CROWN * zc * zc);
    const cP = look(cabP, x, az + Math.max(0, y - CABIN_Y0) * TUMBLE);
    d = smin(d, smax(cS, cP, RC), RU);
    // 輪拱：挖洞
    for (const xa of [ALTIS.xr, ALTIS.xf]) {
      const dc = Math.hypot(x - xa, y - arch.y) - arch.R;
      d = smax(d, -smax(dc, arch.zIn - az, 0.03), 0.02);
    }
    return d;
  };
}
