// 3D AE86（3 門掀背）的表面細節（投影貼圖），做法跟 gtr-look.js 一樣。
// 位置是照片上的點從相機打光線到車身量的（ae863d/probe.mjs）：車頭照白色那台（跳燈關著），車尾照拉花那台，側窗照正側面那張。
// 沒有任何真的車標、字：車頭水箱罩、尾板、車牌都是空白的；車門上的字是自己編的店名（拉花「豆腐店」才有）。
import { BOX, layers, poly, smooth, line, text, both, frit, canvas } from './masks.js';

export const AE86_LOOK = (() => {
  const M = (pts) => pts.map(([u, y]) => [-u, y]); // 左右鏡射
  const S = (pts, s) => pts.map(([u, y]) => [u * s, y]);
  const rrect = (g, x0, y0, x1, y1, r) => { g.beginPath(); g.roundRect(x0, y0, x1 - x0, y1 - y0, r); };
  const both2 = (pts, fn) => { fn(pts); fn(M(pts)); };
  const XF = 1.3025, XR = -1.0975, AY = 0.30, AR = 0.345; // 前後輪軸、輪拱圓心高度、輪拱半徑

  // ---- 側面（x, y）----
  // 側窗：車門窗＋後面的三角窗（中間黑色 B 柱），後窗的上緣跟著 C 柱斜下來，後角是尖的
  const DLO = [[0.665, 0.928], [0.56, 0.99], [0.40, 1.09], [0.24, 1.19], [0.15, 1.245], [0.06, 1.272], [-0.20, 1.282], [-0.55, 1.282],
    [-0.80, 1.262], [-1.00, 1.205], [-1.22, 1.115], [-1.42, 1.025], [-1.56, 0.958], [-1.60, 0.938], [-1.52, 0.932], [-1.00, 0.926],
    [-0.40, 0.924], [0.30, 0.925]];
  const BPIL = [[-0.43, 1.30], [-0.545, 1.30], [-0.545, 0.90], [-0.43, 0.90]]; // B 柱（黑）
  const MIRB = [[0.665, 0.928], [0.56, 0.99], [0.52, 1.015], [0.50, 0.93]]; // 後照鏡底座那塊黑色三角
  // 輪拱外面一圈黑色小輪弧
  const flare = (g, xa) => { g.beginPath(); g.arc(xa, AY, AR + 0.052, 0, Math.PI, false); g.arc(xa, AY, AR - 0.005, Math.PI, 0, true); g.closePath(); g.fill(); };
  function side() {
    return layers(BOX.side, [
      (g) => { smooth(g, DLO); g.fill(); },
      (g) => { // 黑色
        g.lineJoin = 'round'; g.lineWidth = 0.024; smooth(g, DLO); g.stroke(); // 窗框膠條
        poly(g, BPIL); g.fill();
        poly(g, MIRB); g.fill();
        flare(g, XF); flare(g, XR);
        poly(g, [[0.93, 0.585], [-0.72, 0.585], [-0.72, 0.545], [0.93, 0.545]]); g.fill(); // 車門到前葉子板的黑色飾條
        poly(g, [[1.70, 0.585], [2.2, 0.585], [2.2, 0.0], [1.70, 0.0]]); g.fill(); // 前保桿（黑，上面那條白的另外留）
        line(g, [[1.645, 0.62], [1.70, 0.60]], 0.035);
        poly(g, [[-1.43, 0.665], [-2.2, 0.665], [-2.2, 0.615], [-1.43, 0.625]]); g.fill(); // 後輪後面、後保桿上面的黑條（尾板包過來）
        poly(g, [[-1.40, 0.43], [-2.2, 0.43], [-2.2, 0.0], [-1.40, 0.0]]); g.fill(); // 後保桿下半
        poly(g, [[0.93, 0.29], [-0.72, 0.29], [-0.72, 0.0], [0.93, 0.0]]); g.fill(); // 門檻下緣
        rrect(g, -0.395, 0.858, -0.30, 0.882, 0.008); g.fill(); // 門把
      },
      (g) => { // 縫
        line(g, [[0.66, 0.93], [0.76, 0.86], [0.80, 0.70], [0.80, 0.50], [0.79, 0.30]], 0.005); // 車門前緣
        line(g, [[-0.43, 0.925], [-0.47, 0.80], [-0.49, 0.60], [-0.49, 0.30]], 0.005); // 車門後緣
        line(g, [[-0.49, 0.295], [0.79, 0.295]], 0.004);
        line(g, [[1.68, 0.62], [1.70, 0.45], [1.69, 0.30]], 0.004); // 前保桿接葉子板
        line(g, [[1.645, 0.64], [1.85, 0.632], [2.2, 0.63]], 0.004); // 前保桿上緣
        line(g, [[-1.44, 0.615], [-1.47, 0.45], [-1.46, 0.30]], 0.004); // 後保桿接葉子板
        g.lineWidth = 0.005; rrect(g, -1.71, 0.665, -1.53, 0.815, 0.025); g.stroke(); // 油箱蓋
        line(g, [[0.95, 0.885], [1.30, 0.835], [1.70, 0.785], [1.95, 0.75]], 0.004); // 引擎蓋接葉子板
      },
      null,
    ]);
  }

  // ---- 正面（u＝|z|，畫的時候左右鏡射；y）----
  // 跳燈關著：燈蓋前緣是黑的一條，兩個燈蓋中間是一道黑色進氣縫；保桿上面一條白的（車身色），下面整片黑：方向燈、白色小燈、水箱罩、車牌
  const LID = [[0.36, 0.735], [0.70, 0.735], [0.745, 0.715], [0.745, 0.665], [0.36, 0.662]];
  const SLOT = [[0.0, 0.692], [0.37, 0.692], [0.37, 0.632], [0.0, 0.632]];
  const LOWB = [[0.0, 0.585], [0.70, 0.588], [0.80, 0.592], [0.85, 0.592], [0.85, 0.0], [0.0, 0.0]];
  const AMB = [0.33, 0.462, 0.515, 0.528], CLR = [0.525, 0.458, 0.69, 0.528], CORN = [[0.70, 0.718], [0.78, 0.705], [0.80, 0.668], [0.70, 0.665]];
  const GRL = [0.0, 0.49, 0.30, 0.572], FPLATE = [-0.165, 0.29, 0.165, 0.455];
  function front() {
    return layers(BOX.front, [
      (g) => { for (const s of [1, -1]) { rrect(g, ...(s > 0 ? CLR : [-CLR[2], CLR[1], -CLR[0], CLR[3]]), 0.01); g.fill(); } }, // R：保桿上的白色小燈
      (g) => { // G：黑
        both2(LID, (P) => { poly(g, P); g.fill(); });
        poly(g, SLOT.concat(M(SLOT).slice(1, -1).reverse())); g.fill(); poly(g, [[-0.37, 0.692], [0.37, 0.692], [0.37, 0.632], [-0.37, 0.632]]); g.fill();
        poly(g, LOWB.concat(M(LOWB).slice(1, -1).reverse())); g.fill();
      },
      (g) => { // B：橘色方向燈（保桿上、葉子板角落）
        for (const s of [1, -1]) { rrect(g, ...(s > 0 ? AMB : [-AMB[2], AMB[1], -AMB[0], AMB[3]]), 0.008); g.fill(); poly(g, S(CORN, s)); g.fill(); }
      },
      (g) => { // A：燈裡暗的部分＋水箱罩的網子（橫的格柵）
        for (const s of [1, -1]) { g.fillStyle = 'rgb(90,90,90)'; rrect(g, ...(s > 0 ? [0.53, 0.47, 0.60, 0.52] : [-0.60, 0.47, -0.53, 0.52]), 0.01); g.fill(); g.fillStyle = '#fff'; }
        g.save(); poly(g, [[-GRL[2], GRL[1]], [GRL[2], GRL[1]], [GRL[2], GRL[3]], [-GRL[2], GRL[3]]]); g.clip();
        g.fillRect(-1, 0, 2, 1);
        g.fillStyle = '#000'; for (let y = GRL[1] + 0.012; y < GRL[3]; y += 0.02) g.fillRect(-1, y, 2, 0.008); // 橫條之間的縫
        g.restore();
      },
    ]);
  }

  // ---- 後面（u＝z，y）：整片黑色尾板＋紅色尾燈（上面一條亮紅、下面燻黑紅），中間空白車牌，保桿上白下黑 ----
  const LAMP = [[0.255, 0.868], [0.62, 0.868], [0.70, 0.86], [0.745, 0.835], [0.75, 0.70], [0.72, 0.672], [0.255, 0.668]];
  const RED = [[0.255, 0.868], [0.62, 0.868], [0.70, 0.86], [0.745, 0.835], [0.745, 0.828], [0.255, 0.828]];
  const PANEL = [[0.0, 0.885], [0.70, 0.88], [0.76, 0.85], [0.775, 0.70], [0.76, 0.62], [0.0, 0.60]];
  function rear() {
    return layers(BOX.rear, [
      (g) => { both2(LAMP, (P) => { poly(g, P); g.fill(); }); }, // R：整個尾燈都是紅的（下半跟 G 疊在一起變燻黑紅）
      (g) => { // G：黑色尾板、車牌框、保桿下半
        poly(g, PANEL.concat(M(PANEL).slice(1, -1).reverse())); g.fill();
        poly(g, [[-1, 0.44], [1, 0.44], [1, 0], [-1, 0]]); g.fill();
        g.fillStyle = '#000'; both2(LAMP, (P) => { poly(g, P); g.fill(); }); // 尾燈不要黑（燻黑的下半用 A 壓暗）
        g.fillStyle = '#fff';
        for (const s of [1, -1]) line(g, [[0.255 * s, 0.87], [0.255 * s, 0.665]], 0.012); // 尾燈內側的黑邊
      },
      (g) => { for (const s of [1, -1]) { rrect(g, ...(s > 0 ? [0.27, 0.69, 0.36, 0.735] : [-0.36, 0.69, -0.27, 0.735]), 0.005); g.fill(); } }, // B：倒車燈
      (g) => { // A：縫（尾門下緣、保桿上緣、車牌框）＋尾燈下半燻黑（紅色壓暗）
        g.fillStyle = 'rgb(240,240,240)'; both2(LAMP, (P) => { poly(g, P); g.fill(); });
        g.fillStyle = '#000'; both2(RED, (P) => { poly(g, P); g.fill(); }); g.fillStyle = '#fff';
        line(g, [[-0.78, 0.885], [0.78, 0.885]], 0.004);
        line(g, [[-0.80, 0.598], [0.80, 0.598]], 0.004);
        g.lineWidth = 0.005; rrect(g, -0.17, 0.64, 0.17, 0.815, 0.01); g.stroke();
      },
    ]);
  }

  // ---- 上面（x, z）：前擋、大後擋、雨刷那條黑、引擎蓋和跳燈蓋的縫、尾門的縫 ----
  const WS = [[0.755, 0], [0.752, 0.30], [0.74, 0.50], [0.70, 0.60], [0.62, 0.635], [0.45, 0.615], [0.28, 0.57], [0.16, 0.535],
    [0.10, 0.50], [0.085, 0.30], [0.08, 0]];
  const BL = [[-0.88, 0], [-0.885, 0.30], [-0.90, 0.42], [-0.96, 0.465], [-1.20, 0.50], [-1.45, 0.53], [-1.58, 0.535], [-1.64, 0.50], [-1.65, 0.30], [-1.65, 0]];
  const COWL = [[0.80, 0], [0.798, 0.30], [0.79, 0.52], [0.765, 0.62], [0.73, 0.64], [0.725, 0.60], [0.745, 0.50], [0.755, 0.30], [0.757, 0]];
  function top() {
    return layers(BOX.top, [
      null,
      (g) => {
        frit(g, both(WS), 0.022, [0.06, 0.12], [0.72, 0.78]);
        smooth(g, both(COWL)); g.fill();
        frit(g, both(BL), 0.025, [-0.90, -0.86], [-1.67, -1.62]);
        for (const xa of [XF, XR]) for (const s of [1, -1]) { poly(g, [[xa - 0.37, 0.788 * s], [xa + 0.37, 0.788 * s], [xa + 0.37, 0.9 * s], [xa - 0.37, 0.9 * s]]); g.fill(); } // 輪弧朝上的那面也黑
      },
      (g) => {
        line(g, [[0.80, 0.70], [1.30, 0.725], [1.75, 0.725], [1.97, 0.71], [2.03, 0.60], [2.06, 0], [2.03, -0.60], [1.97, -0.71], [1.75, -0.725], [1.30, -0.725], [0.80, -0.70]], 0.005); // 引擎蓋
        for (const s of [1, -1]) { g.lineWidth = 0.005; g.beginPath(); g.moveTo(1.985, 0.36 * s); g.lineTo(1.76, 0.36 * s); g.lineTo(1.76, 0.715 * s); g.stroke(); } // 跳燈蓋（後緣、內側）
        line(g, [[-0.86, 0.64], [-1.30, 0.66], [-1.70, 0.665], [-1.97, 0.66]], 0.005); line(g, [[-0.86, -0.64], [-1.30, -0.66], [-1.70, -0.665], [-1.97, -0.66]], 0.005); // 尾門兩邊
        line(g, [[-0.86, 0.64], [-0.86, -0.64]], 0.005);
      },
      (g) => { smooth(g, both(WS)); g.fill(); smooth(g, both(BL)); g.fill(); },
    ]);
  }

  // ---- 拉花：panda＝下半部黑（黑白豆腐車）；tofu＝黑白＋車門上自己編的店名 ----
  const FONT = '"Noto Sans TC", "Noto Sans CJK TC", "PingFang TC", "Microsoft JhengHei", "WenQuanYi Zen Hei", sans-serif';
  function livery(sd, style = 'panda') {
    const { c, g } = canvas(BOX.side);
    g.clearRect(-3, -1, 6, 3);
    if (style === 'none') return c;
    g.fillStyle = '#0b0b0c'; // 下半部黑：前保桿後面到後保桿前面、白色細線下面
    poly(g, [[1.72, 0.49], [-1.45, 0.49], [-1.45, 0.0], [1.72, 0.0]]); g.fill();
    if (style === 'tofu') { // 右邊（從右邊看車頭在右手邊）字從後往前讀，「（自家用）」在前面；左邊反過來，所以小字在後面
      g.fillStyle = '#0b0b0c'; // 一整排在車門中間：大字 0.6 公尺長，小字接在車頭那邊（左邊看是車尾那邊）
      const A = sd > 0 ? 0.03 : 0.27, B = sd > 0 ? 0.49 : -0.19;
      text(g, '大便龍豆腐店', A, 0.79, 0.10, { font: FONT, weight: 900, mirror: sd < 0 });
      text(g, '（自家用）', B, 0.767, 0.056, { font: FONT, weight: 900, mirror: sd < 0 });
    }
    return c;
  }
  function frontLivery() { const { c, g } = canvas(BOX.front); g.clearRect(-2, -1, 4, 3); return c; }

  return {
    side, rear, top,
    fronts: { base: front },
    livery, frontLivery,
    livDefault: 1,
    nose: () => 'base',
    // 輪拱內側變黑的半徑比挖洞的大一點點
    U: { uXr: XR, uXf: XF, uFx: [1.86, 1.95], uRx: [-1.90, -1.98], uWell: [AY, AR + 0.04, 0.83], uGlassY: 0.90 },
  };
})();
