// 中線側面輪廓、俯視輪廓拉成柱體取交集＋修圓，頂面用「高度差」做出前葉子板的隆起，車艙（水滴形的玻璃屋）另外做再接上。
// 招牌的 C 字側線：C 裡面（車門、側窗、側面進氣口）整片比後面的葉子板凹進去一階，C 的邊緣是亮銀色飾條（chiron-spec.js）。
// 座標（公尺）：x 往車頭（-2.272 車尾、+2.272 車頭）、y 往上、z 往車的右側。
// 尺寸：長 4.544、寬 2.038、高 1.212、軸距 2.711；輪胎前 285/30 R20（半徑 0.3395）、後 355/25 R21（半徑 0.3555）。
// 形狀照四張照片（藍色右前方、淺藍右前方、黑色正後方、藍色左側），相機從輪子、水箱罩、車牌反推（chiron3d/）。
import { curve, sdf2d, look, smin, smax, rbox } from './body.mjs';

export const CHIRON = { L: 4.544, W: 2.038, H: 1.212, xf: 1.37, xr: -1.341, RF: 0.3395, RR: 0.3555 };
export const BOUNDS = [-2.36, 0.04, 2.36, 1.26, 1.06];
const mirrorZ = (r) => [...r, ...r.slice(1, -1).reverse().map(([x, z, s]) => [x, -z, s])];

// 下半身中線側面：車頭（馬蹄形水箱罩）→ 引擎蓋 → 前擋下緣 →（車艙底下）→ 引擎蓋板 → 車尾上緣 → 車尾 → 擴散器 → 底盤 → 前下巴
export const SIDE = [
  [2.245, 0.44, 1], [2.22, 0.56, 1], [2.16, 0.645, 1], [1.86, 0.70, 1], [1.50, 0.735, 1], [1.10, 0.76, 1], [0.80, 0.78, 1],
  [0.40, 0.79, 1], [-0.40, 0.84, 1], [-0.90, 0.96, 1], [-1.30, 0.985, 1], [-1.80, 0.985, 1], [-2.15, 0.975, 1],
  [-2.245, 0.95, 1], [-2.268, 0.88, 1], [-2.272, 0.60, 1], [-2.262, 0.36, 1], [-2.22, 0.29, 0],
  [-1.80, 0.14, 0], [1.75, 0.12, 0], [2.16, 0.12, 1], [2.23, 0.17, 1], [2.245, 0.30, 1],
];
// 俯視輪廓（最寬的地方）：車頭鈍圓、前葉子板寬、車門窄、後葉子板最寬
export const PLAN = mirrorZ([
  [2.245, 0, 1], [2.235, 0.18, 1], [2.20, 0.35, 1], [2.15, 0.52, 1], [2.05, 0.68, 1], [1.92, 0.82, 1], [1.75, 0.925, 1], [1.55, 0.975, 1],
  [1.25, 0.99, 1], [0.90, 0.965, 1], [0.50, 0.95, 1], [0.0, 0.955, 1], [-0.50, 0.975, 1], [-0.90, 1.005, 1], [-1.25, 1.019, 1],
  [-1.60, 1.012, 1], [-1.88, 0.985, 1], [-2.07, 0.93, 1], [-2.19, 0.84, 1], [-2.25, 0.68, 1], [-2.272, 0.40, 1], [-2.272, 0, 1],
]);
// 車艙側面（中線）：前擋 → 車頂 → 一路斜到引擎蓋板，下面伸進車身
export const CABIN_SIDE = [
  [0.88, 0.70, 0], [0.80, 0.78, 1], [0.50, 0.92, 1], [0.20, 1.06, 1], [-0.05, 1.165, 1], [-0.35, 1.212, 1], [-0.70, 1.20, 1],
  [-1.05, 1.155, 1], [-1.45, 1.085, 1], [-1.80, 1.03, 1], [-2.05, 1.00, 1], [-2.10, 0.90, 0], [0.88, 0.65, 0],
];
// 車艙俯視（腰線高度），越高越往內收
export const CABIN_PLAN = mirrorZ([
  [0.95, 0, 1], [0.93, 0.42, 1], [0.86, 0.68, 1], [0.72, 0.81, 1], [0.50, 0.86, 1], [0.10, 0.875, 1], [-0.30, 0.87, 1], [-0.70, 0.82, 1],
  [-1.10, 0.66, 1], [-1.50, 0.52, 1], [-1.85, 0.42, 1], [-2.10, 0.32, 1], [-2.14, 0, 1],
]);
export const CABIN_Y0 = 0.86, TUMBLE = 0.58;
// C 字側線（側面 x, y）：A 柱底 → 沿車頂邊往後 → 繞過側窗、進氣口往下 → 沿車門下緣往前到前輪後面
export const CLINE = [
  [0.62, 0.84], [0.40, 0.94], [0.15, 1.055], [-0.10, 1.115], [-0.45, 1.115], [-0.70, 1.06], [-0.84, 0.95], [-0.885, 0.82],
  [-0.865, 0.68], [-0.78, 0.53], [-0.64, 0.40], [-0.46, 0.305], [-0.20, 0.26], [0.15, 0.24], [0.50, 0.232], [0.80, 0.228],
  [0.98, 0.226],
];
// C 裡面的範圍（側面）：C 字線再往前包住車門前緣
const C_REGION = [...CLINE.map(([x, y]) => [x, y, 1]), [1.04, 0.30, 1], [1.04, 0.78, 1], [0.80, 0.80, 1]];

const sstep = (a, b, x) => { const t = Math.max(0, Math.min(1, (x - a) / (b - a))); return t * t * (3 - 2 * t); };
const win = (x, a, b, c, d) => sstep(a, b, x) * (1 - sstep(c, d, x));
const bump = (t) => (Math.abs(t) >= 1 ? 0 : (1 - t * t) ** 2);
// 馬蹄形水箱罩的正面輪廓（u＝|z|、y）：上面是高高的圓拱，兩邊往下微微收窄，下緣平
function CHIRON_hs(u, y) {
  if (y > 0.47) return Math.hypot(u, (y - 0.47) * 0.82) - 0.165;
  return Math.max(u - 0.165 + 0.06 * (0.47 - y), 0.20 - y);
}
const box2 = (x, y, hx, hy, r) => { const qx = Math.abs(x) - hx + r, qy = Math.abs(y) - hy + r; return Math.hypot(Math.max(qx, 0), Math.max(qy, 0)) + Math.min(Math.max(qx, qy), 0) - r; };

// 頂面加高多少：前葉子板隆起（中間引擎蓋低一點）、橫向微拱
export function lift(x, az) {
  const crown = -0.03 * (az / 1.0) ** 2;
  const ff = 0.12 * win(x, 0.35, 1.05, 1.65, 2.22) * bump((az - 0.74) / 0.40);
  const ridge = 0.012 * win(x, 0.85, 1.1, 1.9, 2.15) * Math.exp(-((az / 0.06) ** 2)); // 引擎蓋中間一道稜線
  const belt = 0.045 * win(x, -1.3, -0.8, 0.6, 1.0) * sstep(0.40, 0.80, az);
  return crown + ff + belt + ridge;
}
// 側面往內收：下面收（側裙以下）、肩線以上收
function tuck(x, y) {
  const low = 0.06 * (1 - sstep(0.13, 0.36, y));
  const yw = 0.52 + 0.08 * win(x, -2.4, -2.0, -0.9, -0.5);
  return low + 1.0 * Math.max(0, y - yw) ** 2;
}

export function makeSDF(opt = {}) {
  const res = 0.005;
  const side = sdf2d(curve(SIDE), -2.5, -0.05, 2.5, 1.3, res);
  const plan = sdf2d(curve(PLAN), -2.5, -1.2, 2.5, 1.2, res);
  const cabS = sdf2d(curve(CABIN_SIDE), -2.3, 0.6, 1.2, 1.35, res);
  const cabP = sdf2d(curve(CABIN_PLAN), -2.3, -1.0, 1.2, 1.0, res);
  const cReg = sdf2d(curve(C_REGION), -1.0, 0.1, 1.2, 1.2, res);
  const R1 = 0.09, RC = 0.11, RU = 0.05;
  const arches = [{ x: CHIRON.xf, y: CHIRON.RF, R: 0.40, zIn: 0.64 }, { x: CHIRON.xr, y: CHIRON.RR, R: 0.415, zIn: 0.62 }];
  return function f(x, y, z) {
    const az = Math.abs(z);
    const dS = look(side, x, y - lift(x, az));
    const dP = look(plan, x, az + tuck(x, y));
    let d = smax(dS, dP, R1);
    // 車艙
    const zc = az / 0.85;
    const cS = look(cabS, x, y + 0.03 * zc * zc);
    const cP = look(cabP, x, az + Math.max(0, y - CABIN_Y0) * TUMBLE);
    d = smin(d, smax(cS, cP, RC), RU);
    // C 裡面整片往內退一階（只有外側），C 的邊緣就是後葉子板的台階
    if (!opt.noInset && x > -1.0 && x < 1.2 && az > 0.45) {
      const c = look(cReg, x, y);
      d += 0.026 * sstep(0.03, -0.004, c) * sstep(0.45, 0.65, az) * (1 - sstep(0.45, 0.92, x));
    }
    // C 裡面後上角的側面進氣口（側窗後面）：C 的內緣往裡 2 公分、窗下緣以上、側窗後緣以後，往內挖
    if (x > -0.95 && x < -0.35 && y > 0.78 && az > 0.6) {
      const v = Math.max(look(cReg, x, y) + 0.022, 0.845 - y, x + 0.445);
      d = smax(d, -Math.max(v, -(d + 0.05)), 0.012);
    }
    // 車頭：馬蹄形水箱罩（往前凸出一點、上緣往後斜），裡面往內凹；兩邊大燈下面的下進氣口
    if (x > 1.95) {
      const h = CHIRON_hs(az, y), xf = 2.272 - 0.20 * Math.max(0, y - 0.32);
      d = smin(d, smax(h, x - xf, 0.02), 0.025);
      d = smax(d, -Math.max(h + 0.024, x - xf + 0.045), 0.008);
      const li = Math.max(box2(az - 0.63, y - 0.33, 0.25, 0.07, 0.035), 1.95 - x);
      d = smax(d, -Math.max(li, -(d + 0.05)), 0.01);
    }
    // 車尾：尾燈條下面整片黑色面板往內凹、下面的擴散器通道往上斜
    if (x < -2.0) {
      const t = box2(az, y - 0.42, 0.80, 0.13, 0.06);
      d = smax(d, -Math.max(t, -(d + 0.05)), 0.015);
    }
    if (x < -1.75) {
      const roof = 0.14 + 0.16 * Math.min(1, (-1.75 - x) / 0.5);
      d = smax(d, -Math.max(y - roof, az - 0.70), 0.03);
    }
    // 輪拱：挖洞（真車的輪拱邊緣是平順的，沒有外凸的唇邊）
    for (const a of arches) {
      const dc = Math.hypot(x - a.x, y - a.y) - a.R;
      d = smax(d, -smax(dc, a.zIn - az, 0.03), 0.02);
    }
    return d;
  };
}
