// 摩托車（第 59 批：Nick「你去網路上找摩托車的圖片你做一些摩托車」）的車殼 SDF：油箱、座墊＋車尾、（仿賽才有）前面的整流罩＋側邊的整流罩＋底殼。
// 兩台共用這一支：F6 仿賽（opt.fairing＝true）、N4 街車（沒有整流罩，只有油箱＋車尾；車燈、水箱是零件）。自己設計的，沒有真的牌子。
// 做法跟 z2-body.mjs 一樣：側面輪廓拉成柱體、跟寬度取交集＋修圓，再挖大燈、進氣口、尾燈的凹槽；make-car.mjs 切網格（公尺座標，不用縮放）。
// 座標（公尺）：x 往車頭、y 往上（地面 0）、z 往車的右側；軸距 1.38（前軸 +0.70、後軸 −0.68），前輪半徑 0.30（120/70-17）、後輪 0.315（180/55-17）。
// 座墊面 0.81、油箱最高 0.985、仿賽的風鏡（另外的零件）頂 1.17；把手：仿賽 0.99（分離式）、街車 1.06。
import { curve, sdf2d, look, smin, smax } from './body.mjs';

export const MOTO = { xf: 0.70, xr: -0.68, RF: 0.30, RR: 0.315, rim: 0.2159, wF: 0.12, wR: 0.18, head: [0.42, 0.90], rake: 24 * Math.PI / 180 };
const sstep = (a, b, x) => { const t = Math.max(0, Math.min(1, (x - a) / (b - a))); return t * t * (3 - 2 * t); };
const box2 = (px, py, hx, hy, r) => { const qx = Math.abs(px) - hx + r, qy = Math.abs(py) - hy + r; return Math.hypot(Math.max(qx, 0), Math.max(qy, 0)) + Math.min(Math.max(qx, qy), 0) - r; };

// 油箱（側面）：前面靠在龍頭後面，隆起來的最高點在中間偏前，後面接座墊
const TANK_SIDE = [
  [0.43, 0.76, 0], [0.445, 0.90, 1], [0.37, 0.972, 1], [0.22, 0.985, 1], [0.05, 0.92, 1], [-0.06, 0.845, 1], [-0.09, 0.78, 1], [-0.06, 0.70, 0], [0.30, 0.70, 0],
];
// 座墊＋車尾（側面）：座墊低低的、後座那塊隆起來、尾巴翹起來收尖
const TAIL_SIDE = [
  [-0.04, 0.84, 0], [-0.30, 0.805, 1], [-0.46, 0.83, 1], [-0.57, 0.905, 1], [-0.70, 0.90, 1], [-0.82, 0.865, 1], [-0.85, 0.82, 1], [-0.80, 0.785, 1], [-0.45, 0.735, 1], [-0.15, 0.69, 0], [-0.04, 0.70, 0],
];
// 整流罩（仿賽，側面，一整片）：風鏡底下 → 鼻子（大燈）→ 下巴 → 側邊往下包住引擎 → 底殼 → 後面上來接油箱；前輪那一段中間挖空（只剩兩邊的側板）
const FAIR_SIDE = [
  [0.42, 0.95, 0], [0.50, 1.00, 1], [0.62, 1.02, 1], [0.84, 0.995, 1], [0.97, 0.935, 1], [1.00, 0.86, 1], [0.975, 0.77, 1], [0.93, 0.69, 1], [0.84, 0.56, 1],
  [0.70, 0.40, 1], [0.56, 0.31, 1], [0.40, 0.29, 1], [0.10, 0.29, 1], [-0.02, 0.33, 0], [0.0, 0.42, 0], [0.14, 0.44, 1], [0.24, 0.56, 1], [0.30, 0.70, 1], [0.36, 0.80, 1], [0.40, 0.88, 0],
];

export function makeMotoSDF(opt = {}) {
  const fair = opt.fairing !== false, res = 0.004;
  const ts = sdf2d(curve(TANK_SIDE), -0.2, 0.6, 0.55, 1.05, res);
  const ls = sdf2d(curve(TAIL_SIDE), -0.95, 0.6, 0.05, 1.0, res);
  const fsd = fair ? sdf2d(curve(FAIR_SIDE), -0.1, 0.25, 1.1, 1.1, res) : null;
  return (x, y, z) => {
    const az = Math.abs(z);
    // 油箱：中間最寬 0.195（膝蓋夾的地方下半部凹進去 0.035），前後收窄
    const bump = sstep(-0.09, 0.12, x) * sstep(0.45, 0.20, x);
    const wT = 0.135 + 0.06 * bump - 0.035 * sstep(0.84, 0.74, y) * bump;
    let d = smax(look(ts, x, y), az - wT, 0.04);
    // 座墊＋車尾：座墊 0.165 寬，往尾巴收到 0.075；後座隆起那塊上面窄一點
    const wL = 0.165 - 0.09 * sstep(-0.30, -0.85, x) - 0.03 * sstep(0.85, 0.91, y);
    d = smin(d, smax(look(ls, x, y), az - wL, 0.03), 0.03);
    if (fair) {
      // 整流罩的寬：側板最寬 0.24，大燈那裡 0.21、風鏡底下更窄，下巴收窄，底殼 0.17，側板後緣（膝蓋前面）收進來
      const low = sstep(0.47, 0.40, y);
      const wF = 0.24 - 0.03 * sstep(0.74, 0.84, y) - 0.05 * sstep(0.95, 1.02, y) - 0.05 * sstep(0.82, 1.0, x) * sstep(0.80, 0.68, y) - 0.05 * sstep(0.62, 0.36, y) - 0.03 * low - 0.06 * sstep(0.42, 0.24, x) * (1 - low);
      let dF = smax(look(fsd, x, y), az - wF, 0.025);
      // 前輪那一段中間挖空（x 0.50～1.1、y 0.26～0.72、|z| < 0.15）：剩兩邊的側板，輪子、前叉在中間
      const hole = smax(box2(x - 0.83, y - 0.48, 0.28, 0.22, 0.03), az - (0.15 + 0.3 * sstep(0.70, 0.30, y)), 0.04); // 側板越下面越薄（裡面那一面是斜的）
      dF = smax(dF, -hole, 0.015);
      // 上下整流罩中間的縫（8 公釐深）、側板的斜進氣口（2 公分深）：只在兩邊（|z| > 0.12）
      const ys = 0.69 + 0.11 * (0.93 - x) / 0.57, seam = smax(Math.abs(y - ys) - 0.006, Math.max(0.12 - az, x - 0.93, 0.36 - x), 0.004);
      const vent = smax(box2((x - 0.66) * Math.cos(0.6) + (y - 0.53) * Math.sin(0.6), -(x - 0.66) * Math.sin(0.6) + (y - 0.53) * Math.cos(0.6), 0.09, 0.022, 0.012), 0.15 - az, 0.01);
      const dF0 = dF;
      dF = smax(dF, -smax(seam, -(dF0 + 0.008), 0.003), 0.003);
      dF = smax(dF, -smax(vent, -(dF0 + 0.02), 0.004), 0.004);
      d = smin(d, dF, 0.02);
      // 凹槽（照表面往下挖固定的深度）：兩顆斜的大燈（外面高）1.5 公分、中間的進氣口 2 公分
      const dl = smax(box2(az - 0.105, y - 0.86 - 0.25 * (az - 0.105), 0.07, 0.025, 0.012), 0.90 - x, 0.01);
      const dg = smax(box2(az, y - 0.78, 0.05, 0.02, 0.015), 0.92 - x, 0.01);
      const d0 = d;
      d = smax(d, -smax(dl, -(d0 + 0.015), 0.004), 0.004);
      d = smax(d, -smax(dg, -(d0 + 0.02), 0.004), 0.004);
    }
    // 尾燈：車尾最後面一條（紅色，1.2 公分深）
    const dt = smax(box2(az, y - 0.83, 0.06, 0.015, 0.01), x + 0.80, 0.01);
    d = smax(d, -smax(dt, -(d + 0.012), 0.004), 0.004);
    return d;
  };
}
