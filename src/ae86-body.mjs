// 拱形（中線高 → 兩側低多少）
const CROWN = [[-2.2, 0.03], [-1.8, 0.03], [-1.0, 0.03], [0.8, 0.02], [1.4, 0.018], [2.2, 0.018]];
const CABIN_CROWN = 0.03;
function lerpTable(t, x) {
  if (x <= t[0][0]) return t[0][1];
  for (let i = 1; i < t.length; i++) if (x <= t[i][0]) { const a = t[i - 1], b = t[i], u = (x - a[0]) / (b[0] - a[0]), s = u * u * (3 - 2 * u); return a[1] + (b[1] - a[1]) * s; }
  return t[t.length - 1][1];
}
const sstep = (a, b, x) => { const t = Math.max(0, Math.min(1, (x - a) / (b - a))); return t * t * (3 - 2 * t); };

export const NOSE_X = 1.5;
export function makeSDF(opt = {}) {
  const res = 0.005;
  const side = sdf2d(curve(LOWER_SIDE), -2.25, -0.05, 2.25, 1.2, res);
  const cabS = sdf2d(curve(CABIN_SIDE), -2.1, 0.7, 1.1, 1.45, res);
  const plan = sdf2d(curve(PLAN), -2.25, -1.0, 2.25, 1.0, res);
  const cabP = sdf2d(curve(CABIN_PLAN), -2.1, -1.0, 1.1, 1.0, res);
  const front = sdf2d(curve(FRONT), -1.0, -0.05, 1.0, 1.2, res);
  const R1 = opt.R1 ?? 0.04, R2 = opt.R2 ?? 0.035, RC = opt.RC ?? 0.05, RU = opt.RU ?? 0.03;
  const arch = { R: 0.345, y: 0.30, zIn: 0.60 };
  return function f(x, y, z) {
    const az = Math.abs(z);
    const zz = az / 0.8;
    const cr = lerpTable(CROWN, x) * zz * zz;
    const dS = look(side, x, y + cr);
    // 保桿比上面凸出：車頭跳燈、水箱罩那段（保桿上緣以上）往內收 2.5 公分，車尾尾燈那段收 2 公分
    const inset = 0.025 * sstep(1.70, 1.95, x) * sstep(0.60, 0.65, y) + 0.02 * sstep(-1.85, -2.0, x) * sstep(0.575, 0.615, y);
    const dP = look(plan, x, az) + inset;
    const dF = look(front, az, y);
    let d = smax(dS, dP, R1);
    d = smax(d, dF, R2);
    // 車艙
    const zc = az / 0.75;
    const cS = look(cabS, x, y + CABIN_CROWN * zc * zc);
    const cP = look(cabP, x, az + Math.max(0, y - CABIN_Y0) * TUMBLE * (0.6 + 0.4 * sstep(-1.7, -0.6, x))); // C 柱（後擋兩邊）比較直、比較寬
    d = smin(d, smax(cS, cP, RC), RU);
    // 黑色小輪弧（外擴 1 公分多）：輪拱外緣一圈。0.7902 是故意的：它決定車身最寬的地方，
    // 量化（make-car 的 quantize）以後中線的頂點才會稍微重疊、不會裂一條虛線（0.79 會裂）
    for (const xa of [AE86.xr, AE86.xf]) {
      if (y > 0.2 && Math.abs(x - xa) < 0.55) {
        const q = Math.hypot(x - xa, y - arch.y) - (arch.R + 0.012);
        d = smin(d, Math.hypot(q, az - 0.7902) - 0.022 + 2.5 * Math.max(0, 0.34 - y), 0.02); // 下面兩端慢慢收掉，不要掛在車底下
      }
    }
    for (const xa of [AE86.xr, AE86.xf]) {
      const dc = Math.hypot(x - xa, y - arch.y) - arch.R;
      d = smax(d, -smax(dc, arch.zIn - az, 0.03), 0.02);
    }
    return d;
  };
}
