// 3D 吉普車（J4，自己編的車，不是哪個牌子）的車身 SDF：方方正正的兩門越野車、平的引擎蓋、外面一層平的葉子板、直立的前擋、黑色硬頂
// 做法跟 ae86-body.mjs、monster-body.mjs 一樣：幾個方塊、側面輪廓拉成柱體取交集＋修圓，再挖輪拱、大燈、水箱罩的凹槽，最後 make-car.mjs 切網格。
// 葉子板外面的黑色輪弧、保桿、側踏、備胎、後照鏡、門鉸鏈都是另外的零件（jp4-spec.js）。
// 座標（公尺，原廠高度）：x 往車頭、y 往上（地面 0）、z 往車的右側；軸距 2.42（前軸 +1.22、後軸 −1.20），輪距 1.60，34 吋輪胎（半徑 0.415＋胎紋 1.5 公分）。
// 尺寸：車身長 4.10（加備胎 4.36）、車身寬 1.72（加輪弧 1.94）、車頂 1.85、車底（門檻）離地 0.52。
// 遮罩（masks.js 的 shader）只認得 y 0～1.4（車頭、車尾 0～1.3）的車身，這台比較高，所以網格存成「遮罩座標」（跟怪獸卡車一樣）：
//   xm = x·S、ym = (y − Y0)·S、zm = z·S；jp4-spec.js 再把網格放大、抬高回公尺。
import { curve, sdf2d, look, smin, smax, rbox } from './body.mjs';

export const JP4 = { S: 0.92, Y0: 0.44, xf: 1.22, xr: -1.20, R: 0.415, T: 0.80 };
const { S, Y0 } = JP4;
// 遮罩座標的範圍：[x0, y0, x1, y1, zmax]
export const BOUNDS = [-2.10 * S, (0.46 - Y0) * S, 2.04 * S, (1.90 - Y0) * S, 0.93 * S];

const sstep = (a, b, x) => { const t = Math.max(0, Math.min(1, (x - a) / (b - a))); return t * t * (3 - 2 * t); };
const box2 = (px, py, hx, hy, r) => { const qx = Math.abs(px) - hx + r, qy = Math.abs(py) - hy + r; return Math.hypot(Math.max(qx, 0), Math.max(qy, 0)) + Math.min(Math.max(qx, qy), 0) - r; };

// 葉子板的側面（x, y）：駕駛座前面（跟車身接）→ 上緣（往前低一點）→ 前緣斜斜往下 → 保桿上面 → 底下（輪拱另外挖）
const FENDER_SIDE = [
  [0.60, 0.53, 0], [0.60, 1.078, 0], [1.70, 1.05, 1], [1.93, 1.036, 1], [1.955, 1.012, 1], [1.95, 0.96, 1], [1.88, 0.735, 1], [1.84, 0.70, 0],
  [1.30, 0.70, 0], [0.60, 0.53, 0],
];
// 硬頂車艙的側面：前擋下緣 → 前擋（57 度）→ 車頂 → 車尾（直的，上面修圓）→ 往下伸進車身
const CAB_SIDE = [
  [0.74, 1.15, 0], [0.735, 1.225, 1], [0.70, 1.245, 1], [0.665, 1.255, 1], [0.335, 1.775, 1], [0.30, 1.815, 1], [0.24, 1.845, 1], [-0.60, 1.852, 1],
  [-1.88, 1.85, 1], [-1.975, 1.83, 1], [-2.012, 1.78, 1], [-2.022, 1.65, 1], [-2.025, 1.15, 0],
];

export function makeSDF() {
  const res = 0.004;
  const fend = sdf2d(curve(FENDER_SIDE), 0.4, 0.3, 2.2, 1.3, res);
  const cab = sdf2d(curve(CAB_SIDE), -2.3, 1.0, 1.0, 2.0, res);
  const { xf, xr } = JP4, AY = 0.42; // 輪拱圓心（輪子中心 0.415）
  // 公尺座標的 SDF
  function F(x, y, z) {
    const az = Math.abs(z);
    // 車身（後面的「浴缸」）：x −2.035…0.70、y 0.52…1.21，側面是直的
    let d = rbox(x + 0.6675, y - 0.865, az, 1.3675, 0.345, 0.86, 0.045);
    // 引擎蓋＋水箱罩那一塊：引擎蓋往前低一點、中間拱一點點；水箱罩上面往後倒一點
    const hoodY = 1.218 - 0.034 * sstep(0.7, 1.95, x) + 0.006 * (1 - Math.min(1, (az / 0.665) ** 2));
    const gx = 1.987 - 0.03 * sstep(0.62, 1.17, y); // 水箱罩的面
    d = smin(d, smax(smax(smax(x - gx, y - hoodY, 0.03), smax(az - 0.668, 0.62 - y, 0.02), 0.02), 0.60 - x, 0.01), 0.012);
    // 葉子板：一片平的「架子」從引擎蓋旁邊伸出去（z 0.60…0.905），前面斜斜往下
    const fs = look(fend, x, y);
    d = smin(d, smax(fs, smax(az - 0.905, 0.58 - az, 0.02), 0.03), 0.015);
    // 車艙（硬頂）：側面輪廓 ∩ 俯視（越高越往內收），前擋那段比較窄
    const zc = 0.845 - 0.075 * sstep(1.2, 1.85, y) - 0.045 * sstep(0.45, 0.70, x);
    d = smin(d, smax(look(cab, x, y), az - zc, 0.045), 0.02);
    // 輪拱：前後都挖到 z 0.585（裡面一道牆）；後輪拱比較方一點（圓＋往上的方塊）
    for (const [xa, R] of [[xf, 0.50], [xr, 0.49]]) {
      const dc = Math.hypot(x - xa, y - AY) - R;
      d = smax(d, -smax(dc, 0.585 - az, 0.03), 0.015);
    }
    // 大燈的圓凹槽（3 公分深）、水箱罩橫條那一塊凹進去 2 公分
    const dl = Math.hypot(az - 0.505, y - 0.985) - 0.118;
    d = smax(d, -smax(dl, (gx - 0.03) - x, 0.006), 0.006);
    const dg = box2(az, y - 0.935, 0.345, 0.185, 0.03);
    d = smax(d, -smax(dg, (gx - 0.022) - x, 0.005), 0.005);
    return d;
  }
  // 遮罩座標 → 公尺座標
  return (xm, ym, zm) => F(xm / S, ym / S + Y0, zm / S) * S;
}
