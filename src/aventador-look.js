// 3D Lamborghini Aventador S 的表面細節（投影貼圖），做法跟 gtr-look.js 一樣。
// 位置是照三張照片量的：照片上的點從相機打光線到車身（camfit.hit，aventador3d/hit.mjs），得到車身上的 (x, y, z)。
// 沒有任何廠牌字、牛的徽章：車頭徽章、車尾的字、車牌都留空白。
import { BOX, layers, poly, smooth, line, both, frit, canvas } from './masks.js';

export const AVENTADOR_LOOK = (() => {
  const M = (pts) => pts.map(([u, y]) => [-u, y]); // 左右鏡射
  const both2 = (pts, fn) => { for (const P of [pts, M(pts)]) fn(P); };
  let style = 'stripe'; // 最後畫的拉花（給零件的顏色用）

  // ---- 側面（x, y）----
  // 車門的側窗：前緣沿著 A 柱、上緣沿著車頂邊、後緣斜斜往前下（Aventador 的窗是一個長的斜梯形）
  const DLO = [[0.84, 0.862], [0.62, 0.93], [0.38, 1.012], [0.12, 1.068], [-0.18, 1.084], [-0.42, 1.068], [-0.54, 1.045], [-0.30, 0.885], [0.20, 0.87], [0.55, 0.862]];
  // 門窗後面的小三角窗（黑）
  const QTR = [[-0.56, 1.04], [-0.86, 0.985], [-0.40, 0.885], [-0.33, 0.885]];
  // 車門後面的大進氣口（跟 aventador-body.mjs 的 INTAKE 一樣，邊緣多 1.5 公分）
  const INTAKE = [[-0.79, 0.855], [-0.93, 0.855], [-1.075, 0.62], [-1.055, 0.275], [-0.385, 0.275]];
  function side() {
    return layers(BOX.side, [
      (g) => { smooth(g, DLO); g.fill(); },
      (g) => { // 黑色：窗框、小三角窗、進氣口、肩膀上的進氣口、門檻、前後保桿的下角
        g.lineJoin = 'round'; g.lineWidth = 0.018; smooth(g, DLO); g.stroke();
        poly(g, QTR); g.fill();
        poly(g, INTAKE); g.fill();
        poly(g, [[-0.60, 0.985], [-0.86, 1.06], [-1.46, 1.02], [-1.42, 0.975], [-1.16, 0.905]]); g.fill(); // 肩膀上的進氣口（側面看得到的那一邊）
        poly(g, [[0.80, 0.10], [-1.18, 0.10], [-1.16, 0.205], [0.76, 0.225]]); g.fill(); // 黑色門檻（側裙）
        poly(g, [[1.86, 0.10], [2.45, 0.10], [2.45, 0.30], [2.20, 0.40], [2.00, 0.33], [1.90, 0.20]]); g.fill(); // 前保桿側面的進氣口
        poly(g, [[-1.98, 0.10], [-2.45, 0.10], [-2.45, 0.52], [-2.26, 0.46], [-2.10, 0.30]]); g.fill(); // 後保桿下角（擴散器）
        poly(g, [[-2.10, 0.50], [-2.16, 0.36], [-2.45, 0.34], [-2.45, 0.78], [-2.24, 0.76]]); g.fill(); // 尾燈旁邊到下角的黑網子
      },
      (g) => { // 縫：車門（前緣、下緣、後緣沿著進氣口）、油箱蓋
        line(g, [[0.82, 0.862], [0.76, 0.62], [0.72, 0.30], [0.66, 0.235]], 0.005);
        line(g, [[0.66, 0.235], [-0.33, 0.235]], 0.004);
        line(g, [[-0.33, 0.235], [-0.36, 0.29], [-0.76, 0.85]], 0.005);
        line(g, [[1.88, 0.46], [2.20, 0.42], [2.36, 0.40]], 0.004); // 前保桿上緣
      },
      null,
    ]);
  }

  // ---- 正面（u＝|z|，畫的時候左右鏡射；y）----
  // 大燈：長長的斜六角形，外端高、往內往下尖（Y 字日行燈畫在裡面）
  const HEAD = [[0.875, 0.685], [0.79, 0.69], [0.63, 0.645], [0.545, 0.605], [0.57, 0.583], [0.68, 0.598], [0.83, 0.632]];
  // 車頭兩角的大進氣口（中間一片車身色的斜刀）
  const CORNER = [[0.44, 0.19], [0.87, 0.19], [0.915, 0.30], [0.77, 0.475], [0.63, 0.485], [0.455, 0.44]];
  const BLADE = [[0.45, 0.405], [0.50, 0.435], [0.87, 0.245], [0.82, 0.21]];
  const BLADE2 = [[0.64, 0.355], [0.69, 0.335], [0.90, 0.385], [0.89, 0.42]]; // Y 字的另一撇（往外上角）
  // 中間下面的開口
  const MOUTH = [[0, 0.43], [0.30, 0.43], [0.44, 0.44], [0.44, 0.19], [0, 0.17]];
  function front() {
    const S2 = (P, s) => P.map(([u, y]) => [u * s, y]);
    const drl = (g, s) => { // 大燈裡的鍍鉻 Y 字日行燈＋上緣燈條
      line(g, S2([[0.865, 0.678], [0.72, 0.655], [0.58, 0.603]], s), 0.011);
      line(g, S2([[0.72, 0.655], [0.69, 0.612]], s), 0.009);
      line(g, S2([[0.72, 0.655], [0.80, 0.630]], s), 0.009);
      for (const [u, y] of [[0.64, 0.612], [0.765, 0.640]]) { g.beginPath(); g.arc(u * s, y, 0.010, 0, Math.PI * 2); g.fill(); } // 小投射鏡
    };
    return layers(BOX.front, [
      (g) => { for (const s of [1, -1]) drl(g, s); }, // R：只有燈條亮（鍍鉻／白）
      (g) => { // G：黑色（大燈裡面、進氣口、下巴）；車身色的斜刀留下來
        for (const s of [1, -1]) {
          smooth(g, S2(HEAD, s)); g.fill();
          g.lineWidth = 0.010; smooth(g, S2(HEAD, s)); g.stroke();
          g.save(); poly(g, S2(CORNER, s)); g.fill();
          g.globalCompositeOperation = 'destination-out'; poly(g, S2(BLADE, s)); g.fill(); poly(g, S2(BLADE2, s)); g.fill(); g.restore();
        }
        smooth(g, [...MOUTH, ...M(MOUTH).reverse()]); g.fill();
        g.fillRect(-1, 0, 2, 0.14);
      },
      null,
      (g) => { // A：中間開口裡幾條細細的橫條（暗灰），兩角的進氣口整片黑
        g.save(); smooth(g, [...MOUTH, ...M(MOUTH).reverse()]); g.clip();
        for (let y = 0.21; y < 0.43; y += 0.055) line(g, [[-0.45, y], [0.45, y]], 0.0035);
        g.restore();
      },
    ]);
  }

  // ---- 後面（u＝z，y）：Y 字尾燈（三個橫躺的 Y）、尾燈下面一整片黑網子、中間黑色車牌板、擴散器 ----
  const TAIL = [[0.30, 0.852], [0.36, 0.888], [0.80, 0.892], [0.875, 0.85], [0.84, 0.80], [0.36, 0.792]];
  function rear() {
    const Ys = (g, s) => { // 三個橫躺的 Y：一支橫的＋兩撇往外張開
      for (const z0 of [0.43, 0.60, 0.77]) {
        line(g, [[(z0 - 0.075) * s, 0.872], [z0 * s, 0.842], [(z0 - 0.075) * s, 0.812]], 0.016);
        line(g, [[z0 * s, 0.842], [(z0 + 0.085) * s, 0.842]], 0.016);
      }
    };
    return layers(BOX.rear, [
      (g) => { // R：紅燈（Y 字燈條、上面中間的第三煞車燈）
        for (const s of [1, -1]) Ys(g, s);
        line(g, [[-0.26, 0.893], [0.26, 0.893]], 0.008);
      },
      (g) => { // G：黑（燈殼、網子、車牌板、擴散器）
        for (const s of [1, -1]) {
          const S = (p) => p.map(([u, y]) => [u * s, y]);
          smooth(g, S(TAIL)); g.fill();
          poly(g, S([[0.36, 0.765], [0.89, 0.765], [0.91, 0.33], [0.52, 0.32], [0.42, 0.44], [0.36, 0.60]])); g.fill(); // 尾燈下面到下角一整片黑網子
        }
        g.beginPath(); g.roundRect(-0.33, 0.56, 0.66, 0.24, 0.02); g.fill(); // 中間黑色車牌板（車牌空白）
        g.strokeStyle = '#000'; for (const s of [1, -1]) Ys(g, s); g.strokeStyle = '#fff'; // Y 字燈條不要黑（紅色才看得到）
        poly(g, [[-0.92, 0.10], [0.92, 0.10], [0.92, 0.33], [0.50, 0.32], [0.30, 0.42], [-0.30, 0.42], [-0.50, 0.32], [-0.92, 0.33]]); g.fill(); // 擴散器
      },
      (g) => { for (const s of [1, -1]) { poly(g, [[0.31 * s, 0.835], [0.355 * s, 0.86], [0.355 * s, 0.82]]); g.fill(); } }, // B：倒車燈（燈殼內側一小塊）
      (g) => { // A：縫（後蓋、保桿）
        line(g, [[-0.88, 0.555], [0.88, 0.555]], 0.004);
        line(g, [[-0.30, 0.905], [0.30, 0.905]], 0.003);
      },
    ]);
  }

  // ---- 上面（x, z）：前擋、引擎蓋板的百葉、肩膀上的進氣口、前蓋的縫、雨刷飾板 ----
  const WS = [[0.935, 0], [0.93, 0.40], [0.905, 0.60], [0.85, 0.69], [0.60, 0.635], [0.38, 0.56], [0.27, 0.46], [0.24, 0]];
  const SCOOP = [[-0.60, 0.80], [-0.86, 0.71], [-1.46, 0.79], [-1.40, 0.88], [-1.15, 0.925]];
  function top() {
    return layers(BOX.top, [
      (g) => { // R：霧黑（引擎蓋板百葉之間、後面的兩條小出風口）
        for (const x0 of [-0.98, -1.18, -1.38]) poly(g, both([[x0, 0], [x0, 0.42], [x0 - 0.06, 0.44], [x0 - 0.06, 0]])), g.fill();
        for (const s of [1, -1]) { g.beginPath(); g.roundRect(-1.80, 0.10 * s - 0.03, 0.16, 0.06, 0.02); g.fill(); }
      },
      (g) => { // G：黑（前擋黑邊、雨刷飾板、肩膀上的進氣口、引擎蓋板四周的黑框）
        frit(g, both(WS), 0.03, [0.20, 0.30], [0.90, 0.97]);
        smooth(g, both([[0.985, 0], [0.98, 0.40], [0.955, 0.58], [0.93, 0.58], [0.95, 0.40], [0.955, 0]])); g.fill();
        for (const s of [1, -1]) { smooth(g, SCOOP.map(([x, z]) => [x, z * s])); g.fill(); }
        g.lineWidth = 0.03; g.lineJoin = 'round';
        poly(g, both([[-0.84, 0], [-0.86, 0.46], [-1.56, 0.47], [-1.58, 0]])); g.stroke();
      },
      (g) => { // B：縫（前蓋 V 字前緣＋兩側、後面的尾翼）
        line(g, [[1.05, 0.62], [1.45, 0.72], [1.80, 0.80], [1.98, 0.68], [2.07, 0.48], [2.11, 0.28], [2.145, 0], [2.11, -0.28], [2.07, -0.48], [1.98, -0.68], [1.80, -0.80], [1.45, -0.72], [1.05, -0.62]], 0.005);
        line(g, [[-2.04, 0.64], [-2.36, 0.62], [-2.36, -0.62], [-2.04, -0.64], [-2.04, 0.64]], 0.004);
      },
      (g) => { smooth(g, both(WS)); g.fill(); },
    ]);
  }

  // ---- 拉花 ----
  // stripe：兩條細細的黃線（照片 1 那台的下巴、門檻是黃邊）；ys：Y 字賽車條紋（車頭到車尾兩條中間條紋＋側面 Y）
  const COL = { stripe: '#f2b705', ys: '#f4f5f6' };
  const pick = (s) => { if (s && s !== 'none' && COL[s]) style = s; return COL[style] || COL.stripe; };
  function livery(sd, s = 'stripe') {
    const { c, g } = canvas(BOX.side);
    g.clearRect(-3, -1, 6, 3);
    if (s === 'none' || !COL[s] && s !== 'ff') return c;
    g.fillStyle = g.strokeStyle = pick(s === 'ff' ? 'stripe' : s);
    if (style === 'stripe') {
      poly(g, [[0.78, 0.222], [-1.16, 0.202], [-1.16, 0.214], [0.78, 0.236]]); g.fill(); // 門檻上緣一條黃線
    } else {
      // 側面：從前輪拱上面斜斜往後的 Y 字（兩條細條紋在進氣口前面分叉）
      line(g, [[1.65, 0.70], [0.80, 0.80], [0.10, 0.78], [-0.30, 0.66]], 0.03);
      line(g, [[0.10, 0.78], [-0.36, 0.86]], 0.03);
      line(g, [[0.10, 0.78], [-0.30, 0.50]], 0.03);
    }
    return c;
  }
  function frontLivery(s = 'stripe') {
    const { c, g } = canvas(BOX.front);
    g.clearRect(-2, -1, 4, 3);
    if (s === 'none') return c;
    const col = pick(s === 'ff' ? 'stripe' : s);
    g.fillStyle = g.strokeStyle = col;
    if (style === 'stripe') line(g, [[-0.86, 0.145], [0.86, 0.145]], 0.008); // 下巴上緣的黃線
    return c;
  }

  return {
    side, rear, top,
    fronts: { base: front },
    livery, frontLivery,
    livDefault: 1,
    nose: () => 'base',
    accent: () => COL[style] || COL.stripe,
    U: { uXr: -1.55, uXf: 1.15, uFx: [1.62, 1.72], uRx: [-2.05, -2.15], uWell: [0.3305, 0.47, 1.0], uWellR: [0.3555, 0.49, 1.0], uGlassY: 0.86 },
  };
})();
