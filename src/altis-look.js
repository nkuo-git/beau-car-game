// 3D Corolla Altis（E210，台灣小黃）的表面細節（投影貼圖），做法跟 gtr-look.js、yaris-look.js 一樣。
// 位置都是照片上的點從擬合好的相機打光線到車身（altis3d/probe.mjs）、或左右對稱的兩點三角定位（altis3d/tri.mjs）量出來的。
// 沒有車標：車頭、行李箱中間原本是 Toyota 標誌的地方留空；車牌是一塊黑色的空白板子（沒有字）。
// 拉花 'taxi'（小黃）：前後保桿下半部、側裙是深灰色（照片那台小黃就是這樣），車門上自己編的車隊名字和號碼、黑白格子條。
import { BOX, layers, poly, smooth, line, text, both, frit, canvas } from './masks.js';

export const ALTIS_LOOK = (() => {
  const M = (pts) => pts.map(([u, y]) => [-u, y]); // 左右鏡射
  const S = (pts, s) => pts.map(([u, y]) => [u * s, y]);
  const rrect = (g, x0, y0, x1, y1, r) => { g.beginPath(); g.roundRect(x0, y0, x1 - x0, y1 - y0, r); };
  const circle = (g, x, y, r) => { g.beginPath(); g.arc(x, y, r, 0, Math.PI * 2); };
  const both2 = (pts, fn) => { fn(pts); fn(M(pts)); };

  // ---- 側面（x, y）----
  // 側窗：前門窗＋後門窗（後門窗後面一小塊固定的三角窗），上緣沿著車頂邊、往後掉到 C 柱
  const DLO = [[0.93, 0.905], [0.70, 0.888], [0.50, 0.886], [0.00, 0.91], [-0.40, 0.935], [-1.00, 0.968], [-1.30, 0.99], [-1.37, 1.008],
    [-1.33, 1.05], [-1.24, 1.11], [-1.10, 1.188], [-0.90, 1.258], [-0.65, 1.284], [-0.34, 1.288], [0.03, 1.27], [0.31, 1.245],
    [0.56, 1.135], [0.80, 0.995]];
  const BPILLAR = [[-0.135, 1.30], [-0.275, 1.30], [-0.262, 0.88], [-0.125, 0.88]];
  const QDIV = [[-0.86, 1.28], [-0.85, 0.94]]; // 後門窗和三角窗中間的黑條
  const SAIL = [[0.93, 0.905], [0.80, 0.995], [0.78, 0.94], [0.80, 0.895]]; // 後照鏡底座那塊黑色三角
  const FUEL = [-1.46, 0.90, 0.085, 0.06]; // 油箱蓋（中心、半寬、半高）
  function side() {
    return layers(BOX.side, [
      (g) => { smooth(g, DLO); g.fill(); },
      (g) => { // 黑色
        g.lineJoin = 'round'; g.lineWidth = 0.026; smooth(g, DLO); g.stroke(); // 窗框
        poly(g, BPILLAR); g.fill();
        line(g, QDIV, 0.03);
        poly(g, SAIL); g.fill();
        line(g, [[-1.0, 0.22], [0.98, 0.22]], 0.012); // 側裙上的飾條（照片上是一條亮亮的細線，這裡畫成深色）
      },
      (g) => { // 縫
        line(g, [[0.885, 0.90], [0.89, 0.70], [0.885, 0.50], [0.875, 0.33]], 0.005); // 前門前緣
        line(g, [[-0.165, 0.89], [-0.17, 0.60], [-0.17, 0.32]], 0.005); // 前後門中間
        line(g, [[-1.10, 0.955], [-1.07, 0.80], [-0.99, 0.66], [-0.92, 0.52], [-0.87, 0.40], [-0.85, 0.32]], 0.005); // 後門後緣（繞過後輪拱）
        line(g, [[-0.85, 0.315], [0.875, 0.32]], 0.004); // 門下緣
        for (const [x, y] of [[0.0, 0.825], [-0.93, 0.862]]) { g.lineWidth = 0.005; rrect(g, x - 0.085, y - 0.018, x + 0.085, y + 0.018, 0.018); g.stroke(); } // 門把
        g.lineWidth = 0.005; rrect(g, FUEL[0] - FUEL[2], FUEL[1] - FUEL[3], FUEL[0] + FUEL[2], FUEL[1] + FUEL[3], 0.03); g.stroke();
        line(g, [[1.66, 0.76], [1.625, 0.70], [1.60, 0.665], [1.62, 0.60], [1.68, 0.56]], 0.004); // 前保桿和葉子板
        line(g, [[-1.74, 0.82], [-1.68, 0.735], [-1.60, 0.69], [-1.54, 0.665]], 0.004); // 後保桿和後葉子板
        line(g, [[1.10, 0.885], [1.40, 0.87], [1.62, 0.845], [1.66, 0.80]], 0.004); // 引擎蓋和葉子板（側面看得到的那段）
      },
      null,
    ]);
  }

  // ---- 正面（u＝|z|，畫的時候左右鏡射；y）----
  // 大燈：細長、往後掃到葉子板上（尖端在 x 1.67）
  const HEAD = [[0.452, 0.627], [0.48, 0.655], [0.539, 0.685], [0.635, 0.70], [0.701, 0.715], [0.755, 0.745], [0.776, 0.782],
    [0.786, 0.745], [0.786, 0.70], [0.78, 0.662], [0.755, 0.613], [0.687, 0.594], [0.564, 0.585], [0.471, 0.597]];
  const SLOT = [[0.0, 0.655], [0.20, 0.672], [0.38, 0.692], [0.50, 0.70], [0.54, 0.69], [0.40, 0.672], [0.20, 0.643], [0.0, 0.633]]; // 引擎蓋下緣到鍍鉻條中間的黑縫（中間原本有車標，這裡留空）
  const CHROME = [[0.0, 0.626], [0.15, 0.628], [0.30, 0.645], [0.40, 0.657], [0.46, 0.648]]; // 鍍鉻條：從中間接到大燈內角
  const UPPER = [[0.0, 0.62], [0.15, 0.622], [0.30, 0.637], [0.44, 0.640], [0.46, 0.60], [0.40, 0.575], [0.30, 0.555], [0.17, 0.533], [0.0, 0.50]]; // 鍍鉻條下面的上水箱罩（亮黑）
  const LOWER = [[0.0, 0.48], [0.20, 0.52], [0.30, 0.542], [0.45, 0.548], [0.55, 0.525], [0.62, 0.49], [0.665, 0.42], [0.69, 0.33],
    [0.685, 0.255], [0.64, 0.215], [0.50, 0.198], [0.30, 0.19], [0.0, 0.185]]; // 下面的大梯形水箱罩（橫格柵）
  const CRING = [[0.47, 0.548], [0.55, 0.536], [0.62, 0.50], [0.668, 0.45], [0.705, 0.38], [0.722, 0.30], [0.715, 0.245], [0.685, 0.215], [0.60, 0.20], [0.52, 0.196]]; // C 形鍍鉻框
  const FOG = [0.635, 0.30, 0.036];
  const FPLATE = [-0.16, 0.318, 0.16, 0.472];
  function front() {
    const L = LOWER.concat(M(LOWER).slice(1, -1).reverse());
    const U = UPPER.concat(M(UPPER).slice(1, -1).reverse());
    const SL = SLOT.concat(M(SLOT).slice(1, -1).reverse());
    return layers(BOX.front, [
      (g) => { // R：燈（鍍鉻反射罩）、鍍鉻條、C 形框、霧燈
        both2(HEAD, (P) => { smooth(g, P); g.fill(); });
        for (const s of [1, -1]) { line(g, S(CHROME, s), 0.012); line(g, S(CRING, s), 0.016); circle(g, FOG[0] * s, FOG[1], FOG[2]); g.fill(); }
      },
      (g) => { // G：黑色
        poly(g, SL); g.fill();
        smooth(g, U); g.fill();
        smooth(g, L); g.fill();
        g.lineWidth = 0.007; both2(HEAD, (P) => { smooth(g, P); g.stroke(); });
        rrect(g, ...FPLATE.slice(0, 2), ...FPLATE.slice(2), 0.01); g.fill(); // 車牌（空白的黑板子）
        for (const s of [1, -1]) { g.lineWidth = 0.012; circle(g, FOG[0] * s, FOG[1], FOG[2] + 0.008); g.stroke(); }
        g.fillStyle = '#000'; for (const s of [1, -1]) { circle(g, FOG[0] * s, FOG[1], FOG[2]); g.fill(); } g.fillStyle = '#fff';
      },
      (g) => { // B：大燈裡內側上面那一小段橘色
        for (const s of [1, -1]) { poly(g, S([[0.50, 0.668], [0.58, 0.684], [0.58, 0.668], [0.51, 0.655]], s)); g.fill(); }
      },
      (g) => { // A：燈裡的投射鏡（暗）、燈殼下緣；水箱罩的橫格柵
        for (const s of [1, -1]) {
          g.save(); smooth(g, S(HEAD, s)); g.clip();
          for (const [u, y, r] of [[0.60, 0.645, 0.026], [0.68, 0.655, 0.022]]) { circle(g, u * s, y, r); g.fill(); }
          g.fillStyle = 'rgb(140,140,140)'; poly(g, S([[0.45, 0.58], [0.80, 0.58], [0.80, 0.615], [0.45, 0.62]], s)); g.fill();
          g.restore(); g.fillStyle = '#fff';
          circle(g, FOG[0] * s, FOG[1], FOG[2] * 0.6); g.fill();
        }
        g.save(); smooth(g, L); g.clip(); g.strokeStyle = 'rgba(255,255,255,0.45)';
        for (let y = 0.205; y < 0.55; y += 0.028) line(g, [[-0.8, y], [0.8, y + 0.012]], 0.009);
        g.restore();
        g.save(); smooth(g, U); g.clip(); g.strokeStyle = 'rgba(255,255,255,0.35)';
        for (let y = 0.51; y < 0.65; y += 0.022) line(g, [[-0.6, y], [0.6, y]], 0.004);
        g.restore();
        g.fillStyle = '#000'; rrect(g, ...FPLATE.slice(0, 2), ...FPLATE.slice(2), 0.01); g.fill(); g.fillStyle = '#fff'; // 車牌上沒有格柵
      },
    ]);
  }

  // ---- 後面（u＝z，y）：細長尾燈（外段在後葉子板、內段在行李箱蓋），中間一條鍍鉻條連起來 ----
  const LAMP = [[0.299, 0.874], [0.309, 0.886], [0.37, 0.890], [0.52, 0.889], [0.634, 0.897], [0.711, 0.892], [0.765, 0.822],
    [0.751, 0.810], [0.715, 0.790], [0.667, 0.765], [0.589, 0.759], [0.508, 0.760], [0.454, 0.767], [0.399, 0.791], [0.357, 0.819], [0.324, 0.856]];
  const RED_TOP = [[0.30, 0.882], [0.52, 0.886], [0.70, 0.893], [0.76, 0.826], [0.72, 0.812], [0.66, 0.845], [0.52, 0.85], [0.33, 0.858]]; // 上緣一條紅＋外段整塊紅
  const RED_OUT = [[0.53, 0.885], [0.70, 0.892], [0.765, 0.822], [0.70, 0.785], [0.60, 0.775], [0.53, 0.79]];
  const REV = [[0.34, 0.845], [0.40, 0.84], [0.50, 0.826], [0.50, 0.81], [0.42, 0.818], [0.36, 0.83]]; // 內段的白色倒車燈條
  const BAR = [[0.0, 0.888], [0.20, 0.886], [0.30, 0.880], [0.30, 0.866], [0.20, 0.872], [0.0, 0.874]]; // 中間的鍍鉻條
  function rear() {
    const B = BAR.concat(M(BAR).slice(1, -1).reverse());
    return layers(BOX.rear, [
      (g) => { // R：紅燈、下面的紅色反光片
        for (const s of [1, -1]) {
          smooth(g, S(RED_TOP, s)); g.fill(); smooth(g, S(RED_OUT, s)); g.fill();
          rrect(g, Math.min(0.47 * s, 0.68 * s), 0.30, Math.max(0.47 * s, 0.68 * s), 0.33, 0.012); g.fill();
        }
      },
      (g) => { // G：燈殼（黑）、車牌、行李箱蓋下面的黑色下巴
        both2(LAMP, (P) => { smooth(g, P); g.fill(); });
        rrect(g, -0.16, 0.668, 0.16, 0.818, 0.01); g.fill(); // 車牌（空白）
        poly(g, [[-0.62, 0.215], [0.62, 0.215], [0.70, 0.235], [0.74, 0.22], [0.74, 0.10], [-0.74, 0.10], [-0.74, 0.22], [-0.70, 0.235]]); g.fill(); // 保桿最下面的黑邊
        g.fillStyle = '#000'; // 紅色的地方不要黑
        for (const s of [1, -1]) { smooth(g, S(RED_TOP, s)); g.fill(); smooth(g, S(RED_OUT, s)); g.fill(); }
        g.fillStyle = '#fff';
      },
      (g) => { // B：倒車燈條、鍍鉻條（淺色）
        for (const s of [1, -1]) { smooth(g, S(REV, s)); g.fill(); }
        smooth(g, B); g.fill();
      },
      (g) => { // A：縫：行李箱蓋、保桿
        line(g, [[-0.515, 0.89], [-0.515, 0.76], [-0.49, 0.65], [-0.44, 0.605], [-0.25, 0.585], [0.25, 0.585], [0.44, 0.605], [0.49, 0.65], [0.515, 0.76], [0.515, 0.89]], 0.004);
        line(g, [[-0.73, 0.235], [0.73, 0.235]], 0.003);
      },
    ]);
  }

  // ---- 上面（x, z）：前擋、後擋、雨刷飾板、引擎蓋和行李箱蓋的縫 ----
  const WS = [[1.10, 0], [1.092, 0.30], [1.06, 0.50], [0.985, 0.62], [0.905, 0.685], [0.82, 0.668], [0.56, 0.565], [0.36, 0.478],
    [0.29, 0.445], [0.27, 0.40], [0.285, 0.20], [0.30, 0]];
  const BL = [[-1.035, 0], [-1.03, 0.30], [-1.02, 0.44], [-1.06, 0.50], [-1.30, 0.545], [-1.52, 0.54], [-1.60, 0.49], [-1.65, 0.30], [-1.67, 0]];
  const COWL = [[1.20, 0], [1.195, 0.30], [1.16, 0.52], [1.08, 0.66], [1.00, 0.70], [0.96, 0.68], [1.04, 0.62], [1.09, 0.50], [1.115, 0.30], [1.12, 0]];
  function top() {
    return layers(BOX.top, [
      null,
      (g) => {
        frit(g, both(WS), 0.03, [0.2, 0.33], [1.05, 1.2]);
        frit(g, both(BL), 0.03, [-1.07, -1.0], [-1.72, -1.62]);
        smooth(g, both(COWL)); g.fill();
      },
      (g) => {
        line(g, [[1.12, 0.72], [1.40, 0.77], [1.62, 0.77], [1.85, 0.70], [2.05, 0.56], [2.20, 0.40], [2.23, 0], [2.20, -0.40], [2.05, -0.56], [1.85, -0.70], [1.62, -0.77], [1.40, -0.77], [1.12, -0.72]], 0.005);
        line(g, [[-1.70, 0.62], [-1.80, 0.66], [-2.00, 0.62], [-2.15, 0.52], [-2.22, 0.30], [-2.235, 0], [-2.22, -0.30], [-2.15, -0.52], [-2.00, -0.62], [-1.80, -0.66], [-1.70, -0.62]], 0.005);
      },
      (g) => { smooth(g, both(WS)); g.fill(); smooth(g, both(BL)); g.fill(); },
    ]);
  }

  // ---- 拉花：小黃 ----
  const GREY = '#4a4b50'; // 保桿下半部、側裙的深灰色
  const FONT = '"Noto Sans TC", "PingFang TC", "Microsoft JhengHei", "Noto Sans CJK TC", "Arial Black", sans-serif';
  // 側面的灰色：前保桿轉角（大燈下面、葉子板縫前面）、側裙、後保桿側面（尾燈下面、後葉子板縫後面）
  const GREY_FRONT = [[1.60, 0.665], [1.63, 0.61], [1.68, 0.585], [1.80, 0.60], [1.95, 0.60], [2.20, 0.62], [2.40, 0.65], [2.40, 0.0], [1.60, 0.0]];
  const GREY_REAR = [[-1.53, 0.0], [-1.53, 0.66], [-1.60, 0.69], [-1.68, 0.735], [-1.745, 0.82], [-1.80, 0.815], [-2.40, 0.79], [-2.40, 0.0]];
  function livery(sd, style = 'taxi') {
    const { c, g } = canvas(BOX.side);
    g.clearRect(-3, -1, 6, 3);
    if (style !== 'taxi') return c;
    g.fillStyle = GREY;
    poly(g, GREY_FRONT); g.fill();
    poly(g, GREY_REAR); g.fill();
    poly(g, [[-1.6, 0.0], [-1.6, 0.30], [1.7, 0.30], [1.7, 0.0]]); g.fill(); // 側裙（門下緣以下）
    // 黑白格子條：前門前緣到後門後緣，車門中間高一點
    const y0 = 0.50, h = 0.05, n = 2, x0 = -1.05, x1 = 0.86, sq = h / n;
    for (let i = 0; x1 - (i + 1) * sq >= x0; i++) for (let j = 0; j < n; j++) {
      g.fillStyle = (i + j) % 2 ? '#f4f5f6' : '#141518';
      const x = x1 - (i + 1) * sq; g.fillRect(x, y0 + j * sq, sq + 0.0005, sq + 0.0005);
    }
    // 車門上的字：前門「大便龍 88」、後門大號碼（兩邊的字都是正的）
    g.fillStyle = '#16348c';
    const tx = (s, x, y, size, w = 900) => text(g, s, x, y, size, { font: FONT, weight: w, mirror: sd < 0 });
    // 字的位置兩邊一樣；左邊那張貼圖從車外看是左右相反的，所以字本身鏡射
    tx('大便龍', 0.40, 0.68, 0.11);
    tx('88', -0.55, 0.70, 0.17);
    tx('計程車', -0.55, 0.605, 0.05, 700);
    // 保留的小格子（2.34, 1.36）：P918 那種貼片看這裡知道現在是小黃拉花（後保桿的灰色貼片用）
    g.fillStyle = GREY; g.fillRect(2.30, 1.33, 0.05, 0.07);
    return c;
  }
  // 正面：保桿下半部灰色（大燈下緣、鍍鉻條以下）
  function frontLivery(style = 'taxi') {
    const { c, g } = canvas(BOX.front);
    g.clearRect(-2, -1, 4, 3);
    if (style !== 'taxi') return c;
    const P = [[0.0, 0.626], [0.30, 0.643], [0.452, 0.627], [0.471, 0.597], [0.564, 0.585], [0.687, 0.594], [0.755, 0.613], [0.78, 0.662],
      [0.79, 0.70], [0.80, 0.745], [1.0, 0.75], [1.0, 0.0], [0.0, 0.0]];
    g.fillStyle = GREY; poly(g, P.concat(M(P).slice(1, -1).reverse())); g.fill();
    return c;
  }

  return {
    side, rear, top,
    fronts: { base: front },
    livery, frontLivery,
    livDefault: 1,
    nose: () => 'base',
    GREY,
    // 輪拱內側變黑的半徑比挖洞的半徑大一點點
    U: { uXr: -1.315, uXf: 1.385, uFx: [1.60, 1.70], uRx: [-1.68, -1.74], uWell: [0.326, 0.372, 0.885], uWellR: [0.326, 0.372, 0.885], uGlassY: 0.87 },
  };
})();
