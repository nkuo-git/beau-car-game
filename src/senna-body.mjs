// 中線側面輪廓、俯視輪廓拉成柱體取交集＋修圓，頂面用「高度差」做出前葉子板、後葉子板的隆起，
// 水滴形車艙（一路變成車尾的引擎蓋脊）另外做再接上；車頭兩邊的大進氣口、車門下面的導風槽、側面大進氣口往內挖，最後切網格。
// 座標（公尺）：x 往車頭（-2.372 車尾、+2.372 車頭，含前下巴）、y 往上、z 往車的右側。
// 尺寸：長 4.744、寬 1.958、高 1.229、軸距 2.670、輪距前 1.68／後 1.63；輪胎前 245/35 R19（半徑 0.327）、後 315/30 R20（半徑 0.3485）。
// 前懸 1.20、後懸 0.87（照片量的）。相機從輪子＋共用的點一起解（senna3d/ba.mjs），再疊圖修輪廓。
import { curve, sdf2d, look, smin, smax, rbox } from './body.mjs';

export const SENNA = { L: 4.744, W: 1.958, H: 1.229, xf: 1.092, xr: -1.578, RF: 0.327, RR: 0.3485 };
export const BOUNDS = [-2.42, 0.04, 2.42, 1.30, 1.02];
const mirrorZ = (r) => [...r, ...r.slice(1, -1).reverse().map(([x, z, s]) => [x, -z, s])];

// 下半身中線側面：車頭上緣 → 引擎蓋（往後上升到前擋下緣）→（車艙底下）→ 引擎蓋脊兩邊的後甲板 → 車尾 → 底盤 → 車頭下面
export const SIDE = [
  [2.33, 0.475, 1], [2.22, 0.54, 1], [2.05, 0.59, 1], [1.85, 0.635, 1], [1.55, 0.69, 1], [1.25, 0.73, 1], [0.95, 0.755, 1],
  [0.50, 0.78, 1], [-0.50, 0.80, 1], [-1.20, 0.80, 1], [-1.60, 0.80, 1], [-2.00, 0.78, 1], [-2.20, 0.74, 1], [-2.27, 0.66, 1],
  [-2.28, 0.52, 1], [-2.32, 0.46, 1], [-2.37, 0.41, 1], [-2.37, 0.34, 1], [-2.30, 0.29, 0], [-2.05, 0.20, 0], [-1.70, 0.12, 0],
  [1.90, 0.11, 0], [2.30, 0.12, 1], [2.36, 0.16, 1], [2.37, 0.30, 1], [2.36, 0.42, 1],
];
// 俯視輪廓（最寬的地方）：車頭寬寬平平、前葉子板、車門稍微窄、後葉子板最寬，車尾往內收
export const PLAN = mirrorZ([
  [2.37, 0, 1], [2.365, 0.32, 1], [2.33, 0.52, 1], [2.26, 0.68, 1], [2.15, 0.80, 1], [1.98, 0.90, 1], [1.75, 0.955, 1], [1.45, 0.975, 1],
  [1.10, 0.975, 1], [0.75, 0.95, 1], [0.40, 0.93, 1], [0.0, 0.925, 1], [-0.40, 0.94, 1], [-0.80, 0.965, 1], [-1.20, 0.979, 1],
  [-1.60, 0.979, 1], [-1.95, 0.97, 1], [-2.15, 0.94, 1], [-2.28, 0.88, 1], [-2.35, 0.75, 1], [-2.37, 0.50, 1], [-2.37, 0, 1],
]);
// 車艙側面（中線）：前擋 → 車頂 → 一路往後變成引擎蓋脊，下面伸進車身
export const CABIN_SIDE = [
  [1.05, 0.70, 0], [0.95, 0.76, 1], [0.70, 0.925, 1], [0.45, 1.07, 1], [0.19, 1.175, 1], [-0.10, 1.21, 1], [-0.40, 1.205, 1],
  [-0.70, 1.165, 1], [-0.95, 1.115, 1], [-1.30, 1.03, 1], [-1.70, 0.95, 1], [-2.05, 0.895, 1], [-2.20, 0.865, 1], [-2.25, 0.78, 0],
  [-2.25, 0.70, 0], [1.05, 0.62, 0],
];
// 車艙俯視（腰線高度）：水滴形，前擋那邊寬、往後收成細細的引擎蓋脊
export const CABIN_PLAN = mirrorZ([
  [1.06, 0, 1], [1.03, 0.50, 1], [0.93, 0.64, 1], [0.70, 0.70, 1], [0.30, 0.71, 1], [-0.10, 0.70, 1], [-0.40, 0.66, 1],
  [-0.70, 0.56, 1], [-1.00, 0.43, 1], [-1.40, 0.32, 1], [-1.80, 0.27, 1], [-2.10, 0.24, 1], [-2.25, 0.20, 1], [-2.27, 0, 1],
]);
export const CABIN_Y0 = 0.78, TUMBLE = 0.72;

const sstep = (a, b, x) => { const t = Math.max(0, Math.min(1, (x - a) / (b - a))); return t * t * (3 - 2 * t); };
const win = (x, a, b, c, d) => sstep(a, b, x) * (1 - sstep(c, d, x));
const bump = (t) => (Math.abs(t) >= 1 ? 0 : (1 - t * t) ** 2);
const box2 = (x, y, hx, hy, r) => { const qx = Math.abs(x) - hx + r, qy = Math.abs(y) - hy + r; return Math.hypot(Math.max(qx, 0), Math.max(qy, 0)) + Math.min(Math.max(qx, qy), 0) - r; };
function tab(t, x) {
  if (x <= t[0][0]) return t[0][1];
  for (let i = 1; i < t.length; i++) if (x <= t[i][0]) { const a = t[i - 1], b = t[i], u = (x - a[0]) / (b[0] - a[0]), q = u * u * (3 - 2 * u); return a[1] + (b[1] - a[1]) * q; }
  return t[t.length - 1][1];
}
// 前葉子板頂比中線高多少（沿 x）
const FF_LIFT = [[0.65, 0.0], [0.90, 0.035], [1.12, 0.045], [1.40, 0.055], [1.80, 0.06], [2.05, 0.045], [2.25, 0.02], [2.36, 0.0]];
// 後葉子板頂比中線高多少
const RR_LIFT = [[-2.36, 0.0], [-2.24, 0.03], [-2.00, 0.08], [-1.67, 0.115], [-1.36, 0.14], [-1.00, 0.15], [-0.75, 0.13], [-0.45, 0.08], [-0.25, 0.0]];
export function lift(x, az) {
  const crown = -0.02 * (az / 1.0) ** 2;
  const ff = tab(FF_LIFT, x) * bump((az - 0.80) / 0.30);
  const rr = tab(RR_LIFT, x) * bump((az - 0.79) / 0.34);
  return crown + ff + rr;
}
// 側面往內收：下面收（側裙以下）、上面收（肩線以上）
function tuck(x, y) {
  const low = 0.06 * (1 - sstep(0.13, 0.32, y));
  const shoulder = 1.2 * Math.max(0, y - 0.62) ** 2;
  return low + shoulder;
}

export function makeSDF(opt = {}) {
  const res = 0.005;
  const side = sdf2d(curve(SIDE), -2.45, -0.05, 2.45, 1.3, res);
  const plan = sdf2d(curve(PLAN), -2.45, -1.1, 2.45, 1.1, res);
  const cabS = sdf2d(curve(CABIN_SIDE), -2.3, 0.5, 1.4, 1.35, res);
  const cabP = sdf2d(curve(CABIN_PLAN), -2.3, -1.0, 1.4, 1.0, res);
  const R1 = 0.08, RC = 0.10, RU = 0.05;
  const arches = [{ x: SENNA.xf, y: SENNA.RF, R: 0.372, zIn: 0.60 }, { x: SENNA.xr, y: SENNA.RR, R: 0.395, zIn: 0.60 }];
  return function f(x, y, z) {
    const az = Math.abs(z);
    const dS = look(side, x, y - lift(x, az));
    const dP = look(plan, x, az + tuck(x, y));
    let d = smax(dS, dP, R1);
    // 車艙
    const zc = az / 0.72;
    const cS = look(cabS, x, y + 0.05 * zc * zc);
    const cP = look(cabP, x, az + Math.max(0, y - CABIN_Y0) * TUMBLE);
    d = smin(d, smax(cS, cP, RC), RU);
    // 車頭兩邊的大進氣口（鼻子和葉子板刀片中間、大燈下面）：往內挖很深（裡面黑色）
    if (x > 1.75) {
      const yt = 0.47 + 0.06 * sstep(0.5, 0.8, az);
      const g = Math.max(box2(az - 0.625, y - (0.13 + yt) / 2 - 0.02, 0.185, (yt - 0.13) / 2, 0.05), 1.95 - x);
      d = smax(d, -Math.max(g, -(d + 0.28)), 0.015);
    }
    // 引擎蓋中間的出風口：往下凹的大碗（前尖後寬，後面開口對著前擋）
    if (x > 1.0 && x < 2.1 && az < 0.5) {
      const t = (x - 1.10) / 0.85, hz = 0.40 - 0.28 * Math.max(0, t);
      const b = Math.max(box2(x - 1.52, y - 0.73, 0.42, 0.14, 0.05), az - hz);
      d = smax(d, -Math.max(b, -(d + 0.05 + 0.03 * (1 - Math.max(0, t)))), 0.03);
    }
    // 車門下半部往內凹（下車窗那一塊），後面接側面大進氣口
    if (x > -0.40 && x < 0.75 && az > 0.6) {
      const ch = box2(x - 0.17, y - 0.535, 0.46, 0.195, 0.08);
      d = smax(d, -Math.max(ch, -(d + 0.09)), 0.04);
    }
    if (x > -1.0 && x < -0.2 && az > 0.55) {
      const it = box2(x + 0.59, y - 0.60, 0.26, 0.29, 0.10);
      d = smax(d, -Math.max(it, -(d + 0.24)), 0.03);
    }
    // 車尾：網子那一片往內凹
    if (x < -2.1) {
      const t = box2(az, y - 0.63, 0.80, 0.135, 0.04);
      d = smax(d, -Math.max(t, -(d + 0.10)), 0.015);
    }
    // 車尾下面：擴散器的通道往上斜（鰭片是另外的零件）
    if (x < -1.85) {
      const roof = 0.12 + 0.20 * Math.min(1, (-1.85 - x) / 0.52);
      d = smax(d, -Math.max(y - roof, az - 0.78), 0.03);
    }
    // 輪拱：挖洞
    for (const a of arches) {
      const dc = Math.hypot(x - a.x, y - a.y) - a.R;
      d = smax(d, -smax(dc, a.zIn - az, 0.03), 0.02);
    }
    // 車頂進氣口（車頂後面的小鼓包）
    if (x < -0.35 && x > -1.05 && y > 1.0) {
      const sc = rbox(x + 0.68, y - 1.19, az, 0.25, 0.045 - 0.03 * sstep(-0.5, -0.95, x), 0.15, 0.03);
      d = smin(d, sc, 0.04);
    }
    return d;
  };
}
