// 3D Bugatti Chiron 的表面細節（投影貼圖），做法跟 gtr-look.js 一樣。
// 位置是照四張照片量的：照片上的點從相機打光線到車身（camfit.hit，chiron3d/hit.mjs），得到車身上的 (x, y, z)。
// 沒有任何牌子、字、徽章：水箱罩中間、車尾中間原本有徽章的地方都留空；車牌是一塊空白的板子。
// 拉花「雙色」＝經典的兩色車身：C 字線後面（後葉子板、引擎蓋板、車尾）和 C 上面（A 柱、車頂）是深色，前面是車漆。
// 側面拉花貼圖左上角有一小塊記號：chiron-spec.js 的車漆補丁看到它，才把這張圖也畫到朝上、朝後的面（車頂、引擎蓋板、車尾）。
import { BOX, layers, poly, smooth, line, both, frit, canvas } from './masks.js';

export const CHIRON_LOOK = (() => {
  const M = (pts) => pts.map(([u, y]) => [-u, y]); // 左右鏡射
  const both2 = (g, pts, fn) => { for (const P of [pts, M(pts)]) fn(P); };
  const DARK = '#111725';

  // ---- 側面（x, y）----
  // C 字線（跟 chiron-body.mjs 的 CLINE 一樣）
  const CL = [[0.62, 0.84], [0.40, 0.94], [0.15, 1.055], [-0.10, 1.115], [-0.45, 1.115], [-0.70, 1.06], [-0.84, 0.95], [-0.885, 0.82],
    [-0.865, 0.68], [-0.78, 0.53], [-0.64, 0.40], [-0.46, 0.305], [-0.20, 0.26], [0.15, 0.24], [0.50, 0.232], [0.80, 0.228], [0.98, 0.226]];
  // 側窗：前緣沿著 A 柱、上緣在 C 字線裡面、後緣直直的（後面是進氣口）
  const DLO = [[0.545, 0.838], [0.38, 0.918], [0.15, 1.028], [-0.10, 1.083], [-0.36, 1.085], [-0.415, 1.06], [-0.425, 0.95], [-0.42, 0.838], [0.0, 0.832]];
  // 側窗後面的大進氣口（C 裡面後上角），沿著 C 的內緣往下收成一條細縫
  const INTAKE = [[-0.41, 1.09], [-0.445, 1.092], [-0.69, 1.045], [-0.82, 0.94], [-0.862, 0.82], [-0.845, 0.69], [-0.77, 0.548], [-0.64, 0.425], [-0.615, 0.445],
    [-0.725, 0.565], [-0.79, 0.69], [-0.79, 0.79], [-0.70, 0.835], [-0.47, 0.84], [-0.41, 0.84]];
  function side() {
    return layers(BOX.side, [
      (g) => { smooth(g, DLO); g.fill(); },
      (g) => { // 黑色：窗框、進氣口、門檻下面的碳纖維側裙
        g.lineJoin = 'round'; g.lineWidth = 0.014; smooth(g, DLO); g.stroke();
        smooth(g, INTAKE); g.fill();
        poly(g, [[-0.97, 0.10], [1.0, 0.10], [0.99, 0.19], [0.60, 0.205], [0.0, 0.212], [-0.60, 0.215], [-0.95, 0.215]]); g.fill();
      },
      (g) => { // 縫：車門前緣（前輪拱後面）、後緣（斜的）
        line(g, [[0.60, 0.834], [0.93, 0.79], [0.935, 0.62], [0.925, 0.42], [0.90, 0.25]], 0.005);
        line(g, [[-0.33, 0.832], [-0.25, 0.64], [-0.14, 0.42], [-0.06, 0.262]], 0.005);
        line(g, [[1.70, 0.78], [1.98, 0.72], [2.16, 0.62]], 0.004); // 引擎蓋側邊
      },
      null,
    ]);
  }

  // ---- 正面（u＝|z|，畫的時候左右鏡射；y）----
  // 大燈：前葉子板前緣細長的一條，裡面四顆 LED 投射燈
  const HEAD = [[0.905, 0.625], [0.89, 0.641], [0.81, 0.652], [0.71, 0.659], [0.60, 0.664], [0.615, 0.645], [0.64, 0.585], [0.74, 0.579], [0.845, 0.575], [0.90, 0.588]];
  const LEDS = [[0.878, 0.611], [0.825, 0.614], [0.765, 0.618], [0.700, 0.622]];
  // 下進氣口（大燈下面，網子）
  const MOUTH = [[0.36, 0.395], [0.60, 0.405], [0.80, 0.39], [0.875, 0.37], [0.88, 0.32], [0.855, 0.268], [0.60, 0.258], [0.38, 0.262], [0.345, 0.32]];
  // 馬蹄形水箱罩的輪廓（跟 chiron-body.mjs 的 CHIRON_hs 一樣：圓拱＋兩邊往下微微收窄），k＝往內縮多少
  function shoe(g, k, begin = true) {
    if (begin) g.beginPath();
    const r = 0.165 - k, ry = r / 0.82;
    g.moveTo(0.165 - 0.06 * 0.27 - k, 0.20 + k);
    g.lineTo(r, 0.47);
    for (let i = 0; i <= 24; i++) { const t = (i / 24) * Math.PI; g.lineTo(Math.cos(t) * r, 0.47 + Math.sin(t) * ry); }
    g.lineTo(-(0.165 - 0.06 * 0.27 - k), 0.20 + k);
    g.closePath();
  }
  const mesh = (g, x0, x1, y0, y1, s, w) => { // 斜格子網
    for (let k = x0 - (y1 - y0); k < x1; k += s) { line(g, [[k, y0], [k + (y1 - y0), y1]], w); line(g, [[k, y1], [k + (y1 - y0), y0]], w); }
  };
  function front() {
    return layers(BOX.front, [
      (g) => { // R：大燈、馬蹄形的亮框（下緣比較粗）、下進氣口下面的銀色飾條
        both2(g, HEAD, (P) => { smooth(g, P); g.fill(); });
        shoe(g, -0.004); shoe(g, 0.024, false); g.fill('evenodd');
        poly(g, [[-0.15, 0.198], [0.15, 0.198], [0.14, 0.236], [0.02, 0.24], [0, 0.262], [-0.02, 0.24], [-0.14, 0.236]]); g.fill();
        both2(g, [[0.17, 0.236], [0.60, 0.243], [0.93, 0.262], [0.93, 0.248], [0.60, 0.229], [0.17, 0.222]], (P) => { poly(g, P); g.fill(); });
      },
      (g) => { // G：黑色（水箱罩裡面、下進氣口、大燈外框、下巴）
        shoe(g, 0.024); g.fill();
        both2(g, MOUTH, (P) => { smooth(g, P); g.fill(); });
        g.lineWidth = 0.006; both2(g, HEAD, (P) => { smooth(g, P); g.stroke(); });
        poly(g, [[-1, 0], [1, 0], [1, 0.205], [-1, 0.205]]); g.fill();
      },
      null,
      (g) => { // A：大燈裡面是燻黑的燈殼（四顆投射燈亮的）、水箱罩和下進氣口的網子
        for (const s of [1, -1]) {
          g.save(); smooth(g, HEAD.map(([u, y]) => [u * s, y])); g.clip();
          g.fillRect(-1, 0.5, 2, 0.2);
          g.fillStyle = '#000';
          for (const [u, y] of LEDS) { g.beginPath(); g.roundRect(u * s - 0.02, y - 0.017, 0.04, 0.034, 0.008); g.fill(); }
          g.fillStyle = '#fff';
          for (const [u, y] of LEDS) { g.beginPath(); g.arc(u * s, y, 0.009, 0, Math.PI * 2); g.fill(); }
          g.restore();
        }
        g.save(); shoe(g, 0.024); g.clip(); mesh(g, -0.2, 0.2, 0.19, 0.66, 0.026, 0.003); g.restore();
        for (const s of [1, -1]) { g.save(); smooth(g, MOUTH.map(([u, y]) => [u * s, y])); g.clip(); mesh(g, -0.9, 0.9, 0.25, 0.41, 0.024, 0.003); g.restore(); }
      },
    ]);
  }

  // ---- 後面（u＝z，y）：上角兩組鋸齒形紅色尾燈、整條弧形的燈條、下面整片黑色網子面板、空白車牌 ----
  const barY = (u) => 0.505 + 0.08 * (u / 0.80) ** 2;
  const BAR = (dy0, dy1) => { const a = [], b = []; for (let i = 0; i <= 40; i++) { const u = -0.80 + (1.60 * i) / 40; a.push([u, barY(u) + dy1]); b.push([u, barY(u) + dy0]); } return [...a, ...b.reverse()]; };
  function teeth(g, s) { // 鋸齒形尾燈：底下一條，上面一排尖尖的
    const pts = [[0.50 * s, 0.578], [0.825 * s, 0.592], [0.83 * s, 0.618]];
    const n = 10;
    for (let i = n; i >= 0; i--) { const u = 0.51 + (0.31 * i) / n; pts.push([u * s, i % 2 ? 0.652 : 0.616]); }
    poly(g, pts); g.fill();
  }
  function rear() {
    return layers(BOX.rear, [
      (g) => { for (const s of [1, -1]) teeth(g, s); poly(g, BAR(0.0, 0.024)); g.fill(); },
      (g) => { // 黑色：燈條下面整片面板、兩組尾燈中間、上面的散熱網
        poly(g, [...BAR(-0.004, -0.004).slice(0, 41), [0.82, 0.28], [-0.82, 0.28]]); g.fill();
        poly(g, [[-0.50, 0.57], [0.50, 0.57], [0.50, 0.675], [-0.50, 0.675]]); g.fill();
        g.beginPath(); g.roundRect(-0.33, 0.715, 0.66, 0.09, 0.03); g.fill();
      },
      (g) => { // B：燈條下緣的銀邊、空白車牌
        poly(g, BAR(-0.008, 0.0)); g.fill();
        g.beginPath(); g.roundRect(-0.26, 0.36, 0.52, 0.105, 0.008); g.fill();
      },
      (g) => { line(g, [[-0.80, 0.69], [0.80, 0.69]], 0.004); },
    ]);
  }

  // ---- 上面（x, z）：前擋（黑邊）、引擎室兩片玻璃（黑）、蓋子的縫 ----
  const WS = [[0.80, 0], [0.795, 0.35], [0.775, 0.60], [0.74, 0.72], [0.50, 0.70], [0.30, 0.62], [0.17, 0.545], [0.06, 0.40], [-0.02, 0.20], [-0.05, 0]];
  const ENG = [[-1.00, 0.04], [-1.00, 0.36], [-1.10, 0.42], [-1.62, 0.36], [-1.66, 0.30], [-1.66, 0.04]];
  function top() {
    return layers(BOX.top, [
      (g) => { // R：霧面黑（尾翼前面的散熱網）
        for (const s of [1, -1]) { poly(g, [[-1.70, 0.05 * s], [-1.70, 0.40 * s], [-1.76, 0.42 * s], [-1.76, 0.05 * s]]); g.fill(); }
      },
      (g) => { // G：黑色（前擋黑邊、引擎室玻璃）
        frit(g, both(WS), 0.035, [-0.10, 0.02], [0.74, 0.85]);
        for (const s of [1, -1]) { smooth(g, ENG.map(([x, z]) => [x, z * s])); g.fill(); }
      },
      (g) => { // B：縫（引擎蓋、引擎室蓋、尾翼）
        line(g, [[0.86, 0.60], [1.40, 0.58], [1.90, 0.50], [2.12, 0.30], [2.14, 0], [2.12, -0.30], [1.90, -0.50], [1.40, -0.58], [0.86, -0.60]], 0.005);
        smooth(g, both([[-0.95, 0], [-0.95, 0.45], [-1.70, 0.48], [-1.70, 0]])); g.lineWidth = 0.005; g.stroke();
        poly(g, both([[-1.765, 0], [-1.765, 0.76], [-2.20, 0.76], [-2.20, 0]])); g.stroke();
      },
      (g) => { smooth(g, both(WS)); g.fill(); },
    ]);
  }

  // ---- 拉花「雙色」：C 字線後面、上面整片深色（側面貼圖；車漆補丁也拿它畫車頂、引擎蓋板、車尾）----
  function livery(sd, s = 'duo') {
    const { c, g } = canvas(BOX.side);
    g.clearRect(-3, -1, 6, 3);
    if (s === 'none') return c;
    g.fillStyle = DARK;
    g.beginPath(); g.moveTo(0.80, 1.45); g.lineTo(0.80, 0.86); g.lineTo(0.66, 0.842);
    for (const [x, y] of CL) g.lineTo(x, y);
    g.lineTo(1.00, 0.215); g.lineTo(1.00, -0.1); g.lineTo(-2.45, -0.1); g.lineTo(-2.45, 1.45); g.closePath(); g.fill();
    g.fillRect(-2.35, 1.37, 0.03, 0.03); // 記號（車身碰不到的角落）
    return c;
  }
  function frontLivery() { const { c, g } = canvas(BOX.front); g.clearRect(-2, -1, 4, 3); return c; }

  return {
    side, rear, top,
    fronts: { base: front },
    livery, frontLivery,
    livDefault: 1,
    nose: () => 'base',
    U: { uXr: -1.341, uXf: 1.37, uFx: [1.62, 1.72], uRx: [-1.95, -2.05], uWell: [0.3395, 0.41, 1.2], uWellR: [0.3555, 0.425, 1.2], uGlassY: 0.77 },
  };
})();
