// 拱形（中線高 → 兩側低多少）
const CROWN = [[-2.2, 0.05], [-1.6, 0.06], [-1.0, 0.06], [0.6, 0.05], [1.4, 0.04], [2.2, 0.05]];
// 前葉子板比引擎蓋高多少（x → 高度），中心在 |z|＝FEN_Z
const FENDER = [[0.50, 0.0], [0.90, 0.04], [1.30, 0.065], [1.55, 0.07], [1.75, 0.06], [1.95, 0.035], [2.12, 0.0]];
const FEN_Z = 0.62, FEN_S = 0.15;
// 掀式大燈蓋（關著）：俯視的輪廓（x, |z|），蓋子比旁邊高一點、邊緣清楚
export const LID = [[1.923, 0.617], [1.876, 0.699], [1.782, 0.761], [1.66, 0.795], [1.567, 0.769], [1.534, 0.71], [1.57, 0.64], [1.64, 0.55],
  [1.75, 0.525], [1.86, 0.565]];
function lerpTable(t, x) {
  if (x <= t[0][0]) return t[0][1];
  for (let i = 1; i < t.length; i++) if (x <= t[i][0]) { const a = t[i - 1], b = t[i], u = (x - a[0]) / (b[0] - a[0]), s = u * u * (3 - 2 * u); return a[1] + (b[1] - a[1]) * s; }
  return t[t.length - 1][1];
}
const sstep = (a, b, x) => { const t = Math.max(0, Math.min(1, (x - a) / (b - a))); return t * t * (3 - 2 * t); };
const gau = (a, m, s) => Math.exp(-(((a - m) / s) ** 2));
const box2 = (x, y, hx, hy, r) => { const qx = Math.abs(x) - hx + r, qy = Math.abs(y) - hy + r; return Math.hypot(Math.max(qx, 0), Math.max(qy, 0)) + Math.min(Math.max(qx, qy), 0) - r; };

export const NOSE_X = 1.5;
export function makeSDF(opt = {}) {
  const res = 0.005;
  const side = sdf2d(curve(LOWER_SIDE), -2.35, -0.05, 2.35, 1.2, res);
  const cabS = sdf2d(curve(CABIN_SIDE), -2.1, 0.7, 0.9, 1.4, res);
  const plan = sdf2d(curve(PLAN), -2.35, -1.1, 2.35, 1.1, res);
  const cabP = sdf2d(curve(CABIN_PLAN), -2.2, -1.0, 0.9, 1.0, res);
  const front = sdf2d(curve(FRONT), -1.1, -0.05, 1.1, 1.2, res);
  const R1 = opt.R1 ?? 0.10, R2 = opt.R2 ?? 0.09, RC = opt.RC ?? 0.12, RU = opt.RU ?? 0.06;
  const lid = sdf2d(curve(LID), 1.4, 0.4, 2.05, 0.9, 0.004);
  const arch = { R: 0.352, y: RX7.R, zIn: 0.60 };
  return function f(x, y, z) {
    const az = Math.abs(z);
    const zz = az / 0.9;
    // 拱形往下＋前葉子板往上＋大燈蓋（只動上半部，底盤不跟著動）
    const up = sstep(0.30, 0.55, y);
    const lb = x > 1.45 && x < 2.0 && az > 0.45 ? 0.009 * sstep(0.02, -0.012, look(lid, x, az)) : 0;
    const cr = lerpTable(CROWN, x) * zz * zz - up * (lerpTable(FENDER, x) * gau(az, FEN_Z, FEN_S) + lb);
    const dS = look(side, x, y + cr);
    // 車門下半部往內凹一點（凹的上緣從前輪後面往後上斜）
    const yL = 0.33 + (0.5 - x) * 0.06;
    const ins = 0.022 * sstep(yL + 0.06, yL - 0.04, y) * sstep(0.86, 0.62, x) * sstep(-0.98, -0.72, x);
    const dP = look(plan, x, az + ins);
    const dF = look(front, az, y);
    let d = smax(dS, dP, R1);
    d = smax(d, dF, R2);
    // 車艙：雙泡泡車頂（兩條鼓起、中間一道淺溝）
    const zc = az / 0.72;
    const bub = sstep(0.25, -0.05, x) * sstep(-1.25, -0.85, x);
    const cS = look(cabS, x, y + 0.05 * zc * zc - bub * 0.014 * (gau(az, 0.30, 0.14) - 0.6 * gau(az, 0, 0.08)));
    const cP = look(cabP, x, az + Math.max(0, y - CABIN_Y0) * TUMBLE);
    d = smin(d, smax(cS, cP, RC), RU);
    // 前保桿：中間的橢圓進氣口（往後挖）
    if (x > 1.9) {
      const win = box2(az, y - 0.385, 0.49, 0.040, 0.038);
      d = smax(d, -Math.max(win, -(dP + 0.012)), 0.01);
    }
    // 前輪後面、葉子板上的直立導風凹槽
    if (x > 0.50 && x < 0.82 && y > 0.22 && y < 0.60) {
      const v = box2(x - 0.656, y - 0.405, 0.068, 0.11, 0.035);
      d = smax(d, -Math.max(v, -(dP + 0.018)), 0.012);
    }
    // 輪拱：外緣一小圈翻邊（沿著車身表面的一條細管）、挖洞
    const d0 = d;
    for (const xa of [RX7.xr, RX7.xf]) {
      if (y > 0.16 && Math.abs(x - xa) < 0.6 && az > 0.6) {
        const q = Math.hypot(x - xa, y - arch.y) - (arch.R + 0.006);
        d = smin(d, Math.hypot(q, d0 + 0.012) - 0.02, 0.03);
      }
    }
    for (const xa of [RX7.xr, RX7.xf]) {
      const dc = Math.hypot(x - xa, y - arch.y) - arch.R;
      d = smax(d, -smax(dc, arch.zIn - az, 0.03), 0.02);
    }
    return d;
  };
}
