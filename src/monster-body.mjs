// 後輪拱（側面，挖到 |z| > ARCH_ZIN，裡面剩一片黑色的內葉子板）
export const REAR_ARCH = [
  [-2.25, 1.0, 0], [-2.24, 1.70, 1], [-2.21, 2.08, 1], [-2.12, 2.24, 1], [-1.92, 2.285, 1], [-1.67, 2.225, 1], [-1.38, 2.115, 1],
  [-1.10, 1.975, 1], [-0.88, 1.80, 1], [-0.74, 1.62, 1], [-0.62, 1.44, 1], [-0.55, 1.0, 0],
];
export const ARCH_ZIN = 0.56;

const CROWN = [[-2.6, 0.02], [0.9, 0.02], [1.2, 0.05], [2.7, 0.06]]; // 中間比兩邊高多少（z＝1 的地方）
const CAB_CROWN = 0.035;
function lerpTable(t, x) {
  if (x <= t[0][0]) return t[0][1];
  for (let i = 1; i < t.length; i++) if (x <= t[i][0]) { const a = t[i - 1], b = t[i], u = (x - a[0]) / (b[0] - a[0]), s = u * u * (3 - 2 * u); return a[1] + (b[1] - a[1]) * s; }
  return t[t.length - 1][1];
}

// 車殼的 SDF（公尺）
export function makeRealSDF() {
  const res = 0.006;
  const side = sdf2d(curve(LOWER_SIDE), -2.7, 1.2, 2.9, 2.7, res);
  const cabS = sdf2d(curve(CAB_SIDE), -2.7, 2.1, 1.4, 3.15, res);
  const plan = sdf2d(curve(PLAN), -2.7, -1.2, 2.9, 1.2, res);
  const cabP = sdf2d(curve(CAB_PLAN), -2.7, -1.2, 1.4, 1.2, res);
  const front = sdf2d(curve(FRONT), -1.2, 1.2, 1.2, 2.7, res);
  const arch = sdf2d(curve(REAR_ARCH), -2.5, 0.8, -0.3, 2.5, res);
  const R1 = 0.07, R2 = 0.06, RC = 0.035, RU = 0.03;
  return function f(x, y, z) {
    const az = Math.abs(z), zz = az;
    const dS = look(side, x, y + lerpTable(CROWN, x) * zz * zz);
    const dP = look(plan, x, az);
    const dF = look(front, az, y);
    let d = smax(smax(dS, dP, R1), dF, R2);
    // 車艙＋貨斗蓋
    const cS = look(cabS, x, y + CAB_CROWN * (az / 0.95) ** 2);
    const cP = look(cabP, x, az + Math.max(0, y - CAB_Y0) * TUMBLE);
    d = smin(d, smax(cS, cP, RC), RU);
    // 後輪拱：外面挖到 ARCH_ZIN
    const a = smax(look(arch, x, y), ARCH_ZIN - az, 0.03);
    d = smax(d, -a, 0.03);
    return d;
  };
}
// 網格用的 SDF（遮罩座標）
export function makeSDF() {
  const F = makeRealSDF();
  return (xm, ym, zm) => F(xm / S + X0, ym / S + Y0, zm / S) * S;
}
