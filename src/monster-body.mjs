// 座標（公尺，靜止時）：x 往車頭、y 往上（地面 0）、z 往車的右側；軸距 3.80（前軸 +1.90、後軸 −1.90），輪距 2.72，66 吋輪胎（半徑 0.84）。
// 車殼從 y≈1.45 到 3.0，照 Nick 2026-09-28 傳的粉紅色怪獸卡車照片量的（相機從四個輪框圈、輪胎上下緣、水箱罩四角、車窗下緣反推，monster3d/fit2.mjs）。
// 遮罩（masks.js 的 shader）只認得 x −2.35～2.35、y 0～1.4、z −1～1 的車身，所以網格存成「遮罩座標」：
//   xm = (x − MONSTER_X0)·MONSTER_S、ym = (y − MONSTER_Y0)·MONSTER_S、zm = z·MONSTER_S；monster-spec.js 再把網格放大、抬高回公尺。
import { curve, sdf2d, look, smin, smax } from './body.mjs';

export const MONSTER = { S: 0.8, X0: 0.1, Y0: 1.38, xf: 1.90, xr: -1.90, R: 0.84, T: 1.36 };
const { S, X0, Y0 } = MONSTER;
// 遮罩座標的範圍：[x0, y0, x1, y1, zmax]
export const BOUNDS = [(-2.62 - X0) * S, 0.0, (2.82 - X0) * S, (3.08 - Y0) * S, 1.08 * S];
const mirrorZ = (r) => [...r, ...r.slice(1, -1).reverse().map(([x, z, s]) => [x, -z, s])];

// 下半身側面（中線）：車尾下 → 底部（後輪拱另外挖）→ 車門前緣 → 前面挖空（葉子板下緣）→ 保桿 → 水箱罩 → 引擎蓋 → 腰線 → 車尾
