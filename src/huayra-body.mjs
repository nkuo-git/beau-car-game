export const NOSE_X = 1.5;
export function makeSDF(opt = {}) {
  const res = 0.005;
  const side = sdf2d(curve(LOWER_SIDE), -2.45, -0.05, 2.45, 1.2, res);
  const cabS = sdf2d(curve(CABIN_SIDE), -2.45, 0.45, 1.5, 1.3, res);
  const plan = sdf2d(curve(PLAN), -2.45, -1.15, 2.45, 1.15, res);
  const cabP = sdf2d(curve(CABIN_PLAN), -2.45, -1.0, 1.5, 1.0, res);
  const front = sdf2d(curve(FRONT), -1.15, -0.05, 1.15, 1.2, res);
  const R1 = opt.R1 ?? 0.08, R2 = opt.R2 ?? 0.08, RC = opt.RC ?? 0.12, RU = opt.RU ?? 0.05;
  const AR = [[HUAYRA.xr, HUAYRA.RR, 0.395, 0.62], [HUAYRA.xf, HUAYRA.RF, 0.37, 0.64]];
  return function f(x, y, z) {
    const az = Math.abs(z);
    const rz = lerpTable(RIDGE, x);
    const val = lerpTable(VALLEY, x) * (1 - sstep(rz - 0.30, rz - 0.02, az));
    const deck = lerpTable(DECK, x) * (1 - sstep(0.62, 0.80, az));
    const drop = lerpTable(SIDE_DROP, x) * sstep(0.78, 1.03, az) ** 1.5;
    const dS = look(side, x, y + val + deck + drop);
    const dP = look(plan, x, az);
    const dF = look(front, az, y);
    let d = smax(dS, dP, R1);
    d = smax(d, dF, R2);
    // 車艙＋中間的脊
    const zc = az / 0.80;
    const cS = look(cabS, x, y + (0.10 + 0.06 * sstep(-0.6, -1.6, x)) * zc * zc);
    const cP = look(cabP, x, az + Math.max(0, y - CABIN_Y0) * TUMBLE);
    d = smin(d, smax(cS, cP, RC), RU);
    // 車尾下面：兩組尾燈中間一整片往內凹（黑網、車牌、擴散器）
    if (x < -1.9) d = smax(d, -rbox(x + 2.42, y - 0.40, az, 0.22, 0.26, 0.60 + Math.max(0, 0.30 - y) * 0.3, 0.07), 0.03);
    // 車頭下面的大進氣口（黑網）
    if (x > 1.9) d = smax(d, -rbox(x - 2.40, y - 0.245, az, 0.16, 0.095, 0.70, 0.05), 0.02);
    // 輪拱：挖洞
    for (const [xa, R, ar, zIn] of AR) {
      const dc = Math.hypot(x - xa, y - R) - ar;
      d = smax(d, -smax(dc, zIn - az, 0.03), 0.025);
    }
    return d;
  };
}
