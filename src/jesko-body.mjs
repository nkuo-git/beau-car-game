function lerpTable(t, x) {
  if (x <= t[0][0]) return t[0][1];
  for (let i = 1; i < t.length; i++) if (x <= t[i][0]) { const a = t[i - 1], b = t[i], u = (x - a[0]) / (b[0] - a[0]), s = u * u * (3 - 2 * u); return a[1] + (b[1] - a[1]) * s; }
  return t[t.length - 1][1];
}
const sstep = (a, b, x) => { const t = Math.max(0, Math.min(1, (x - a) / (b - a))); return t * t * (3 - 2 * t); };
const gau = (a, m, s) => Math.exp(-(((a - m) / s) ** 2));
// 中間引擎蓋比兩邊葉子板低多少（x → 深度）
const VALLEY = [[-2.3, 0.07], [-1.9, 0.09], [-1.3, 0.09], [-0.9, 0.03], [-0.5, 0.0], [0.85, 0.0], [1.10, 0.03], [1.40, 0.05], [1.80, 0.05], [2.10, 0.03], [2.30, 0.0]];
// 兩側往下圓掉多少
const SIDE_DROP = [[-2.4, 0.10], [-1.8, 0.08], [-1.35, 0.07], [-0.9, 0.06], [0.0, 0.05], [0.9, 0.06], [1.4, 0.08], [2.0, 0.10], [2.4, 0.12]];

export const NOSE_X = 1.5;
export function makeSDF(opt = {}) {
  const res = 0.005;
  const side = sdf2d(curve(LOWER_SIDE), -2.45, -0.05, 2.45, 1.2, res);
  const cabS = sdf2d(curve(CABIN_SIDE), -2.45, 0.5, 1.4, 1.35, res);
  const plan = sdf2d(curve(PLAN), -2.45, -1.15, 2.45, 1.15, res);
  const cabP = sdf2d(curve(CABIN_PLAN), -2.45, -1.0, 1.4, 1.0, res);
  const front = sdf2d(curve(FRONT), -1.15, -0.05, 1.15, 1.2, res);
  const R1 = opt.R1 ?? 0.08, R2 = opt.R2 ?? 0.08, RC = opt.RC ?? 0.12, RU = opt.RU ?? 0.05;
  const XF = JESKO.xf, XR = JESKO.xr;
  const archF = { R: 0.375, zIn: 0.62 }, archR = { R: 0.395, zIn: 0.62 };
  return function f(x, y, z) {
    const az = Math.abs(z);
    const zz = az / 1.0;
    const cr = lerpTable(VALLEY, x) * (1 - sstep(0.30, 0.74, az)) + lerpTable(SIDE_DROP, x) * sstep(0.74, 1.02, az) ** 1.5;
    const dS = look(side, x, y + cr);
    const dP = look(plan, x, az);
    const dF = look(front, az, y);
    let d = smax(dS, dP, R1);
    d = smax(d, dF, R2);
    // 車艙
    const zc = az / 0.86;
    const cS = look(cabS, x, y + (0.16 + 0.14 * sstep(0.4, -0.5, x)) * zc * zc);
    const cP = look(cabP, x, az + Math.max(0, y - CABIN_Y0) * TUMBLE);
    d = smin(d, smax(cS, cP, RC), RU);
    // 側面大進氣口（後輪前面）：往內挖
    if (x > -1.15 && x < -0.20 && y > 0.18) {
      const win = rbox(x + 0.68, y - 0.45, az - 1.02, 0.33, 0.22, 0.14, 0.08);
      d = smax(d, -win, 0.04);
    }
    // 車尾大開口：鴨尾下面整片往內凹（下緣比較寬）
    if (x < -1.9) d = smax(d, -rbox(x + 2.47, y - 0.38, az, 0.27, 0.265, 0.74 + Math.max(0, 0.30 - y) * 0.35, 0.09), 0.03);
    // 引擎蓋中間的大散熱出風口（往下凹，中間留一條隔板）
    if (x > 1.1 && x < 2.05 && az < 0.6) {
      const v = rbox(x - 1.58, y - 0.80, az - 0.255, 0.36, 0.12, 0.215, 0.06);
      d = smax(d, -v, 0.02);
    }
    // 前保桿下面的大進氣口
    if (x > 1.8) d = smax(d, -rbox(x - 2.34, y - 0.21, az, 0.14, 0.075, 0.78, 0.04), 0.02);
    // 輪拱：外緣一圈、挖洞
    for (const [xa, R, a, zl] of [[XR, JESKO.RR, archR, 1.0], [XF, JESKO.RF, archF, 0.98]]) {
      const dc = Math.hypot(x - xa, y - R) - a.R;
      d = smax(d, -smax(dc, a.zIn - az, 0.03), 0.025);
    }
    return d;
  };
}
