// 3D Mazda RX-7（FD3S）的表面細節（投影貼圖），做法跟 gtr-look.js 一樣。
// 位置都是照四張紅色 FD 照片量的：照片上的點從擬合好的相機打光線到車身（rx73d/hit.mjs），得到車身上的 (x, y, z)。
// 車頭照 1994 年那台（照片 1：大燈蓋關著、保桿上兩個長條小燈、中間橢圓進氣口），車尾照照片 3、4（燻黑尾燈條）。
// 沒有任何廠牌字、徽章：車頭、車尾原本有徽章的地方都是素的車漆。
import { BOX, layers, poly, smooth, line, both, frit, canvas } from './masks.js';

export const RX7_LOOK = (() => {
  const M = (pts) => pts.map(([u, y]) => [-u, y]); // 左右鏡射
  const rrect = (g, x0, y0, x1, y1, r) => { g.beginPath(); g.roundRect(x0, y0, x1 - x0, y1 - y0, r); };
  const circle = (g, x, y, r) => { g.beginPath(); g.arc(x, y, r, 0, Math.PI * 2); };
  const ellipse = (g, x, y, rx, ry, a = 0) => { g.beginPath(); g.ellipse(x, y, rx, ry, a, 0, Math.PI * 2); };
  const both2 = (pts, fn) => { fn(pts); fn(M(pts)); };

  // ---- 側面（x, y）----
  // 側窗：A 柱後緣 → 車頂邊 → 後端圓圓地往下 → 腰線（照片 1、3 量的），後面一小塊三角窗（黑色分隔條）
  const DLO = [[0.30, 0.842], [0.16, 0.93], [0.0, 1.03], [-0.12, 1.11], [-0.20, 1.158], [-0.28, 1.181], [-0.42, 1.19], [-0.56, 1.182],
    [-0.66, 1.165], [-0.73, 1.12], [-0.755, 1.05], [-0.75, 0.97], [-0.72, 0.895], [-0.69, 0.868], [-0.40, 0.862], [-0.10, 0.856], [0.20, 0.846]];
  const DIVIDER = [[-0.575, 1.19], [-0.605, 1.19], [-0.635, 0.86], [-0.605, 0.86]];
  // 後擋（大泡泡玻璃）包到側面的那段：前緣從車頂斜斜往後下到腰線，下緣沿著後葉子板上面
  const HATCH = [[-0.70, 1.26], [-0.72, 1.175], [-0.80, 1.09], [-0.90, 1.0], [-0.99, 0.93], [-1.07, 0.885], [-1.27, 0.893],
    [-1.46, 0.909], [-1.66, 0.924], [-1.84, 0.942], [-1.93, 0.97], [-1.95, 1.10], [-1.95, 1.26]];
  const DOOR_F = [[0.345, 0.835], [0.40, 0.76], [0.418, 0.70], [0.43, 0.524], [0.445, 0.40], [0.461, 0.266]];
  const DOOR_R = [[-0.735, 0.85], [-0.80, 0.75], [-0.815, 0.692], [-0.79, 0.60], [-0.725, 0.508], [-0.649, 0.377]];
  const DOOR_B = [[0.461, 0.266], [0.20, 0.278], [-0.177, 0.303], [-0.45, 0.35], [-0.649, 0.377]];
  const VENT = [[0.585, 0.50], [0.60, 0.515], [0.64, 0.52], [0.70, 0.51], [0.725, 0.47], [0.728, 0.33], [0.71, 0.30], [0.66, 0.29], [0.60, 0.30], [0.585, 0.33]];
  function side() {
    return layers(BOX.side, [
      (g) => { smooth(g, DLO); g.fill(); poly(g, HATCH); g.fill(); },
      (g) => { // 黑色
        g.lineJoin = 'round'; g.lineWidth = 0.022; smooth(g, DLO); g.stroke(); // 窗框膠條
        poly(g, DIVIDER); g.fill();
        g.lineWidth = 0.016; line(g, HATCH.slice(1, 11), 0.016); // 後擋的黑邊
        g.save(); smooth(g, VENT); g.clip(); rrect(g, 0.585, 0.30, 0.62, 0.51, 0.015); g.fill(); g.restore(); // 導風口後面的開口
        line(g, [[1.55, 0.17], [1.80, 0.18], [2.15, 0.19]], 0.04); // 前保桿最下面（下巴後面）
        line(g, [[-1.62, 0.29], [-1.85, 0.30], [-2.15, 0.31]], 0.04); // 後保桿下緣
      },
      (g) => { // 縫
        line(g, DOOR_F, 0.005); line(g, DOOR_R, 0.005); line(g, DOOR_B, 0.004);
        g.lineWidth = 0.004; rrect(g, -0.66, 0.785, -0.50, 0.812, 0.012); g.stroke(); // 門把
        g.lineWidth = 0.005; circle(g, -1.61, 0.645, 0.062); g.stroke(); // 油箱蓋
        g.lineWidth = 0.004; smooth(g, VENT); g.stroke();
        line(g, [[1.75, 0.65], [1.73, 0.628], [1.692, 0.588], [1.646, 0.536], [1.60, 0.45], [1.57, 0.37]], 0.004); // 前保桿和葉子板
        line(g, [[-1.87, 0.72], [-1.82, 0.60], [-1.74, 0.46], [-1.64, 0.36]], 0.004); // 後保桿和葉子板
      },
      null,
    ]);
  }

  // ---- 正面（u＝|z|，左右鏡射畫；y）----
  // 保桿上的長條小燈（透明燈殼＋鍍鉻反射罩），中間橢圓進氣口，下面兩個小進氣口，最下面黑色下巴
  const LAMP = [[0.545, 0.49], [0.56, 0.508], [0.62, 0.517], [0.70, 0.514], [0.75, 0.504], [0.765, 0.49], [0.752, 0.474], [0.70, 0.464], [0.62, 0.461], [0.56, 0.470]];
  const MOUTH = [[0.0, 0.432], [0.30, 0.43], [0.45, 0.423], [0.505, 0.405], [0.52, 0.383], [0.505, 0.357], [0.45, 0.343], [0.30, 0.338], [0.0, 0.337]];
  const SIDEIN = [[0.60, 0.372], [0.70, 0.374], [0.775, 0.368], [0.79, 0.345], [0.775, 0.322], [0.70, 0.315], [0.62, 0.318], [0.595, 0.345]];
  const MARKER = [[0.815, 0.452], [0.85, 0.452], [0.85, 0.398], [0.815, 0.398]]; // 保桿側面的橘色方向燈
  function front() {
    const MO = MOUTH.concat(M(MOUTH).slice(1, -1).reverse());
    return layers(BOX.front, [
      (g) => { both2(LAMP, (P) => { smooth(g, P); g.fill(); }); }, // R：小燈
      (g) => { // G：黑色
        smooth(g, MO); g.fill();
        both2(SIDEIN, (P) => { smooth(g, P); g.fill(); });
        g.lineWidth = 0.007; both2(LAMP, (P) => { smooth(g, P); g.stroke(); });
        g.fillRect(-1, 0, 2, 0.20); // 保桿最下面（下巴後面）
      },
      (g) => { both2(MARKER, (P) => { poly(g, P); g.fill(); }); }, // B：橘色
      (g) => { // A：燈裡面的條紋、進氣口的網子
        for (const s of [1, -1]) {
          g.save(); smooth(g, LAMP.map(([u, y]) => [u * s, y])); g.clip();
          g.fillStyle = 'rgb(190,190,190)';
          for (let u = 0.57; u < 0.76; u += 0.016) poly(g, [[u * s, 0.46], [(u + 0.006) * s, 0.46], [(u + 0.013) * s, 0.52], [(u + 0.007) * s, 0.52]]), g.fill();
          g.restore(); g.fillStyle = '#fff';
        }
        g.save(); smooth(g, MO); g.clip(); // 進氣口裡面兩條橫桿
        line(g, [[-0.6, 0.385], [0.6, 0.385]], 0.008);
        g.restore();
      },
    ]);
  }

  // ---- 後面（u＝z，y）：燻黑尾燈條（兩端圓圓的燈座、中間細條連起來），每邊三顆圓燈；保桿上紅色反光條＋白色倒車燈 ----
  const TAIL = [[0.0, 0.858], [0.30, 0.86], [0.50, 0.857], [0.62, 0.85], [0.70, 0.838], [0.75, 0.818], [0.785, 0.787], [0.80, 0.752],
    [0.792, 0.72], [0.755, 0.70], [0.65, 0.702], [0.535, 0.712], [0.475, 0.735], [0.452, 0.77], [0.435, 0.80], [0.39, 0.812], [0.0, 0.814]];
  const RINGS = [[0.515, 0.765, 0.034], [0.612, 0.768, 0.042], [0.712, 0.766, 0.042]];
  const REFL = [[0.43, 0.452], [0.66, 0.49], [0.675, 0.505], [0.665, 0.55], [0.43, 0.518], [0.42, 0.485]];
  function rear() {
    const T = TAIL.concat(M(TAIL).slice(1, -1).reverse());
    return layers(BOX.rear, [
      (g) => { // R：紅燈（圓燈、反光條）
        for (const s of [1, -1]) for (const [u, y, r] of RINGS) { circle(g, u * s, y, r); g.fill(); }
        both2(REFL, (P) => { smooth(g, P); g.fill(); });
      },
      (g) => { // G：黑色（燈條挖掉圓燈）、車牌、下面
        g.save(); smooth(g, T); g.fill();
        g.globalCompositeOperation = 'destination-out';
        for (const s of [1, -1]) for (const [u, y, r] of RINGS) { circle(g, u * s, y, r - 0.006); g.fill(); }
        g.restore(); g.fillStyle = '#fff';
        rrect(g, -0.165, 0.33, 0.165, 0.495, 0.012); g.fill(); // 車牌（素的）
        g.fillRect(-1, 0, 2, 0.265); // 保桿下緣
      },
      (g) => { // B：倒車燈（反光條靠中間那段）
        for (const s of [1, -1]) { g.save(); smooth(g, REFL.map(([u, y]) => [u * s, y])); g.clip(); g.fillRect(s > 0 ? 0.40 : -0.49, 0.4, 0.09, 0.2); g.restore(); }
      },
      (g) => { // A：縫
        line(g, [[-0.66, 0.885], [0.66, 0.885]], 0.004); // 鴨尾下緣（掀背門的縫）
        line(g, [[-0.82, 0.69], [-0.45, 0.70], [0.45, 0.70], [0.82, 0.69]], 0.004); // 後保桿上緣
        g.lineWidth = 0.004; rrect(g, -0.18, 0.315, 0.18, 0.51, 0.02); g.stroke(); // 車牌凹槽
      },
    ]);
  }

  // ---- 上面（x, z）：前擋、後擋（大泡泡）、雨刷飾板、引擎蓋和大燈蓋的縫 ----
  const WS = [[0.605, 0], [0.60, 0.30], [0.565, 0.50], [0.48, 0.63], [0.37, 0.705], [0.25, 0.665], [0.10, 0.605], [-0.04, 0.54],
    [-0.15, 0.48], [-0.195, 0.42], [-0.212, 0.25], [-0.218, 0]];
  const BL = [[-0.80, 0], [-0.81, 0.25], [-0.84, 0.40], [-0.90, 0.53], [-1.00, 0.63], [-1.07, 0.675], [-1.27, 0.645], [-1.46, 0.607],
    [-1.66, 0.566], [-1.84, 0.516], [-1.905, 0.40], [-1.925, 0.20], [-1.93, 0]];
  const COWL = [[0.665, 0], [0.66, 0.30], [0.63, 0.52], [0.56, 0.65], [0.47, 0.70], [0.46, 0.64], [0.545, 0.53], [0.585, 0.30], [0.59, 0]];
  const LID = [[1.923, 0.617], [1.876, 0.699], [1.782, 0.761], [1.66, 0.795], [1.567, 0.769], [1.534, 0.71], [1.57, 0.64], [1.64, 0.55],
    [1.75, 0.525], [1.86, 0.565]];
  // 側窗上緣靠近車頂邊（法線朝上的那段）：從上面看的範圍（A 柱後緣 → 車頂邊 → 後端），外側只到 z 0.66，再外面交給側視圖
  const TOPDLO = [[0.22, 0.66], [0.05, 0.60], [-0.10, 0.545], [-0.20, 0.505], [-0.30, 0.49], [-0.45, 0.488], [-0.58, 0.50], [-0.67, 0.53], [-0.72, 0.58], [-0.74, 0.66]];
  function top() {
    return layers(BOX.top, [
      null,
      (g) => {
        frit(g, both(WS), 0.03, [-0.26, -0.15], [0.56, 0.64]);
        frit(g, both(BL), 0.025, [-0.86, -0.79], [-1.96, -1.88]);
        smooth(g, both(COWL)); g.fill();
      },
      (g) => {
        g.lineWidth = 0.005; for (const s of [1, -1]) { smooth(g, LID.map(([x, z]) => [x, z * s])); g.stroke(); }
        // 引擎蓋：前緣（大燈蓋中間）＋兩邊沿著葉子板內側往後到雨刷飾板
        line(g, [[0.67, 0.64], [1.10, 0.655], [1.45, 0.64], [1.57, 0.62], [1.70, 0.535], [1.83, 0.50], [1.875, 0.40], [1.868, 0.0],
          [1.875, -0.40], [1.83, -0.50], [1.70, -0.535], [1.57, -0.62], [1.45, -0.64], [1.10, -0.655], [0.67, -0.64]], 0.005);
        // 掀背門：後擋外面一圈
        line(g, [[-0.78, 0.0], [-0.79, 0.30], [-0.84, 0.47], [-0.96, 0.63], [-1.08, 0.70]], 0.004);
        line(g, [[-0.78, -0.0], [-0.79, -0.30], [-0.84, -0.47], [-0.96, -0.63], [-1.08, -0.70]], 0.004);
      },
      (g) => {
        smooth(g, both(WS)); g.fill(); smooth(g, both(BL)); g.fill();
        for (const s of [1, -1]) { smooth(g, TOPDLO.map(([x, z]) => [x, z * s])); g.fill(); } // 側窗上半部（朝上一點的地方看俯視圖）
      },
    ]);
  }

  // ---- 拉花：轉子引擎的圓三角形（勒洛三角形）圖案＋一條細線，在車門下半部 ----
  function reuleaux(g, cx, cy, r, a0) { // 勒洛三角形：三個角各畫一段圓弧
    const P = [0, 1, 2].map((i) => [cx + r * Math.cos(a0 + (i * 2 * Math.PI) / 3), cy + r * Math.sin(a0 + (i * 2 * Math.PI) / 3)]);
    const s = r * Math.sqrt(3);
    g.beginPath();
    for (let i = 0; i < 3; i++) {
      const c = P[i], a = P[(i + 1) % 3], b = P[(i + 2) % 3];
      const t0 = Math.atan2(a[1] - c[1], a[0] - c[0]), t1 = Math.atan2(b[1] - c[1], b[0] - c[0]);
      if (i === 0) g.moveTo(a[0], a[1]);
      g.arc(c[0], c[1], s, t0, t1 < t0 ? t1 + Math.PI * 2 : t1, false);
    }
    g.closePath();
  }
  function livery(sd, style = 'rotor') {
    const { c, g } = canvas(BOX.side);
    g.clearRect(-3, -1, 6, 3);
    if (style !== 'rotor') return c;
    // 一條往後越來越細的白線（從前輪後面到後輪前面）
    g.fillStyle = '#f2f3f5';
    poly(g, [[0.80, 0.37], [-0.95, 0.43], [-0.95, 0.418], [0.80, 0.345]]); g.fill();
    g.fillStyle = '#16171a';
    poly(g, [[0.80, 0.338], [-0.95, 0.414], [-0.95, 0.408], [0.80, 0.326]]); g.fill();
    // 三個圓三角形（尖的那頭朝上），前面大、往後越來越小，一個比一個轉一點
    const R = [[0.16, 0.565, 0.12, Math.PI / 2, '#f2f3f5'], [-0.14, 0.58, 0.09, Math.PI / 2 + 0.4, '#f2f3f5'], [-0.38, 0.59, 0.065, Math.PI / 2 + 0.8, '#f2f3f5']];
    for (const [x, y, r, a, col] of R) {
      g.fillStyle = '#16171a'; reuleaux(g, x, y, r + 0.012, (sd < 0 ? Math.PI - a : a)); g.fill();
      g.fillStyle = col; reuleaux(g, x, y, r, (sd < 0 ? Math.PI - a : a)); g.fill();
    }
    return c;
  }
  function frontLivery() { const { c, g } = canvas(BOX.front); g.clearRect(-2, -1, 4, 3); return c; }

  return {
    side, rear, top,
    fronts: { base: front },
    livery, frontLivery,
    livDefault: 0,
    nose: () => 'base',
    U: { uXr: -1.215, uXf: 1.21, uFx: [1.50, 1.56], uRx: [-1.72, -1.80], uWell: [0.316, 0.35, 0.84], uGlassY: 0.84 },
  };
})();
