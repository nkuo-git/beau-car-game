const CROWN = [[-2.4, 0.05], [-1.6, 0.05], [-1.0, 0.055], [0.8, 0.05], [1.4, 0.045], [2.4, 0.05]];
const CABIN_CROWN = 0.05;
function lerpTable(t, x) {
  if (x <= t[0][0]) return t[0][1];
  for (let i = 1; i < t.length; i++) if (x <= t[i][0]) { const a = t[i - 1], b = t[i], u = (x - a[0]) / (b[0] - a[0]), s = u * u * (3 - 2 * u); return a[1] + (b[1] - a[1]) * s; }
  return t[t.length - 1][1];
}
const sstep = (a, b, x) => { const t = Math.max(0, Math.min(1, (x - a) / (b - a))); return t * t * (3 - 2 * t); };

export function makeSDF(opt = {}) {
  const res = 0.005;
  const side = sdf2d(curve(LOWER_SIDE), -2.4, -0.05, 2.4, 1.2, res);
  const cabS = sdf2d(curve(CABIN_SIDE), -2.0, 0.7, 1.3, 1.55, res);
  const plan = sdf2d(curve(PLAN), -2.4, -1.1, 2.4, 1.1, res);
  const cabP = sdf2d(curve(CABIN_PLAN), -2.0, -1.0, 1.3, 1.0, res);
  const front = sdf2d(curve(FRONT), -1.1, -0.05, 1.1, 1.2, res);
  const R1 = opt.R1 ?? 0.09, R2 = opt.R2 ?? 0.08, RC = opt.RC ?? 0.12, RU = opt.RU ?? 0.05;
  const arch = { R: 0.358, y: EVO.R, zIn: 0.62 };
  return function f(x, y, z) {
    const az = Math.abs(z);
    const zz = az / 0.9;
    const cr = lerpTable(CROWN, x) * zz * zz;
    const dS = look(side, x, y + cr);
    const dP = look(plan, x, az);
    const dF = look(front, az, y);
    let d = smax(dS, dP, R1);
    d = smax(d, dF, R2);
    // 前後保桿的下緣：兩個角往上收（後面中間是黑色擴散器，比較低）
    if (x < -1.6) d = smax(d, 0.27 + 0.10 * sstep(0.35, 0.85, az) * sstep(-1.75, -2.0, x) - y, 0.04);
    if (x > 1.75) d = smax(d, 0.15 + 0.07 * sstep(0.45, 0.85, az) * sstep(1.85, 2.05, x) - y, 0.03);
    // 車艙
    const zc = az / 0.75;
    const cS = look(cabS, x, y + CABIN_CROWN * zc * zc);
    const cP = look(cabP, x, az + Math.max(0, y - CABIN_Y0) * TUMBLE);
    d = smin(d, smax(cS, cP, RC), RU);
    // 引擎蓋中間的大散熱口：往下挖一個梯形的凹槽（後面寬、前面窄；裡面的網子畫在貼圖上）
    if (x > 1.35 && x < 1.75 && az < 0.5) {
      const hood = 0.858 - (x - 1.40) * 0.184;
      const hw = 0.41 - (x - 1.43) * 0.48;
      const rec = smax(Math.abs(x - 1.555) - 0.125, az - hw, 0.03);
      d = smax(d, -smax(rec, Math.abs(y - hood) - 0.022, 0.01), 0.008);
    }
    // 前保桿的開口：沿著保桿表面往裡挖（上面的水箱罩、下面的大進氣口、兩邊的導風口）
    if (x > 1.85 && y < 0.75) {
      const sk = dP + 0.004 * 0; // 到保桿表面（俯視）的距離
      const hole = (w, depth, k) => d = smax(d, -smax(w, -(sk + depth), 0.006), k);
      hole(Math.max(Math.abs(y - 0.385) - 0.075, az - 0.38), 0.035, 0.012);          // 下面的大進氣口（中冷器）
      hole(Math.max(Math.abs(y - 0.395) - 0.05, Math.abs(az - 0.668) - 0.09), 0.02, 0.01); // 兩邊的導風口
      hole(Math.max(Math.abs(y - 0.64) - 0.045 + (az > 0.3 ? 0 : 0), az - (0.50 - (0.69 - y) * 0.3)), 0.015, 0.008); // 上面的水箱罩
    }
    // 後保桿下面的黑色擴散器：往裡面縮 4 公分（排氣管從右邊伸出來）
    if (x < -1.95 && y < 0.5) {
      const top = 0.445 - 0.08 * sstep(0.55, 0.78, az);
      const box = smax(y - top, az - 0.80, 0.03);
      d = smax(d, -smax(box, x + 2.185, 0.012), 0.012);
    }
    // 輪拱：外緣一圈（外擴的葉子板翻邊）、挖洞
    for (const xa of [EVO.xr, EVO.xf]) {
      if (y > 0.16 && Math.abs(x - xa) < 0.6) {
        const q = Math.hypot(x - xa, y - arch.y) - (arch.R + 0.006);
        d = smin(d, Math.hypot(q, az - 0.866) - 0.022, 0.04);
      }
    }
    for (const xa of [EVO.xr, EVO.xf]) {
      const dc = Math.hypot(x - xa, y - arch.y) - arch.R;
      d = smax(d, -smax(dc, arch.zIn - az, 0.03), 0.02);
    }
    return d;
  };
}
