// 沙灘車（Z2，自己編的四輪沙灘車＝ATV，不是哪個牌子）的塑膠車身 SDF：前後兩個大葉子板（包住輪子上面）、中間窄窄的油箱蓋＋側蓋
// 做法跟 k2-body.mjs 一樣：側面輪廓拉成柱體、跟俯視的寬度取交集＋修圓，再挖輪拱、大燈、水箱罩、尾燈的凹槽，最後 make-car.mjs 切網格。
// 座椅、手把、腳踏板、前後保桿、懸吊（A 臂、避震器）、引擎、排氣管、車架都是另外的零件（z2-spec.js）。
// 座標（公尺，原廠高度）：x 往車頭、y 往上（地面 0）、z 往車的右側；軸距 1.26（前軸 +0.62、後軸 −0.64），輪距前 0.95、後 0.93，輪胎半徑 0.32（25 吋）。
// 尺寸：塑膠殼長 2.01（加前後保桿 2.12）、寬 1.20、葉子板頂 0.81、油箱蓋頂 0.905（座椅 0.88、手把 1.07）；比遮罩的範圍小，不用縮放（遮罩座標＝公尺）。
import { curve, sdf2d, look, smin, smax } from './body.mjs';

export const Z2 = { xf: 0.62, xr: -0.64, R: 0.32, TF: 0.475, TR: 0.465 };
// 範圍：[x0, y0, x1, y1, zmax]（四周至少留 2 格：surface nets 最外面那一格不出面）
export const BOUNDS = [-1.07, 0.40, 1.08, 0.97, 0.67];

const sstep = (a, b, x) => { const t = Math.max(0, Math.min(1, (x - a) / (b - a))); return t * t * (3 - 2 * t); };
const box2 = (px, py, hx, hy, r) => { const qx = Math.abs(px) - hx + r, qy = Math.abs(py) - hy + r; return Math.hypot(Math.max(qx, 0), Math.max(qy, 0)) + Math.min(Math.max(qx, qy), 0) - r; };

// 前面中間（車頭＋前置物台，|z| < 0.36）的側面：後面接油箱蓋 → 平平的置物台 → 圓圓的車頭（水箱罩）→ 車頭下面 → 中間一條往後接腳踏板
const FRONT_SIDE = [
  [0.235, 0.47, 0], [0.245, 0.72, 1], [0.30, 0.775, 1], [0.42, 0.79, 1], [0.70, 0.782, 1], [0.86, 0.768, 1],
  [0.95, 0.738, 1], [0.992, 0.69, 1], [1.004, 0.60, 1], [0.99, 0.522, 1], [0.955, 0.486, 0],
];
// 後面中間（後置物台＋車尾，|z| < 0.38）的側面
const REAR_SIDE = [
  [-0.255, 0.47, 0], [-0.265, 0.735, 1], [-0.31, 0.788, 1], [-0.42, 0.80, 1], [-0.70, 0.802, 1], [-0.90, 0.795, 1],
  [-0.966, 0.772, 1], [-0.996, 0.716, 1], [-1.002, 0.62, 1], [-0.99, 0.54, 1], [-0.955, 0.49, 0],
];
// 中間（油箱蓋＋座椅下面的側蓋）：前面接前置物台 → 油箱蓋最高 → 往下到座椅前緣 → 座椅底下平的 → 後面接後置物台
const CENTER_SIDE = [
  [0.47, 0.52, 0], [0.47, 0.79, 1], [0.43, 0.876, 1], [0.36, 0.905, 1], [0.24, 0.886, 1], [0.13, 0.837, 1], [0.04, 0.809, 1],
  [-0.42, 0.80, 0], [-0.42, 0.52, 0],
];
// 葉子板（輪子上面鼓起來的那一塊，|z| 0.30～0.60）：側面是橢圓（圓心＝輪心，往上 0.52、往前 af、往後 ar），下面切平（前 yf、後 yr）、靠腳踏板那頭切直的（xc）
export const Z2_FENDERS = [
  { x: 0.62, af: 0.43, ar: 0.47, b: 0.52, yf: 0.56, yr: 0.47, xc: 0.235, side: 1 }, // 前：後面切在 x 0.235（腳踏板前面的擋板）
  { x: -0.64, af: 0.47, ar: 0.42, b: 0.52, yf: 0.47, yr: 0.56, xc: -0.255, side: -1 }, // 後：前面切在 x −0.255
];
function fender(F, x, y) {
  const dx = x - F.x, dy = y - 0.32, a = dx > 0 ? F.af : F.ar;
  const e = (Math.hypot(dx / a, dy / F.b) - 1) * Math.min(a, F.b); // 橢圓（大概的距離）
  const cut = F.side > 0 ? F.xc - x : x - F.xc; // 腳踏板那頭
  return Math.max(e, cut, (dx > 0 ? F.yf : F.yr) - y);
}

export function makeSDF() {
  const res = 0.004;
  const fs = sdf2d(curve(FRONT_SIDE), 0.1, 0.35, 1.15, 0.95, res);
  const rs = sdf2d(curve(REAR_SIDE), -1.15, 0.35, -0.1, 0.95, res);
  const cs = sdf2d(curve(CENTER_SIDE), -0.6, 0.4, 0.6, 1.0, res);
  const { xf, xr } = Z2, AY = 0.32;
  return (x, y, z) => {
    const az = Math.abs(z);
    // 前面中間：|z| < 0.36（車頭收窄成 0.30）；後面中間：|z| < 0.38
    const wF = 0.36 - 0.06 * sstep(0.88, 1.01, x);
    const dF = smax(look(fs, x, y), az - wF, 0.05);
    const dR = smax(look(rs, x, y), az - 0.38, 0.05);
    // 中間：油箱蓋寬 0.23（膝蓋那裡 0.205），越上面越窄
    const wC = 0.205 + 0.025 * sstep(0.12, 0.24, x) - 0.035 * sstep(0.80, 0.90, y);
    const dC = smax(look(cs, x, y), az - wC, 0.04);
    let d = smin(smin(dF, dC, 0.04), dR, 0.04);
    // 葉子板：|z| 0.30～0.60，外面的邊圓圓的，裡面跟置物台接起來（斜坡）
    for (const F of Z2_FENDERS) d = smin(d, smax(smax(fender(F, x, y), az - 0.60, 0.07), 0.30 - az, 0.05), 0.03);
    // 輪拱：圓的，只挖 |z| 0.20 以外（中間留一條：車頭、車尾那塊）
    for (const [xa, ra] of [[xf, 0.40], [xr, 0.41]]) {
      const dc = Math.hypot(x - xa, y - AY) - ra;
      d = smax(d, -smax(dc, 0.20 - az, 0.02), 0.015);
    }
    // 凹槽（照表面往下挖固定的深度，只在車頭 x > 0.90／車尾 x < −0.93）：
    // 大燈＝葉子板前面斜的長條（外面高、裡面低）1.5 公分；水箱罩（車頭中間）2 公分；尾燈 1.2 公分
    const dl = smax(box2(az - 0.455, y - 0.635 - 0.22 * (az - 0.455), 0.086, 0.025, 0.012), 0.86 - x, 0.01);
    const dg = smax(box2(az, y - 0.605, 0.19, 0.06, 0.025), 0.90 - x, 0.01);
    const dt = smax(box2(az, y - 0.712, 0.14, 0.02, 0.012), x + 0.93, 0.01);
    const d0 = d;
    d = smax(d, -smax(dl, -(d0 + 0.015), 0.004), 0.004);
    d = smax(d, -smax(dg, -(d0 + 0.02), 0.004), 0.004);
    d = smax(d, -smax(dt, -(d0 + 0.012), 0.004), 0.004);
    return d;
  };
}
