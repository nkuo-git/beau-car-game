// 拱形（中線高 → 兩側低多少）
const CROWN = [[-2.4, 0.05], [-1.9, 0.06], [-1.0, 0.06], [0.6, 0.05], [1.0, 0.035], [1.6, 0.03], [2.4, 0.05]];
const CABIN_CROWN = 0.03;
function lerpTable(t, x) {
  if (x <= t[0][0]) return t[0][1];
  for (let i = 1; i < t.length; i++) if (x <= t[i][0]) { const a = t[i - 1], b = t[i], u = (x - a[0]) / (b[0] - a[0]), s = u * u * (3 - 2 * u); return a[1] + (b[1] - a[1]) * s; }
  return t[t.length - 1][1];
}
const sstep = (a, b, x) => { const t = Math.max(0, Math.min(1, (x - a) / (b - a))); return t * t * (3 - 2 * t); };
const gau = (a, m, s) => Math.exp(-(((a - m) / s) ** 2));
const box2 = (x, y, hx, hy, r) => { const qx = Math.abs(x) - hx + r, qy = Math.abs(y) - hy + r; return Math.hypot(Math.max(qx, 0), Math.max(qy, 0)) + Math.min(Math.max(qx, qy), 0) - r; };
const ell = (x, y, z, e) => {
  const dx = (x - e.x) / e.rx, dy = (y - e.y) / e.ry, dz = (z - e.z) / e.rz;
  return (Math.sqrt(dx * dx + dy * dy + dz * dz) - 1) * Math.min(e.rx, e.ry, e.rz);
};

export const NOSE_X = 1.5;
export function makeSDF(opt = {}) {
  const res = 0.005;
  const side = sdf2d(curve(LOWER_SIDE), -2.45, -0.05, 2.45, 1.25, res);
  const cabS = sdf2d(curve(CABIN_SIDE), -2.3, 0.7, 1.1, 1.55, res);
  const plan = sdf2d(curve(PLAN), -2.45, -1.1, 2.45, 1.1, res);
  const planU = sdf2d(curve(PLAN_UP), -2.45, -1.1, 2.45, 1.1, res);
  const planL = sdf2d(curve(PLAN_LO), -2.45, -1.1, 2.45, 1.1, res);
  const cabP = sdf2d(curve(CABIN_PLAN), -2.3, -1.0, 1.1, 1.0, res);
  const front = sdf2d(curve(FRONT), -1.1, -0.05, 1.1, 1.2, res);
  const R1 = opt.R1 ?? 0.08, R2 = opt.R2 ?? 0.07, RC = opt.RC ?? 0.075, RU = opt.RU ?? 0.05;
  const arch = { R: 0.385, zIn: 0.64 }, archR = { R: 0.385, zIn: 0.64 };
  // 前後葉子板外擴（FK8 的輪拱往外鼓，最寬 1.877）
  const fen = { x: CIVIC.xf - 0.02, y: 0.50, z: 0.56, rx: 0.66, ry: 0.36, rz: 0.37, k: 0.10 };
  const hau = { x: CIVIC.xr + 0.02, y: 0.52, z: 0.56, rx: 0.70, ry: 0.38, rz: 0.37, k: 0.12 };
  return function f(x, y, z) {
    const az = Math.abs(z);
    const zz = az / 0.9;
    // 引擎蓋：兩邊葉子板的稜線比中間高（FK8 的引擎蓋夾在兩道稜線中間）
    const hw = sstep(0.75, 1.0, x) * (1 - sstep(1.75, 2.1, x));
    const cr = lerpTable(CROWN, x) * zz * zz + hw * (-0.05 * gau(az, 0.80, 0.13) + 0.008 * gau(az, 0, 0.30));
    const dS = look(side, x, y + cr);
    const up = sstep(0.50, 0.70, y);
    // 車尾上半部往內收（尾燈在斜的「肩膀」上），照片 3、4 的輪廓量的
    const tp = sstep(-1.45, -2.0, x) * 0.7 * Math.pow(Math.max(0, y - 0.62), 1.5);
    const lo = x > 1.4 ? 1 - sstep(0.22, 0.34, y) : 0;
    let dP = look(plan, x, az + tp);
    if (up > 0) dP = dP * (1 - up) + look(planU, x, az + tp) * up;
    if (lo > 0) dP = dP * (1 - lo) + look(planL, x, az) * lo;
    const dF = look(front, az, y);
    const fr = sstep(1.35, 1.75, x); // 車頭的邊修得利一點（FK8 的保桿角、葉子板稜線是硬的）
    let d = smax(dS, dP, R1 * (1 - 0.45 * fr));
    d = smax(d, dF, R2 * (1 - 0.35 * fr));
    d = smin(d, smax(ell(x, y, az, fen), dS + 0.01, 0.06), fen.k);
    d = smin(d, smax(smax(ell(x, y, az, hau), dS + 0.01, 0.06), -2.10 - x, 0.10), hau.k);
    // 車艙
    const zc = az / 0.78;
    const cS = look(cabS, x, y + CABIN_CROWN * zc * zc);
    const cP = look(cabP, x, az + Math.max(0, y - CABIN_Y0) * TUMBLE);
    d = smin(d, smax(cS, cP, RC), RU);
    // 引擎蓋進氣口：後段隆起 3 公分（前面是直的開口，x 1.30），前面一塊往下凹的導流槽到 x 1.52
    if (x > 0.85 && x < 1.62 && az < 0.40) {
      const h = 0.03 * sstep(0.92, 1.14, x);
      const fp = box2(x - 1.125, az, 0.175, 0.215 + (x - 0.95) * 0.1, 0.03);
      d = smin(d, smax(dS - h, fp, 0.01), 0.008);
      const dep = 0.022 * sstep(1.53, 1.33, x);
      const tr = box2(x - 1.415, az, 0.115, 0.245 + (x - 1.30) * 0.15, 0.03);
      d = smax(d, -Math.max(tr, -dS - dep), 0.01);
    }
    // 前保桿兩邊的大進氣口（霧燈在裡面）、中間下面的進氣口：沿著保桿往裡凹
    if (x > 1.80) {
      for (const [z0, z1, y0, y1, dep] of [[0.475, 0.815, 0.385, 0.535, 0.025], [-0.30, 0.295, 0.26, 0.555, 0.018]]) {
        const win = box2(az - (z0 + z1) / 2, y - (y0 + y1) / 2, (z1 - z0) / 2, (y1 - y0) / 2, 0.02);
        d = smax(d, -Math.max(win, -(dP + dep)), 0.02);
      }
    }
    // 車身側面的腰線：從前葉子板後面一路往後往上到尾燈，線上面的面凸出 6 公釐（光影看得出一道折線）
    if (az > 0.6 && x > -2.0 && x < 1.25) {
      const yl = 0.80 + (1.25 - x) * 0.045 + Math.max(0, -1.0 - x) * 0.05;
      d -= 0.006 * sstep(-0.012, 0.012, y - yl) * sstep(1.25, 0.9, x) * sstep(-2.0, -1.75, x) * sstep(0.6, 0.8, az) * (1 - sstep(yl + 0.10, yl + 0.16, y));
    }
    // 側裙：車門下面黑色的一條，往外凸一點、下緣往外翻
    if (x > -1.0 && x < 0.92 && y < 0.34) {
      const sk = smax(smax(az - 0.915 + Math.max(0, 0.24 - y) * 0.3, Math.max(y - 0.30, 0.175 - y), 0.03), Math.max(-0.98 - x, x - 0.86), 0.06);
      d = smin(d, sk, 0.025);
    }
    // 輪拱：直接挖洞
    for (const [xa, A] of [[CIVIC.xr, archR], [CIVIC.xf, arch]]) {
      const dc = Math.hypot(x - xa, y - CIVIC.R) - A.R;
      d = smax(d, -smax(dc, A.zIn - az, 0.03), 0.025);
    }
    return d;
  };
}
