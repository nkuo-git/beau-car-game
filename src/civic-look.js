// 3D Civic Type R FK8 的表面細節（投影貼圖），做法跟 gtr-look.js、yaris-look.js 一樣。
// 位置都是照四張 FK8 照片量的：照片上的點從相機打光線到車身（civic3d/probe.mjs），得到車身上的 (x, y, z)。
// 沒有任何廠徽、字（照片上的 H 徽章、Type R 紅字、CIVIC 字都不畫，那裡留黑色或車漆）。
import { BOX, layers, poly, smooth, line, both, frit, canvas } from './masks.js';

export const CIVIC_LOOK = (() => {
  const M = (pts) => pts.map(([u, y]) => [-u, y]); // 左右鏡射
  const S = (pts, s) => pts.map(([u, y]) => [u * s, y]);
  const rrect = (g, x0, y0, x1, y1, r) => { g.beginPath(); g.roundRect(x0, y0, x1 - x0, y1 - y0, r); };
  const circle = (g, x, y, r) => { g.beginPath(); g.arc(x, y, r, 0, Math.PI * 2); };
  const both2 = (pts, fn) => { fn(pts); fn(M(pts)); };

  // ---- 側面（x, y）----
  // 側窗：前門窗＋後門窗＋後面往上翹的三角窗（一整塊，中間黑色的 B 柱、分隔條）
  const DLO = [[0.70, 0.952], [0.27, 0.957], [-0.32, 0.982], [-0.82, 1.037], [-1.26, 1.081], [-1.50, 1.11], [-1.53, 1.125], [-1.39, 1.19],
    [-1.22, 1.256], [-1.01, 1.323], [-0.79, 1.355], [-0.45, 1.377], [-0.12, 1.384], [0.20, 1.355], [0.40, 1.24], [0.59, 1.115], [0.67, 1.02]];
  const BPIL = [[-0.385, 1.40], [-0.31, 1.40], [-0.215, 0.96], [-0.29, 0.96]]; // B 柱（黑）
  const CDIV = [[-1.10, 1.33], [-1.06, 1.33], [-1.00, 1.04], [-1.04, 1.04]];  // 後門窗和三角窗中間的分隔條
  const SAIL = [[0.70, 0.952], [0.67, 1.02], [0.62, 1.085], [0.55, 1.05], [0.54, 0.955]]; // 後照鏡底座那塊黑三角
  const VENT = [[0.918, 0.835], [0.952, 0.835], [0.975, 0.585], [0.948, 0.585]];       // 前葉子板後面的直條通風口
  // 側裙（黑）：兩輪中間、門下面，前後兩端往上翹一點接到輪拱
  const SKIRT = [[0.93, 0.15], [0.93, 0.29], [0.86, 0.272], [0.40, 0.262], [-0.40, 0.262], [-0.90, 0.27], [-1.0, 0.29], [-1.0, 0.15]];
  function side() {
    return layers(BOX.side, [
      (g) => { smooth(g, DLO); g.fill(); },
      (g) => { // 黑色
        g.lineJoin = 'round'; g.lineWidth = 0.026; smooth(g, DLO); g.stroke(); // 窗框
        poly(g, BPIL); g.fill(); poly(g, CDIV); g.fill(); poly(g, SAIL); g.fill();
        poly(g, VENT); g.fill();
        poly(g, SKIRT); g.fill();
        poly(g, [[1.55, 0.13], [2.35, 0.13], [2.35, 0.215], [2.0, 0.23], [1.72, 0.23], [1.62, 0.21]]); g.fill(); // 前下巴包到側面
        poly(g, [[-1.70, 0.13], [-2.35, 0.13], [-2.35, 0.33], [-2.05, 0.31], [-1.82, 0.29], [-1.74, 0.25]]); g.fill(); // 後保桿下面的黑色擴散器包到側面
        poly(g, [[-2.012, 0.612], [-2.026, 0.612], [-2.046, 0.512], [-2.032, 0.512]]); g.fill(); // 後保桿轉角直的一條黑縫
      },
      (g) => { // 縫
        line(g, [[0.67, 1.0], [0.84, 0.92], [0.87, 0.80], [0.90, 0.55], [0.905, 0.34], [0.89, 0.30]], 0.005); // 前門前緣
        line(g, [[-0.30, 0.965], [-0.25, 0.75], [-0.18, 0.50], [-0.12, 0.29]], 0.005);                     // 前門後緣（B 柱）
        line(g, [[-1.27, 1.06], [-1.24, 0.90], [-1.12, 0.70], [-1.05, 0.58], [-0.99, 0.42], [-0.98, 0.30]], 0.005); // 後門後緣，沿著後輪拱
        line(g, [[-0.98, 0.295], [0.89, 0.295]], 0.004);                                                    // 車門下緣
        g.lineWidth = 0.004; rrect(g, -0.17, 0.835, -0.02, 0.868, 0.016); g.stroke(); rrect(g, -1.12, 0.91, -0.98, 0.943, 0.016); g.stroke(); // 門把
        line(g, [[-0.15, 0.83], [-0.04, 0.83]], 0.01); line(g, [[-1.10, 0.906], [-1.00, 0.906]], 0.01); // 門把下面的凹槽
        g.lineWidth = 0.004; rrect(g, -1.80, 0.80, -1.62, 0.93, 0.03); g.stroke(); // 油箱蓋
        line(g, [[1.45, 0.895], [1.20, 0.95], [0.98, 1.0], [0.90, 1.02]], 0.004);  // 引擎蓋和葉子板
        line(g, [[1.62, 0.80], [1.60, 0.60], [1.63, 0.42], [1.70, 0.25]], 0.004);  // 前保桿和葉子板
        line(g, [[-1.74, 0.84], [-1.83, 0.66], [-1.90, 0.48], [-1.86, 0.32]], 0.004); // 後保桿
        for (const k of [0.25, 0.5, 0.75]) line(g, [[0.918 + 0.03 * k, 0.835 - 0.25 * k], [0.952 + 0.023 * k, 0.835 - 0.25 * k]], 0.006); // 通風口的鰭片
      },
      null,
    ]);
  }

  // ---- 正面（u＝|z|，畫的時候左右鏡射；y）----
  // 大燈：細長的 LED 燈，往後掃到葉子板上（內側尖端 (0.49, 0.68)、外側尖端 (0.85, 0.775)）
  const HEAD = [[0.49, 0.675], [0.53, 0.72], [0.58, 0.748], [0.70, 0.758], [0.80, 0.768], [0.85, 0.776], [0.835, 0.745], [0.79, 0.722],
    [0.72, 0.698], [0.63, 0.676], [0.55, 0.664]];
  // 上面的黑色寬條（引擎蓋前緣下面一直接到兩邊大燈，大燈下面一道黑色往內往下掃）
  const BAND = [[0.0, 0.795], [0.30, 0.79], [0.46, 0.775], [0.60, 0.775], [0.75, 0.792], [0.88, 0.812], [0.88, 0.76], [0.80, 0.70],
    [0.70, 0.668], [0.60, 0.645], [0.52, 0.628], [0.45, 0.595], [0.40, 0.568], [0.0, 0.566]];
  const INTAKE = [[0.455, 0.555], [0.62, 0.562], [0.77, 0.56], [0.835, 0.55], [0.845, 0.46], [0.84, 0.375], [0.70, 0.362], [0.48, 0.362], [0.452, 0.40]];
  const LOWER = [[0.0, 0.57], [0.30, 0.57], [0.315, 0.52], [0.315, 0.30], [0.30, 0.245], [0.0, 0.24]]; // 中間下面的網子
  const LIP = [[0.0, 0.235], [0.42, 0.235], [0.70, 0.30], [0.86, 0.345], [0.92, 0.33], [0.92, 0.12], [0.0, 0.12]]; // 黑色下巴（含兩邊往上的導流片）
  const FOG = [0.725, 0.432, 0.04];
  function front() {
    const B = BAND.concat(M(BAND).slice(1, -1).reverse()), L = LOWER.concat(M(LOWER).slice(1, -1).reverse()), P = LIP.concat(M(LIP).slice(1, -1).reverse());
    return layers(BOX.front, [
      (g) => { // R：燈（鍍鉻／LED）、霧燈
        both2(HEAD, (H) => { smooth(g, H); g.fill(); });
        for (const s of [1, -1]) { circle(g, FOG[0] * s, FOG[1], FOG[2]); g.fill(); }
      },
      (g) => { // G：黑色
        poly(g, B); g.fill();
        both2(INTAKE, (H) => { smooth(g, H); g.fill(); });
        poly(g, L); g.fill();
        poly(g, P); g.fill();
        g.fillStyle = '#000'; // 進氣口外側四片車身色的直鰭片（挖掉黑色）
        for (const s of [1, -1]) for (let i = 0; i < 4; i++) { const y = 0.535 - i * 0.045; poly(g, S([[0.80, y], [0.845, y + 0.004], [0.845, y - 0.014], [0.80, y - 0.018]], s)); g.fill(); }
        g.fillStyle = '#fff';
        for (const s of [1, -1]) { g.lineWidth = 0.014; circle(g, FOG[0] * s, FOG[1], FOG[2] + 0.008); g.stroke(); }
      },
      null, // B：橘色方向燈（FK8 的在大燈裡，看不到）
      (g) => { // A：燈裡暗的地方＋網子
        for (const s of [1, -1]) {
          g.save(); smooth(g, S(HEAD, s)); g.clip();
          g.fillStyle = 'rgb(120,120,120)'; poly(g, S([[0.48, 0.66], [0.90, 0.72], [0.90, 0.735], [0.48, 0.69]], s)); g.fill(); // 燈殼下半暗一點，上面一條亮的 LED
          g.restore(); g.fillStyle = '#fff';
          circle(g, FOG[0] * s, FOG[1], FOG[2] * 0.55); g.fill();
        }
        const mesh = (clip, k = 0.026) => { // 蜂巢網（斜格子）
          g.save(); clip(); g.clip(); g.strokeStyle = 'rgba(255,255,255,0.6)';
          for (let a = -1.5; a < 1.5; a += k) { line(g, [[a, 0.1], [a + 0.6, 0.85]], 0.004); line(g, [[a, 0.85], [a + 0.6, 0.1]], 0.004); }
          g.restore();
        };
        mesh(() => poly(g, L));
        for (const s of [1, -1]) mesh(() => smooth(g, S(INTAKE, s)));
        mesh(() => { g.beginPath(); g.rect(-0.36, 0.60, 0.72, 0.07); }, 0.03); // 上面黑條下半的網子
        g.fillStyle = '#000'; for (const s of [1, -1]) { circle(g, FOG[0] * s, FOG[1], FOG[2] + 0.016); g.fill(); } g.fillStyle = '#fff';
        for (const s of [1, -1]) { circle(g, FOG[0] * s, FOG[1], FOG[2] * 0.55); g.fill(); }
      },
    ]);
  }

  // ---- 後面（u＝z，y）----
  // 尾燈：迴力鏢形狀，在車尾的「肩膀」上（照片 3、4 打到車身量的）：內上角 (0.55, 1.095)、外側包到側面 (0.84, 0.95)、內下尖端 (0.525, 0.775)
  // 紅色沿著上緣到外側再沿著下緣往內收到尖端（一個「C」），中間透明的倒車燈，外面一圈燻黑
  const LAMP = [[0.548, 1.10], [0.63, 1.10], [0.72, 1.058], [0.80, 1.005], [0.845, 0.96], [0.845, 0.90], [0.80, 0.872], [0.74, 0.838],
    [0.65, 0.807], [0.535, 0.768], [0.522, 0.79], [0.552, 0.98]];
  const CRED = [[0.565, 1.078], [0.63, 1.078], [0.715, 1.04], [0.79, 0.99], [0.825, 0.95], [0.82, 0.905], [0.78, 0.885], [0.73, 0.855], [0.645, 0.825], [0.545, 0.792]];
  const REV = [[0.63, 0.985], [0.69, 0.98], [0.715, 0.955], [0.70, 0.925], [0.64, 0.92], [0.615, 0.95]];
  const BAR = [[0.0, 1.17], [0.56, 1.17], [0.55, 1.072], [0.0, 1.068]]; // 尾門上黑色的橫條（後擋下緣）
  const VENTR = [[0.728, 0.692], [0.448, 0.672], [0.262, 0.485], [0.775, 0.487]]; // 後保桿兩邊的通風口（黑、蜂巢網）
  const DIFF = [[0.0, 0.51], [0.30, 0.51], [0.241, 0.487], [0.589, 0.412], [0.773, 0.433], [0.86, 0.40], [0.95, 0.30], [0.95, 0.10], [0.0, 0.10]]; // 中間的擴散器＋通風口下面那片白色刀片下緣以下
  const REFL = [[0.728, 0.655], [0.748, 0.655], [0.768, 0.50], [0.748, 0.50]]; // 通風口外側直的紅色反光片
  function rear() {
    const BB = BAR.concat(M(BAR).slice(1, -1).reverse()), D = DIFF.concat(M(DIFF).slice(1, -1).reverse());
    return layers(BOX.rear, [
      (g) => { // R：紅色 C、反光片
        for (const s of [1, -1]) { g.lineJoin = 'round'; line(g, S(CRED, s), 0.036); poly(g, S(REFL, s)); g.fill(); }
      },
      (g) => { // G：燻黑燈殼、黑橫條、車牌、通風口、擴散器
        both2(LAMP, (P) => { smooth(g, P); g.fill(); });
        poly(g, BB); g.fill();
        rrect(g, -0.16, 0.75, 0.16, 0.912, 0.012); g.fill(); // 車牌（空白）
        both2(VENTR, (P) => { poly(g, P); g.fill(); });
        poly(g, D); g.fill();
        g.strokeStyle = '#000'; g.fillStyle = '#000'; // 紅色的地方不要黑
        for (const s of [1, -1]) { line(g, S(CRED, s), 0.036); poly(g, S(REFL, s)); g.fill(); }
        g.strokeStyle = g.fillStyle = '#fff';
      },
      (g) => { for (const s of [1, -1]) { smooth(g, S(REV, s)); g.fill(); } }, // B：倒車燈（白）
      (g) => { // A：縫（尾門、保桿）＋通風口的網子
        line(g, [[-0.53, 1.06], [-0.50, 0.88], [-0.46, 0.73], [-0.30, 0.70], [0.30, 0.70], [0.46, 0.73], [0.50, 0.88], [0.53, 1.06]], 0.004); // 尾門下緣
        for (const s of [1, -1]) {
          g.save(); poly(g, S(VENTR, s)); g.clip();
          for (let a = -1.5; a < 1.5; a += 0.03) { line(g, [[a, 0.3], [a + 0.4, 0.75]], 0.0035); line(g, [[a, 0.75], [a + 0.4, 0.3]], 0.0035); }
          g.restore();
        }
      },
    ]);
  }

  // ---- 上面（x, z）：前擋、後擋（含黑邊）、雨刷飾板、引擎蓋進氣口外框、引擎蓋和尾門的縫 ----
  const WS = [[1.0, 0], [0.99, 0.30], [0.95, 0.52], [0.86, 0.66], [0.78, 0.715], [0.60, 0.70], [0.40, 0.66], [0.20, 0.615], [0.10, 0.58],
    [0.06, 0.45], [0.045, 0.25], [0.04, 0]];
  const BL = [[-1.66, 0], [-1.665, 0.30], [-1.69, 0.47], [-1.78, 0.53], [-1.95, 0.53], [-2.08, 0.50], [-2.09, 0.30], [-2.09, 0]];
  const COWL = [[1.07, 0], [1.065, 0.30], [1.03, 0.55], [0.94, 0.68], [0.88, 0.70], [0.90, 0.62], [0.96, 0.50], [0.99, 0.30], [1.0, 0]];
  const SCOOP = [[1.53, 0.0], [1.53, 0.21], [1.51, 0.245], [1.32, 0.24], [1.30, 0.22], [1.30, 0.0]];
  function top() {
    return layers(BOX.top, [
      null,
      (g) => {
        frit(g, both(WS), 0.03, [0.0, 0.13], [0.94, 1.02]);
        smooth(g, both(COWL)); g.fill();
        frit(g, both(BL), 0.03, [-1.72, -1.64], [-2.12, -2.04]);
        g.lineWidth = 0.012; g.lineJoin = 'round'; poly(g, both(SCOOP)); g.stroke(); // 引擎蓋導流槽的黑邊
      },
      (g) => {
        line(g, [[1.07, 0.71], [1.30, 0.80], [1.62, 0.83], [1.86, 0.74], [2.06, 0.55], [2.12, 0.30], [2.13, 0], [2.12, -0.30], [2.06, -0.55], [1.86, -0.74], [1.62, -0.83], [1.30, -0.80], [1.07, -0.71]], 0.005);
        line(g, [[-2.10, 0.55], [-2.12, 0], [-2.10, -0.55]], 0.004);
      },
      (g) => { smooth(g, both(WS)); g.fill(); poly(g, both(BL)); g.fill(); },
    ]);
  }

  // ---- 拉花：紅色細線（FK8 原廠下巴、側裙、後擴散器邊緣的紅線）----
  function livery(sd, style = 'redline') {
    const { c, g } = canvas(BOX.side);
    g.clearRect(-3, -1, 6, 3);
    if (style !== 'redline') return c;
    g.fillStyle = '#d0101c';
    poly(g, [[0.88, 0.168], [0.86, 0.185], [-0.92, 0.185], [-0.95, 0.168]]); g.fill(); // 側裙下緣
    poly(g, [[1.62, 0.15], [2.35, 0.15], [2.35, 0.165], [1.64, 0.165]]); g.fill(); // 前下巴側面
    poly(g, [[-1.76, 0.19], [-2.35, 0.21], [-2.35, 0.225], [-1.77, 0.205]]); g.fill(); // 後擴散器側面
    return c;
  }
  function frontLivery(style = 'redline') {
    const { c, g } = canvas(BOX.front);
    g.clearRect(-2, -1, 4, 3);
    if (style !== 'redline') return c;
    g.fillStyle = '#d0101c'; // 下巴前緣一條紅線，兩邊沿著導流片往上
    const R = [[0.0, 0.17], [0.40, 0.17], [0.70, 0.235], [0.88, 0.27], [0.92, 0.26], [0.92, 0.245], [0.88, 0.255], [0.70, 0.22], [0.40, 0.155], [0.0, 0.155]];
    poly(g, R.concat(M(R).slice(1, -1).reverse())); g.fill();
    return c;
  }

  return {
    side, rear, top,
    fronts: { base: front },
    livery, frontLivery,
    livDefault: 1,
    nose: () => 'base',
    // 輪拱內側變黑的半徑比挖洞的半徑大一點點
    U: { uXr: -1.41, uXf: 1.29, uFx: [1.60, 1.66], uRx: [-1.66, -1.72], uWell: [0.3275, 0.395, 0.90], uWellR: [0.3275, 0.395, 0.90], uGlassY: 0.98 },
  };
})();
